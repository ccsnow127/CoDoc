def _quoted(pattern: str) -> re.Pattern:
    """a diagnostic pattern written with '...' accepting ASCII, ‘...’ and `...' quotes."""
    parts = pattern.split("'")
    out = parts[0]
    for i, part in enumerate(parts[1:]):
        out += ("[‘'`]" if i % 2 == 0 else "[’']") + part
    return re.compile(out)


