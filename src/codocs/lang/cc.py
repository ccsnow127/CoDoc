# -- support files ------------------------------------------------------------------


def support_files() -> dict[str, str]:
    """name -> text of the embedded test support files (codocs_test.h, codocs_main.c/.cpp)."""
    return {name: (TOOLS_DIR / name).read_text(encoding="utf-8") for name in SUPPORT_FILES}


def write_support(dest: str | Path) -> Path:
    """write the support files into dest (OUT/work/tools/cc or OUT/tests/_support)."""
    d = Path(dest)
    d.mkdir(parents=True, exist_ok=True)
    for name, text in support_files().items():
        p = d / name
        try:
            if p.read_text(encoding="utf-8") == text:
                continue
        except OSError:
            pass
        tmp = p.with_name(f".{name}.tmp")
        tmp.write_text(text, encoding="utf-8")
        tmp.replace(p)
    return d


# -- small helpers --------------------------------------------------------------------


def _parent(rel: str) -> str:
    p = PurePosixPath(rel).parent.as_posix()
    return "" if p == "." else p


def _join(d: str, name: str) -> str:
    return f"{d}/{name}" if d else name


def _collapse(text: str) -> str:
    return " ".join(text.split())


def _stem_of(rel: str) -> str:
    name = PurePosixPath(rel).name
    dot = name.rfind(".")
    return name[:dot] if dot > 0 else name


def in_test_dir(d: str) -> bool:
    """whether a directory rel lies in a test directory (test, tests, ut, unittest)."""
    return any(part in TEST_DIRS for part in PurePosixPath(d).parts) if d else False


def _common(a: str, b: str) -> int:
    pa, pb = PurePosixPath(a).parts, PurePosixPath(b).parts
    n = 0
    for x, y in zip(pa, pb):
        if x != y:
            break
        n += 1
    return n


def nearest(rels: list[str], to: str) -> list[str]:
    """rels sorted nearest first by path distance to `to` (most common leading dirs, then lexical)."""
    base = _parent(to) if to else ""
    return sorted(rels, key=lambda r: (-_common(_parent(r), base), r))


def _child(node: Any, name: str) -> Any:
    return node.child_by_field_name(name)


def _inner(node: Any) -> Any:
    """the declarator inside a wrapper declarator (field `declarator`, else last named child)."""
    d = _child(node, "declarator")
    if d is not None:
        return d
    named = node.named_children
    return named[-1] if named else None


def _func_declarator(node: Any) -> Any:
    """the function_declarator of a definition's declarator (through pointers/references)."""
    n = node
    while n is not None:
        if n.type == "function_declarator":
            return n
        if n.type in _WRAPPERS:
            n = _inner(n)
            continue
        return None
    return None


def _is_prototype(node: Any) -> bool:
    """whether a declaration's declarator declares a function (not a function pointer)."""
    n = node
    while n is not None:
        if n.type == "function_declarator":
            inner = _child(n, "declarator")
            return inner is not None and inner.type in _NAME_TYPES
        if n.type in _WRAPPERS:
            n = _inner(n)
            continue
        return False
    return False


def _innermost(p: ts.Parsed, node: Any) -> str:
    """the declared name of a declarator (identifier, type name, qualified name)."""
    n = node
    for _ in range(64):
        if n is None:
            return ""
        if n.type in _NAME_TYPES or n.type == "primitive_type":
            if n.type == "qualified_identifier":
                return _qual_parts(p, n)[1]
            if n.type == "template_function":
                nm = _child(n, "name")
                return p.node_text(nm) if nm is not None else p.node_text(n)
            return p.node_text(n).strip()
        nxt = _child(n, "declarator")
        if nxt is None:
            kids = [c for c in n.named_children
                    if c.type not in ("parameter_list", "argument_list", "initializer_list")]
            nxt = kids[0] if kids else None
        n = nxt
    return ""


def _seg(p: ts.Parsed, node: Any) -> str:
    if node is None:
        return ""
    if node.type in ("template_type", "template_function"):
        nm = _child(node, "name")
        if nm is not None:
            return p.node_text(nm)
    return p.node_text(node).split("<", 1)[0].strip()


def _qual_parts(p: ts.Parsed, node: Any) -> tuple[list[str], str]:
    """(scope segments, name) of a qualified_identifier `a::B::m`."""
    scope: list[str] = []
    cur = node
    while cur is not None and cur.type == "qualified_identifier":
        s = _child(cur, "scope")
        if s is not None:
            scope.append(_seg(p, s))
        cur = _child(cur, "name")
    if cur is None:
        return scope, ""
    if cur.type == "template_function":
        return scope, _seg(p, cur)
    return scope, p.node_text(cur).strip()


def _storage(node: Any, p: ts.Parsed) -> set[str]:
    return {p.node_text(c) for c in node.children if c.type == "storage_class_specifier"}


def _doc_start(p: ts.Parsed, node: Any) -> int:
    """char offset of node including the comments right above it (each on its own line)."""
    start = p.start(node)
    row = node.start_point[0]
    prev = node.prev_sibling
    text = p.text
    while prev is not None and prev.type == "comment" and prev.end_point[0] >= row - 1:
        a = p.start(prev)
        ls = text.rfind("\n", 0, a) + 1
        if text[ls:a].strip():
            break
        start = a
        row = prev.start_point[0]
        prev = prev.prev_sibling
    return start


def _namespaces(p: ts.Parsed) -> set[str]:
    """namespace names a file declares, opens with `using namespace` or aliases."""
    out = {"std"}
    for n in ts.iter_types(p.root, ("namespace_definition", "namespace_alias_definition")):
        nm = _child(n, "name")
        if nm is not None:
            out.update(s for s in re.split(r"\s*::\s*", p.node_text(nm)) if s)
    for n in ts.iter_types(p.root, ("using_declaration",)):
        if any(c.type == "namespace" for c in n.children):
            last = n.named_children[-1] if n.named_children else None
            if last is not None:
                out.update(s for s in re.split(r"\s*::\s*", p.node_text(last)) if s)
    return out


_NS_DECL_RE = re.compile(r"\bnamespace\s+([A-Za-z_]\w*(?:\s*::\s*[A-Za-z_]\w*)*)\s*(?:\{|=)")


def namespaces_in(text: str) -> set[str]:
    """namespace names declared (or aliased) anywhere in a text, by a quick scan."""
    if "namespace" not in text:
        return set()
    out: set[str] = set()
    for m in _NS_DECL_RE.finditer(ts.mask_c_like(text)):
        out.update(s for s in re.split(r"\s*::\s*", m.group(1)) if s)
    return out


def preproc_spans(text: str) -> list[tuple[int, int]]:
    """char spans of preprocessor lines (with their backslash continuations)."""
    return [(m.start(), m.end()) for m in _PP_LINE_RE.finditer(text)]


# -- the per-file scan (declarations, prototypes, bodies) -----------------------------


@dataclass
class _Item:
    decl: Decl
    static: bool = False
    proto: bool = False
    node_start: int = 0
    body: tuple[int, int] | None = None
    text: str = ""
    ns: str = ""            # the enclosing namespace (`geo::detail`), "" at file scope


@lru_cache(maxsize=128)
def _scan(src: str, lang: str, extra_ns: frozenset[str] = frozenset()) -> tuple[_Item, ...]:
    """every declaration of a C/C++ file in source order (prototypes flagged proto).

    scope segments naming a namespace (declared in the file or in extra_ns, the repo's) are
    not part of a receiver: `int geo::Vec::dot()` is the method Vec.dot, `geo::detail::sq` the
    function sq.
    """
    p = ts.parse(src, lang)
    ns = (_namespaces(p) | extra_ns) if lang == "cpp" else {"std"}
    items: list[_Item] = []
    text = p.text
    ns_stack: list[str] = []

    def emit(kind: str, name: str, node: Any, sig: str, *, outer: Any = None, receiver: str = "",
             static: bool = False, proto: bool = False, body: Any = None,
             end_node: Any = None) -> None:
        if not name:
            return
        top = outer if outer is not None else node
        last = end_node if end_node is not None else top
        start = _doc_start(p, top)
        end = p.end(last)
        while end > start and text[end - 1] == "\n":
            end -= 1
        bspan = p.span(body) if body is not None else None
        d = Decl(kind=kind, name=name, receiver=receiver, start=start, end=end,
                 line=p.line(top), end_line=p.line_at(max(end - 1, start)), signature=sig)
        items.append(_Item(d, static=static, proto=proto, node_start=p.start(top), body=bspan,
                           text=text[start:end], ns="::".join(x for x in ns_stack if x)))

    def sig_upto(node: Any, outer: Any, stop: Any) -> str:
        a = p.start(outer if outer is not None else node)
        b = p.start(stop) if stop is not None else p.end(node)
        return _collapse(text[a:b])

    def function(node: Any, outer: Any = None, recv: str = "") -> None:
        fd = _func_declarator(_child(node, "declarator"))
        if fd is None:
            return
        nm = _child(fd, "declarator")
        if nm is None:
            return
        body = _child(node, "body")
        stop = next((c for c in node.children if c.type == "field_initializer_list"), None)
        sig = sig_upto(node, outer, stop if stop is not None else body)
        static = "static" in _storage(node, p)
        if nm.type == "qualified_identifier":
            scope, name = _qual_parts(p, nm)
            rparts = [s for s in scope if s and s not in ns]
            receiver = ".".join(([recv] if recv else []) + rparts)
        else:
            name = _innermost(p, nm)
            receiver = recv
        if receiver:
            emit("method", name, node, sig, outer=outer, receiver=receiver, body=body)
        else:
            emit("func", name, node, sig, outer=outer, static=static, body=body)

    def members(body: Any, recv: str) -> None:
        for c in body.named_children:
            t = c.type
            if t == "function_definition":
                function(c, None, recv)
            elif t == "template_declaration":
                for k in c.named_children:
                    if k.type == "function_definition":
                        function(k, c, recv)
            elif t in _SPECIFIERS:
                nested(c, recv)
            elif t == "field_declaration":
                ty = _child(c, "type")
                if ty is not None and ty.type in _SPECIFIERS:
                    nested(ty, recv)
            elif t.startswith("preproc_") and t not in ("preproc_def", "preproc_function_def",
                                                       "preproc_include", "preproc_call"):
                members(c, recv)

    def nested(spec: Any, recv: str) -> None:
        nm, body = _child(spec, "name"), _child(spec, "body")
        if nm is not None and body is not None and spec.type != "enum_specifier":
            members(body, f"{recv}.{_seg(p, nm)}")

    def specifier(node: Any, outer: Any = None, end_node: Any = None, recv_ok: bool = True
                  ) -> None:
        nm, body = _child(node, "name"), _child(node, "body")
        if nm is None or body is None:
            return
        name = _seg(p, nm)
        top = outer if outer is not None else node
        if end_node is None:
            nxt = top.next_sibling
            end_node = nxt if nxt is not None and nxt.type == ";" else None
        sig = _collapse(text[p.start(top):p.end(end_node or top)])
        emit("type", name, node, sig[:400], outer=outer, end_node=end_node)
        if recv_ok and node.type != "enum_specifier":
            members(body, name)

    def declaration(node: Any, outer: Any = None) -> None:
        st = _storage(node, p)
        if "extern" in st:
            return
        ty = _child(node, "type")
        if ty is not None and ty.type in _SPECIFIERS and _child(ty, "body") is not None:
            specifier(ty, outer if outer is not None else node, end_node=None)
        static = "static" in st
        full = _collapse(text[p.start(outer if outer is not None else node):p.end(node)])
        for dcl in node.children_by_field_name("declarator"):
            if _is_prototype(dcl):
                fd = _func_declarator(dcl)
                nmn = _child(fd, "declarator") if fd is not None else None
                if nmn is None:
                    continue
                if nmn.type == "qualified_identifier":
                    scope, name = _qual_parts(p, nmn)
                else:
                    name = _innermost(p, nmn)
                emit("func", name, node, full, outer=outer, static=static, proto=True)
                continue
            name = _innermost(p, dcl)
            sig = full if len(full) <= 200 else full.split("=", 1)[0].rstrip() + " = ...;"
            emit("var", name, node, sig, outer=outer, static=static)

    def typedef(node: Any, outer: Any = None) -> None:
        dcls = node.children_by_field_name("declarator")
        if not dcls:
            return
        name = _innermost(p, dcls[0])
        sig = _collapse(text[p.start(outer if outer is not None else node):p.end(node)])
        emit("type", name, node, sig[:400], outer=outer)
        ty = _child(node, "type")
        if ty is not None and ty.type in _SPECIFIERS and _child(ty, "body") is not None \
                and ty.type != "enum_specifier":
            members(_child(ty, "body"), name)

    def macro(node: Any) -> None:
        nm = _child(node, "name")
        if nm is None:
            return
        name = p.node_text(nm)
        par = node.parent
        if (node.type == "preproc_def" and _child(node, "value") is None and par is not None
                and par.type == "preproc_ifdef" and _child(par, "name") is not None
                and p.node_text(_child(par, "name")) == name):
            return          # include guard
        emit("const", name, node, _collapse(p.node_text(node))[:300])

    def visit(node: Any, outer: Any = None) -> None:
        t = node.type
        if t in _CONTAINERS:
            for c in node.named_children:
                visit(c)
        elif t == "namespace_definition":
            body = _child(node, "body")
            nm = _child(node, "name")
            seg = re.sub(r"\s+", "", p.node_text(nm)) if nm is not None else ""
            if body is not None:
                ns_stack.append(seg)
                try:
                    visit(body)
                finally:
                    ns_stack.pop()
        elif t == "template_declaration":
            for c in node.named_children:
                if c.type != "template_parameter_list":
                    visit(c, node)
        elif t == "function_definition":
            function(node, outer)
        elif t == "declaration":
            declaration(node, outer)
        elif t == "type_definition":
            typedef(node, outer)
        elif t in _SPECIFIERS:
            specifier(node, outer)
        elif t == "alias_declaration":
            nm = _child(node, "name")
            if nm is not None:
                emit("type", p.node_text(nm), node,
                     _collapse(p.node_text(outer if outer is not None else node)), outer=outer)
        elif t in ("preproc_def", "preproc_function_def"):
            macro(node)

    visit(p.root)
    items.sort(key=lambda it: (it.node_start, it.decl.start))
    return tuple(items)


def scan_decls(src: str, lang: str, *, prototypes: bool = False,
               namespaces: frozenset[str] | None = None) -> list[Decl]:
    """top-level declarations of a C/C++ file (optionally with function prototypes).

    namespaces: the repo's namespace names (default: only the file's own).
    """
    extra = frozenset() if namespaces is None else namespaces
    return [it.decl for it in _scan(src, lang, extra if lang == "cpp" else frozenset())
            if prototypes or not it.proto]


def defines_main(src: str, lang: str = "c") -> bool:
    if not _MAIN_HINT_RE.search(src):
        return False
    return any(it.decl.kind == "func" and it.decl.name in MAIN_NAMES and not it.proto
               for it in _scan(src, lang))


@lru_cache(maxsize=256)
def _calls(src: str, lang: str) -> frozenset[str]:
    """names called anywhere in the file (identifier callees)."""
    p = ts.parse(src, lang)
    out: set[str] = set()
    for n in ts.iter_types(p.root, ("call_expression",)):
        fn = _child(n, "function")
        if fn is None:
            continue
        if fn.type == "identifier":
            out.add(p.node_text(fn))
        elif fn.type == "qualified_identifier":
            out.add(_qual_parts(p, fn)[1])
    return frozenset(out)


def asn1c_skeleton(rel: str, src: str) -> bool:
    """an asn1c runtime skeleton (OCTET_STRING.c, per_decoder.c, ...): its name and an include
    of the asn1c runtime headers."""
    return bool(_ASN1C_SKELETON_RE.match(PurePosixPath(rel).name)) and \
        bool(_ASN1C_INCLUDE_RE.search(src[:8000]))


def handwritten_header(src: str) -> bool:
    """whether the leading comment block is clearly a person's (Doxygen tags, a copyright) and
    carries no generated marker: the directory rule never overrides such a file."""
    head = _leading_comments(src)
    return bool(head) and bool(_HANDWRITTEN_RE.search(head)) and not _GEN_RE.search(head)


def _leading_comments(src: str) -> str:
    """the leading run of comments (<= 60 lines)."""
    i, n = 0, len(src)
    parts: list[str] = []
    limit = 0
    for _ in range(200):
        while i < n and src[i] in " \t\r\n\f\v":
            i += 1
        if src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            j = n if j < 0 else j + 2
        else:
            break
        parts.append(src[i:j])
        i = j
        limit = src.count("\n", 0, i)
        if limit >= 60:
            break
    head = "\n".join(parts)
    return "\n".join(head.splitlines()[:60])


_DEFINE_RE = re.compile(r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*)", re.MULTILINE)
_PREPROC_IFS = frozenset({"preproc_if", "preproc_ifdef", "preproc_elif", "preproc_elifdef"})


def _branch_value(p: ts.Parsed, node: Any, macros: set[str] | None) -> bool | None:
    """the condition of an #if/#ifdef/#elif: True/False when statically known, else None."""
    if node.type in ("preproc_if", "preproc_elif"):
        cond = _child(node, "condition")
        text = _collapse(p.node_text(cond)) if cond is not None else ""
        return {"0": False, "1": True, "false": False, "true": True}.get(text)
    name = _child(node, "name")
    if name is None or macros is None:
        return None
    macro = p.node_text(name).strip()
    if macro.startswith("_") or macro in macros:
        return None         # reserved/predefined names and macros something defines
    neg = any(c.type in ("#ifndef", "#elifndef") for c in node.children)
    return neg      # never defined: #ifdef is false, #ifndef true


def _compiled_out(p: ts.Parsed, node: Any, macros: set[str] | None) -> bool:
    """whether node sits in a preprocessor branch that is statically never compiled."""
    child, cur = node, node.parent
    while cur is not None:
        if cur.type in _PREPROC_IFS:
            alt = _child(cur, "alternative")
            in_alt = alt is not None and alt.start_byte <= child.start_byte and \
                child.end_byte <= alt.end_byte
            val = _branch_value(p, cur, macros)
            if val is not None and val == in_alt:
                return True
        child, cur = cur, cur.parent
    return False


@lru_cache(maxsize=256)
def _used_names(src: str, lang: str) -> frozenset[str]:
    """type and namespace-qualified names a file uses (`geo::Vec a(1, 2)`, `Vec v;`)."""
    p = ts.parse(src, lang)
    out: set[str] = set()
    for n in ts.iter_types(p.root, ("type_identifier", "namespace_identifier"),
                           prune=("comment", "string_literal")):
        out.add(p.node_text(n))
    return frozenset(out)


def is_generated_text(src: str) -> bool:
    """the generated-file rule: a generated marker in the leading comment block (<= 60 lines)."""
    return bool(_GEN_RE.search(_leading_comments(src)))


def case_names(src: str) -> list[tuple[str, int]]:
    """(name, offset) of every CODOCS_TEST(name) case outside comments and strings."""
    masked = ts.mask_c_like(src)
    seen: set[str] = set()
    out = []
    for m in _CASE_RE.finditer(masked):
        if m.group(1) not in seen:
            seen.add(m.group(1))
            out.append((m.group(1), m.start(1)))
    return out


def _match_brace(masked: str, i: int) -> int:
    """offset after the `}` matching the first `{` at or after i (len if unbalanced)."""
    j = masked.find("{", i)
    if j < 0:
        return -1
    depth = 0
    for k in range(j, len(masked)):
        ch = masked[k]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return k + 1
    return len(masked)


def _cut_lines(src: str, spans: list[tuple[int, int]]) -> str:
    """remove spans widened to whole lines, collapsing the blank lines they leave."""
    if not spans:
        return src
    merged: list[list[int]] = []
    for a, b in sorted(spans):
        a = src.rfind("\n", 0, a) + 1
        nl = src.find("\n", b)
        b = len(src) if nl < 0 else nl + 1
        if merged and a <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    out = []
    pos = 0
    for a, b in merged:
        out.append(src[pos:a])
        pos = b
    out.append(src[pos:])
    text = "".join(out)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.lstrip("\n") if not src.startswith("\n") else text


# -- the adapter ------------------------------------------------------------------------


class CcAdapter(LangAdapterBase):
    """shared C / C++ adapter; CAdapter and CppAdapter fix the language."""

    name = "c"

    def __init__(self, ctx: RepoContext | None = None):
        super().__init__(ctx)
        self._units: dict[str, Unit] | None = None

    # -- caches on the context --------------------------------------------------------

    def _cache(self, *key: Any) -> Any:
        return self.ctx.cache.get(("cc",) + key) if self.ctx is not None else None

    def _store(self, value: Any, *key: Any) -> Any:
        if self.ctx is not None:
            self.ctx.cache[("cc",) + key] = value
        return value

    @property
    def suite_ext(self) -> str:
        return ".c" if self.name == "c" else ".cpp"

    def lang_of(self, rel: str) -> str:
        """c or cpp for a repo file (headers: header_language), else this adapter's language."""
        lang = source_language(rel)
        if lang in ("c", "cpp"):
            return lang
        if is_header(rel) and self.ctx is not None:
            got = file_language(self.ctx.root, rel, self.ctx.dirs.get(_parent(rel)))
            if got in ("c", "cpp"):
                return got
        return self.name

    def _exists(self, rel: str) -> bool:
        if self.ctx is None:
            return False
        return PurePosixPath(rel).name in self.ctx.dirs.get(_parent(rel), ())

    # -- files and parsing --------------------------------------------------------------

    def is_program(self, rel: str, src: str | None = None) -> bool:
        """an auto-detected existing test program (defines main; test name or test dir)."""
        if is_header(rel) or source_language(rel) not in ("c", "cpp"):
            return False
        stem_ok = bool(_TEST_STEM_RE.match(_stem_of(rel))) or in_test_dir(_parent(rel))
        if not stem_ok:
            return False
        if src is None:
            src = self.read(rel)
        return defines_main(src, self.lang_of(rel))

    def is_framework_test(self, rel: str, src: str | None = None) -> bool:
        """a test file of a C/C++ test framework without its own main (gtest's foo_test.cc,
        Catch2, Unity, CMocka, Check, doctest, Boost.Test): never library code or a target."""
        if is_header(rel) or source_language(rel) not in ("c", "cpp"):
            return False
        if not (_TEST_STEM_RE.match(_stem_of(rel)) or in_test_dir(_parent(rel))):
            return False
        if src is None:
            src = self.read(rel)
        if not (_FRAMEWORK_INCLUDE_RE.search(src) or _FRAMEWORK_MACRO_RE.search(src)):
            return False
        return not defines_main(src, self.lang_of(rel)) and not self.is_suite(rel, src)

    def is_suite(self, rel: str, src: str | None = None) -> bool:
        """a generated suite (`*_codocs_test.<ext>` or CODOCS_TEST cases)."""
        if is_header(rel):
            return False
        if _SUITE_NAME_RE.search(PurePosixPath(rel).name):
            return True
        if src is None:
            src = self.read(rel)
        return "CODOCS_TEST" in src and bool(case_names(src))

    def is_test_file(self, rel: str, src: str | None = None) -> bool:
        if is_header(rel):
            return False
        if src is None:
            src = self.read(rel)
        return self.is_suite(rel, src) or self.is_program(rel, src) or \
            self.is_framework_test(rel, src)

    def _gen_dir(self, d: str) -> bool:
        hit = self._cache("gendir", d)
        if hit is not None:
            return hit
        names = self.ctx.dirs.get(d, []) if self.ctx is not None else []
        srcs = [n for n in names if source_language(n) in ("c", "cpp")]
        pool = srcs or [n for n in names if is_header(n)]
        gen = sum(1 for n in pool if self._generated_file(_join(d, n),
                                                          self.ctx.read(_join(d, n))))
        return self._store(bool(pool) and 2 * gen >= len(pool), "gendir", d)

    @staticmethod
    def _generated_file(rel: str, src: str) -> bool:
        """the file rule: a generated marker, or an asn1c runtime skeleton."""
        return is_generated_text(src) or asn1c_skeleton(rel, src)

    def is_generated(self, src: str, rel: str = "") -> bool:
        if self.include_generated:
            return False
        if self._generated_file(rel, src):
            return True
        if not rel or self.ctx is None or handwritten_header(src):
            return False        # a hand-written file next to generated ones stays
        return self._gen_dir(_parent(rel))

    def repo_namespaces(self) -> frozenset[str]:
        """namespace names declared anywhere in the repo's C/C++ files (cached; unbound: none,
        the docgen section check passes the run's bound adapter)."""
        if self.ctx is None:
            return frozenset()
        hit = self.ctx.cache.get(("cc", "namespaces"))
        if hit is not None:
            return hit
        out: set[str] = set()
        for lang in ("c", "cpp"):
            for rel in self.ctx.files.get(lang, []):
                if lang == "cpp" or is_header(rel):
                    out |= namespaces_in(self.ctx.read(rel))
        got = frozenset(out)
        self.ctx.cache[("cc", "namespaces")] = got
        return got

    def _items(self, src: str, lang: str) -> tuple[_Item, ...]:
        """_scan with the repo's namespaces (C++)."""
        return _scan(src, lang, self.repo_namespaces() if lang == "cpp" else frozenset())

    def _decls(self, src: str, lang: str, prototypes: bool = False) -> list[Decl]:
        return [it.decl for it in self._items(src, lang) if prototypes or not it.proto]

    def decls(self, src: str) -> list[Decl]:
        return self._decls(src, self.name)

    def imports(self, src: str) -> list[ImportSpec]:
        p = ts.parse(src, self.name)
        out: list[ImportSpec] = []
        for n in ts.iter_types(p.root, ("preproc_include",)):
            path = _child(n, "path")
            if path is None:
                continue
            raw = p.node_text(path).strip()
            if path.type == "system_lib_string":
                module, kind = raw[1:-1].strip(), "angle"
            elif path.type == "string_literal":
                module, kind = raw.strip('"'), "quote"
            else:
                continue
            text = p.node_text(n).strip().splitlines()[0].strip() if p.node_text(n).strip() \
                else ""
            out.append(ImportSpec(module=module, line=p.line(n), text=text, kind=kind))
        return sorted(out, key=lambda i: i.line)

    def format_import(self, imp: Any) -> str:
        module = getattr(imp, "module", str(imp))
        if getattr(imp, "kind", "") == "angle":
            return f"#include <{module}>"
        return f'#include "{module}"'

    def preamble(self, src: str) -> str:
        """the leading run of comments, blanks, #include/#pragma and include-only conditionals."""
        lines = src.splitlines(keepends=True)
        pos = 0
        end = 0                 # end of the last accepted directive line
        depth = 0
        open_at = 0             # offset of the outermost open conditional
        in_comment = False
        for line in lines:
            s = line.strip()
            nxt = pos + len(line)
            if in_comment:
                if "*/" in s:
                    in_comment = False
                    if s.split("*/", 1)[1].strip():
                        break
                pos = nxt
                continue
            if not s or s.startswith("//"):
                pos = nxt
                continue
            if s.startswith("/*"):
                if "*/" not in s[2:]:
                    in_comment = True
                elif s.split("*/", 1)[1].strip():
                    break
                pos = nxt
                continue
            m = re.match(r"#\s*(\w+)", s)
            if not m:
                break
            word = m.group(1)
            if word in ("include", "pragma", "import"):
                pos = nxt
                if depth == 0:
                    end = pos
                continue
            if word in ("if", "ifdef", "ifndef"):
                if depth == 0:
                    open_at = pos
                depth += 1
                pos = nxt
                continue
            if word in ("elif", "else") and depth:
                pos = nxt
                continue
            if word == "endif" and depth:
                depth -= 1
                pos = nxt
                if depth == 0:
                    end = pos
                continue
            break
        if depth:
            end = min(end, open_at) if end > open_at else end
        return src[:end]

    def apply_preamble(self, code: str, preamble: str) -> str:
        """prepend the original preamble, dropping the generated file's own leading includes.

        angle includes the generated file adds beyond the preamble are kept after it.
        """
        if not preamble.strip():
            return code
        own = self.preamble(code)
        rest = code[len(own):].lstrip("\n")
        have = {(m.group(1), m.group(2).strip()) for m in _INCLUDE_LINE_RE.finditer(preamble)}
        extra = []
        for m in _INCLUDE_LINE_RE.finditer(own):
            key = (m.group(1), m.group(2).strip())
            if m.group(1) == "<" and key not in have:
                have.add(key)
                extra.append(f"#include <{key[1]}>\n")
        head = preamble.rstrip("\n") + "\n"
        if extra:
            head += "".join(extra)
        return head + "\n" + rest

    # -- tests in source -----------------------------------------------------------------

    def test_names(self, src: str, rel: str) -> list[str]:
        cases = case_names(src)
        if cases:
            return [f"{rel}::{name}" for name, _ in cases]
        if defines_main(src, self.lang_of(rel)):
            return [rel]
        return []

    def test_lines(self, src: str, rel: str) -> dict[str, int]:
        cases = case_names(src)
        if cases:
            return {f"{rel}::{name}": src.count("\n", 0, off) + 1 for name, off in cases}
        for d in self._decls(src, self.lang_of(rel)):
            if d.kind == "func" and d.name in MAIN_NAMES:
                return {rel: d.line}
        return {}

    def remove_tests(self, src: str, names: set[str]) -> str:
        bare = {n.rsplit("::", 1)[-1] for n in names}
        masked = ts.mask_c_like(src)
        spans = []
        for m in _CASE_RE.finditer(masked):
            if m.group(1) not in bare:
                continue
            end = _match_brace(masked, m.end())
            if end < 0:
                continue
            spans.append((m.start(), end))
        return _cut_lines(src, spans)

    def strip_non_tests(self, src: str) -> str:
        """drop any main definition (the runner provides main)."""
        spans = [(d.start, d.end) for d in self._decls(src, self.name)
                 if d.kind == "func" and d.name in MAIN_NAMES]
        return _cut_lines(src, spans) if spans else src

    def normalize_suite(self, src: str, unit: Any, target_rel: str) -> str:
        """make the first two non-comment lines `#include "codocs_test.h"` / CODOCS_TARGET."""
        base = PurePosixPath(target_rel).name if target_rel else ""
        drop = re.compile(
            r'^[ \t]*#[ \t]*include[ \t]*(?:"codocs_test\.h"|<codocs_test\.h>|CODOCS_TARGET\b'
            + (r'|"(?:[^"]*/)?' + re.escape(base) + '"' if base else "") + r")[^\n]*\n?",
            re.MULTILINE)
        body = drop.sub("", src)
        lines = body.splitlines(keepends=True)
        i, in_comment = 0, False
        while i < len(lines):
            s = lines[i].strip()
            if in_comment:
                in_comment = "*/" not in s
                i += 1
                continue
            if s.startswith("//") or not s:
                i += 1
                continue
            if s.startswith("/*"):
                in_comment = "*/" not in s[2:]
                i += 1
                continue
            break
        head = "".join(lines[:i]).rstrip()
        head = head + "\n" if head else ""
        rest = "".join(lines[i:]).lstrip("\n")
        return head + '#include "codocs_test.h"\n#include CODOCS_TARGET\n\n' + rest

    def _string_names(self, p: ts.Parsed) -> set[str]:
        names: set[str] = set()
        for n in ts.iter_types(p.root, ("declaration", "parameter_declaration",
                                         "field_declaration", "optional_parameter_declaration")):
            ty = _child(n, "type")
            if ty is None or not _STRING_TYPE_RE.search(p.node_text(ty)):
                continue
            for dcl in n.children_by_field_name("declarator"):
                nm = _innermost(p, dcl)
                if nm:
                    names.add(nm)
        return names

    def _stringy(self, p: ts.Parsed, node: Any, strings: set[str]) -> bool:
        if node is None:
            return False
        if node.type in _STRING_NODES:
            return True
        if node.type == "identifier":
            return p.node_text(node) in strings
        if node.type == "field_expression":
            f = _child(node, "field")
            return f is not None and p.node_text(f) in strings
        if node.type == "binary_expression":
            return any(self._stringy(p, _child(node, k), strings) for k in ("left", "right"))
        if node.type in ("call_expression",):
            fn = _child(node, "function")
            return fn is not None and bool(_STRING_TYPE_RE.search(p.node_text(fn)))
        return False

    def mutation_sites(self, src: str) -> list[Mutant]:
        """Go's operator set inside function bodies; never preprocessor lines, array sizes, ERROR."""
        p = ts.parse(src, self.name)
        pre = preproc_spans(p.text)
        err = ts.error_spans(p)
        strings = self._string_names(p) if self.name == "cpp" else set()
        out: dict[int, Mutant] = {}
        kinds = ("binary_expression", "update_expression", "assignment_expression", "true",
                 "false")
        macros = self._repo_macros()
        for fn in ts.iter_types(p.root, ("function_definition",)):
            if _func_declarator(_child(fn, "declarator")) is None:
                continue
            if _compiled_out(p, fn, macros):
                continue        # under #if 0 / an #ifdef nothing defines: mutants never build
            body = _child(fn, "body")
            if body is None:
                continue
            for n in ts.iter_types(body, kinds, prune=("array_declarator", "preproc_def",
                                                       "preproc_function_def", "preproc_call",
                                                       "preproc_if", "preproc_ifdef",
                                                       "template_argument_list",
                                                       "static_assert_declaration")):
                tok = None
                if n.type in ("true", "false"):
                    tok, cat, repl = n, "bool", _BOOLS[n.type]
                elif n.type == "binary_expression":
                    op = _child(n, "operator")
                    if op is None:
                        continue
                    t = op.type
                    if t in _SWAPS:
                        cat, repl = _SWAPS[t]
                    elif t in _ARITH:
                        cat, repl = "arith", _ARITH[t]
                        if t == "+" and self.name == "cpp" and (
                                self._stringy(p, _child(n, "left"), strings)
                                or self._stringy(p, _child(n, "right"), strings)):
                            continue
                    else:
                        continue
                    tok = op
                elif n.type == "update_expression":
                    op = next((c for c in n.children if c.type in _INCDEC), None)
                    if op is None:
                        continue
                    tok, cat, repl = op, "incdec", _INCDEC[op.type]
                elif n.type == "assignment_expression":
                    op = _child(n, "operator")
                    if op is None or op.type not in _ASSIGN:
                        continue
                    if op.type == "+=" and self.name == "cpp" and (
                            self._stringy(p, _child(n, "left"), strings)
                            or self._stringy(p, _child(n, "right"), strings)):
                        continue
                    tok, cat, repl = op, "assign", _ASSIGN[op.type]
                if tok is None:
                    continue
                off = p.start(tok)
                original = p.node_text(tok)
                if original not in (_SWAPS.keys() | _ARITH.keys() | _ASSIGN.keys()
                                    | _INCDEC.keys() | _BOOLS.keys()):
                    continue
                if ts.in_spans(off, pre) or ts.in_spans(off, err) or off in out:
                    continue
                out[off] = Mutant(id=f"m{off}", offset=off, line=p.line_at(off),
                                  operator=f"{cat}: {original} -> {repl}", original=original,
                                  replacement=repl)
        return [out[k] for k in sorted(out)]

    def _repo_macros(self) -> set[str] | None:
        """every macro some repo C/C++ file #defines or a compile command passes with -D (None
        unbound: then only literal `#if 0` / `#if 1` decide)."""
        if self.ctx is None:
            return None
        hit = self.ctx.cache.get(("cc", "macros"))
        if hit is not None:
            return hit
        out: set[str] = set()
        for lang in ("c", "cpp"):
            for rel in self.ctx.files.get(lang, []):
                out.update(_DEFINE_RE.findall(self.ctx.read(rel)))
        for flags in self.compile_db().values():
            for f in flags:
                if f.startswith("-D") and len(f) > 2:
                    out.add(f[2:].split("=", 1)[0])
        for flag in shlex.split(str(self.ctx.setting("cc_flags", "") or "")):
            if flag.startswith("-D") and len(flag) > 2:
                out.add(flag[2:].split("=", 1)[0])
        self.ctx.cache[("cc", "macros")] = out
        return out

    # -- units and targets ----------------------------------------------------------------

    def symbols(self) -> dict[str, list[str]]:
        """non-static C/C++ function/data name -> defining source rels (no tests, no headers).

        C++ methods are indexed as `Cls::m` too. shared by the C and C++ adapters of a run.
        """
        hit = self.ctx.cache.get(("cc", "symbols")) if self.ctx is not None else None
        if hit is not None:
            return hit
        index: dict[str, list[str]] = {}
        if self.ctx is None:
            return index
        rels = sorted({r for lang in ("c", "cpp") for r in self.ctx.files.get(lang, [])
                       if not is_header(r)})
        for rel in rels:
            src = self.ctx.read(rel)
            if not src or self.is_test_file(rel, src):
                continue
            lang = self.lang_of(rel)
            try:
                items = self._items(src, lang)
            except ts.MissingDependency:
                raise
            except Exception:       # noqa: BLE001 - a file tree-sitter cannot handle
                continue
            for it in items:
                d = it.decl
                if it.proto or it.static or d.kind not in ("func", "method", "var"):
                    continue
                if d.name in MAIN_NAMES:
                    continue
                keys = [d.name]
                if d.kind == "method":
                    keys = [f"{d.receiver.replace('.', '::')}::{d.name}"]
                for k in keys:
                    lst = index.setdefault(k, [])
                    if rel not in lst:
                        lst.append(rel)
        self.ctx.cache[("cc", "symbols")] = index
        for k, v in index.items():
            self.ctx.symbol_index.setdefault(k, list(v))
        return index

    def _build_units(self) -> dict[str, Unit]:
        if self._units is not None:
            return self._units
        if self.ctx is None:
            raise RuntimeError("the C/C++ adapter needs a RepoContext for discovery")
        by_dir: dict[str, list[str]] = {}
        for rel in self.ctx.lang_files(self.name):
            by_dir.setdefault(_parent(rel), []).append(rel)
        units: dict[str, Unit] = {}
        programs: list[str] = []
        for d in sorted(by_dir):
            rels = sorted(by_dir[d])
            sources = [r for r in rels if not is_header(r)]
            progs = [r for r in sources if self.is_program(r)]
            suites = [r for r in sources if r not in progs and self.is_suite(r)]
            fw = [r for r in sources if r not in progs and r not in suites
                  and self.is_framework_test(r)]
            programs.extend(progs)
            plain = [r for r in sources if r not in progs and r not in suites and r not in fw]
            if not plain:
                continue
            headers = [r for r in rels if is_header(r)]
            mains = [r for r in plain if defines_main(self.read(r), self.name)]
            name = PurePosixPath(d).name if d else self.ctx.root.name
            units[d] = Unit(lang=self.name, rel=d, name=name, files=sorted(plain + headers),
                            test_files=[], build_root=d,
                            extra={"main_files": mains, "test_dir": in_test_dir(d)})
            if fw:
                units[d].extra["framework_tests"] = fw
        # test programs of the other C-family language can test this one's units (a .cpp
        # program for a C library through an extern "C" header, and the reverse)
        other = "cpp" if self.name == "c" else "c"
        programs += [r for r in self.ctx.lang_files(other)
                     if not is_header(r) and self.is_program(r)]
        index = self.symbols() if programs else {}
        types = self._type_index(index) if programs else {}
        owner: dict[str, set[str]] = {}
        for prog in programs:
            d = _parent(prog)
            homes: set[str] = set()
            if d in units and not in_test_dir(d) and source_language(prog) == self.name:
                homes.add(d)
            psrc = self.read(prog)
            plang = self.lang_of(prog)
            hits = [r for name in _calls(psrc, plang) for r in index.get(name, [])]
            # C++ classes tested through methods, constructors and operators only
            hits += [r for name in _used_names(psrc, plang) & set(types) for r in types[name]]
            for rel in hits:
                u = _parent(rel)
                if u in units and not in_test_dir(u) and rel in units[u].files:
                    homes.add(u)
            owner[prog] = homes
            for u in homes:
                units[u].test_files.append(prog)
        for u in units.values():
            u.test_files = sorted(set(u.test_files))
            u.extra["test_programs"] = list(u.test_files)
            u.extra.update(self._unit_flags_extra(u))
        self._units = units
        return units

    @staticmethod
    def _type_index(index: dict[str, list[str]]) -> dict[str, list[str]]:
        """C++ class name -> sources defining its methods (from the `Cls::m` symbol keys)."""
        out: dict[str, list[str]] = {}
        for key, rels in index.items():
            parts = key.split("::")
            if len(parts) < 2:
                continue
            for rel in rels:
                lst = out.setdefault(parts[-2], [])
                if rel not in lst:
                    lst.append(rel)
        return out

    def units(self, subtree: str | None = None, packages: list[str] | None = None
              ) -> dict[str, Unit]:
        """the language's units (cached), optionally under a subtree / package prefixes."""
        out = dict(self._build_units())
        sub = _norm(subtree)
        if sub:
            out = {k: v for k, v in out.items() if k == sub or k.startswith(sub + "/")}
        if packages:
            wanted = [_norm(p) for p in packages]
            out = {k: v for k, v in out.items()
                   if any(k == p or not p or k.startswith(p + "/") for p in wanted)}
        return dict(sorted(out.items()))

    def unit(self, rel: str) -> Unit:
        """the unit of a directory (KeyError when the directory is no unit)."""
        return self._build_units()[_norm(rel)]

    async def discover(self, runner: Any, subtree: str | None = None,
                       packages: list[str] | None = None) -> dict[str, Unit]:
        return self.units(subtree, packages)

    def file_status(self, rel: str, unit: Any) -> str | None:
        if is_header(rel):
            return "header"
        if in_test_dir(_parent(rel)):
            return "test-support"
        return None

    # -- flags and include paths ----------------------------------------------------------

    def compile_db(self) -> dict[str, list[str]]:
        """repo rel -> kept flags from compile_commands.json (absolute repo paths)."""
        hit = self._cache("db")
        if hit is not None:
            return hit
        out: dict[str, list[str]] = {}
        if self.ctx is None:
            return out
        root = self.ctx.root
        cands = []
        configured = self.ctx.setting("cc_db", "") or ""
        if configured:
            cands.append(Path(configured).expanduser())
        cands += [root / "compile_commands.json", root / "build" / "compile_commands.json"]
        for path in cands:
            p = path if path.is_absolute() else root / path
            try:
                entries = json.loads(p.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if not isinstance(entries, list):
                continue
            for e in entries:
                if not isinstance(e, dict) or "file" not in e:
                    continue
                cwd = Path(e.get("directory") or p.parent)
                f = Path(e["file"])
                f = (f if f.is_absolute() else cwd / f).resolve()
                try:
                    rel = f.relative_to(root).as_posix()
                except ValueError:
                    continue
                args = e.get("arguments") or shlex.split(e.get("command") or "")
                out.setdefault(rel, _keep_flags(args, cwd))
            break
        return self._store(out, "db")

    def cgo_include_dirs(self, d: str) -> list[str]:
        """-I dirs (rels) of `#cgo CFLAGS:` lines of the Go files in directory d."""
        if self.ctx is None:
            return []
        if d in self.ctx.cgo_flags and "include_dirs" in self.ctx.cgo_flags[d]:
            return list(self.ctx.cgo_flags[d]["include_dirs"])
        dirs: list[str] = []
        cflags: list[str] = []
        for name in self.ctx.dirs.get(d, []):
            if not name.endswith(".go") or name.endswith("_test.go"):
                continue
            src = self.ctx.read(_join(d, name))
            if 'import "C"' not in src:
                continue
            for m in _CGO_RE.finditer(src):
                try:
                    args = shlex.split(m.group(2))
                except ValueError:
                    args = m.group(2).split()
                cflags.extend(args)
                it = iter(args)
                for a in it:
                    path = a[2:] if a.startswith("-I") and len(a) > 2 else (
                        next(it, "") if a == "-I" else "")
                    if not path:
                        continue
                    path = path.replace("${SRCDIR}", str(self.ctx.root / d) if d
                                        else str(self.ctx.root))
                    rel = _rel_of(self.ctx.root, d, path)
                    if rel is not None and rel not in dirs:
                        dirs.append(rel)
        self.ctx.cgo_flags.setdefault(d, {}).update({"CFLAGS": cflags, "include_dirs": dirs})
        return dirs

    def _base_include_dirs(self, d: str) -> list[str]:
        out = [d, ""] + self.cgo_include_dirs(d)
        anc = d
        chain = []
        while True:
            chain.append(anc)
            if not anc:
                break
            anc = _parent(anc)
        for a in chain:
            for nm in INCLUDE_DIR_NAMES:
                cand = _join(a, nm)
                if self.ctx is not None and cand in self.ctx.dirs:
                    out.append(cand)
        seen: list[str] = []
        for x in out:
            if x not in seen:
                seen.append(x)
        return seen

    def _resolve_in(self, includer: str, header: str, dirs: list[str], quote: bool) -> str | None:
        if quote:
            cand = posixpath.normpath(_join(_parent(includer), header))
            if not cand.startswith("..") and self._exists(cand):
                return cand
        for inc in dirs:
            cand = posixpath.normpath(_join(inc, header))
            if not cand.startswith("..") and self._exists(cand):
                return cand
        return None

    def _suffix_match(self, header: str, includer: str) -> str | None:
        if self.ctx is None:
            return None
        base = PurePosixPath(header).name
        rels = self.ctx.header_index.get(base, [])
        if not rels:
            rels = [_join(dd, base) for dd, names in self.ctx.dirs.items() if base in names
                    and is_header(base)]
        hits = [r for r in rels if r == header or r.endswith("/" + header)]
        if not hits:
            return None
        return nearest(hits, includer)[0]

    def include_dirs(self, d: str) -> list[str]:
        """include search dirs (rels) of a directory: include heuristics, cached."""
        hit = self._cache("incdirs", d)
        if hit is not None:
            return hit
        dirs = self._base_include_dirs(d)
        if self.ctx is not None:
            names = self.ctx.dirs.get(d, [])
            queue = [_join(d, n) for n in names
                     if source_language(n) in ("c", "cpp") or is_header(n)]
            seen = set(queue)
            # the unit's files, then (transitively) the repo headers they include: a header's
            # own #include "x.h" needs its directory on the path as well
            while queue and len(seen) <= MAX_INCLUDE_SCAN:
                rel = queue.pop(0)
                for m in _INCLUDE_LINE_RE.finditer(self.ctx.read(rel)):
                    quote, header = m.group(1) == '"', m.group(2).strip()
                    if not quote and header in STD_C_HEADER_NAMES:
                        continue
                    found = self._resolve_in(rel, header, dirs, quote)
                    if found is None:
                        found = self._suffix_match(header, rel)
                        if found is None:
                            continue
                        inc = found[: len(found) - len(header)].rstrip("/")
                        if inc not in dirs:
                            dirs.append(inc)
                    if found not in seen and is_header(found):
                        seen.add(found)
                        queue.append(found)
        return self._store(dirs, "incdirs", d)

    def resolve_include(self, rel: str, header: str, ctx: RepoContext | None = None
                        ) -> str | None:
        """the repo header a `#include` of rel names (relative, -I dirs, nearest suffix match)."""
        quote = True
        h = header.strip()
        if h.startswith("<") and h.endswith(">"):
            quote, h = False, h[1:-1].strip()
        elif h.startswith('"') and h.endswith('"'):
            h = h[1:-1].strip()
        got = self._resolve_in(rel, h, self.include_dirs(_parent(rel)), quote)
        if got is not None:
            return got
        if not quote and h in STD_C_HEADER_NAMES:
            return None
        return self._suffix_match(h, rel)

    def resolve_imports(self, rel: str, imports: list, ctx: RepoContext | None = None
                        ) -> list[str]:
        """directories (rels) of the repo headers rel includes, its own directory excluded."""
        own = _parent(rel)
        out: list[str] = []
        for imp in imports:
            module = getattr(imp, "module", "")
            if not module:
                continue
            spec = f"<{module}>" if getattr(imp, "kind", "") == "angle" else module
            got = self.resolve_include(rel, spec, ctx)
            if got is None:
                continue
            d = _parent(got)
            if d != own and d not in out:
                out.append(d)
        return out

    def file_flags(self, rel: str) -> tuple[list[str], bool]:
        """(compile flags with absolute repo paths, from compile_commands.json) of a source."""
        db = self.compile_db()
        if rel in db:
            return list(db[rel]), True
        root = self.ctx.root if self.ctx is not None else Path(".")
        flags = [f"-I{(root / inc).as_posix() if inc else root.as_posix()}"
                 for inc in self.include_dirs(_parent(rel))]
        return flags, False

    def _unit_flags_extra(self, unit: Unit) -> dict:
        db = self.compile_db()
        defines: list[str] = []
        std = ""
        used_db = False
        for f in unit.files:
            if f in db:
                used_db = True
                for a in db[f]:
                    if a.startswith(("-D", "-U")) and a not in defines:
                        defines.append(a)
                    elif a.startswith("-std=") and not std:
                        std = a[5:]
        return {"include_dirs": self.include_dirs(unit.rel), "defines": defines, "std": std,
                "compile_db": used_db}

    # -- context for prompts ----------------------------------------------------------------

    def _included(self, rel: str, src: str, depth: int = 2) -> list[str]:
        """repo headers rel includes, then the headers they include (one transitive level)."""
        out: list[str] = []
        frontier = [(rel, src)]
        for _ in range(depth):
            nxt = []
            for f, text in frontier:
                for imp in self.imports(text) if f == rel else _quick_includes(text):
                    spec = f"<{imp.module}>" if imp.kind == "angle" else imp.module
                    h = self.resolve_include(f, spec)
                    if h and h not in out and h != rel:
                        out.append(h)
                        nxt.append((h, self.read(h)))
            frontier = nxt
        return out

    def _strip_bodies(self, src: str, lang: str, d: Decl) -> str:
        """a C++ class definition without method bodies (bodies become `;`)."""
        p = ts.parse(src, lang)
        cuts: list[tuple[int, int]] = []
        for fn in ts.iter_types(p.root, ("function_definition",)):
            a, b = p.span(fn)
            if a < d.start or b > d.end:
                continue
            body = _child(fn, "body")
            if body is None:
                continue
            start = p.start(body)
            init = next((c for c in fn.children if c.type == "field_initializer_list"), None)
            if init is not None:
                start = p.start(init)
            cuts.append((start, p.end(body)))
        text = src[d.start:d.end]
        for a, b in sorted(cuts, reverse=True):
            if any(x < a < y for x, y in cuts if (x, y) != (a, b)):
                continue
            text = text[: a - d.start].rstrip() + ";" + text[b - d.start:]
        return text

    def package_context(self, root: Path, unit: Any, target_rel: str,
                        max_chars: int = 12000) -> str:
        """declarations from included repo headers, then prototypes of unit functions it calls."""
        src = self.read(target_rel, root)
        used = self.identifiers(src) if src else set()
        own = {d.name for d in self.decls(src)} if src else set()
        blocks: list[tuple[str, list[tuple[bool, str]]]] = []
        declared: set[str] = set()
        for h in self._included(target_rel, src):
            hsrc = self.read(h, root)
            lang = self.lang_of(h)
            entries: list[tuple[bool, str]] = []
            for it in self._items(hsrc, lang):
                d = it.decl
                declared.add(d.name)
                text = it.text.strip()
                if lang == "cpp" and d.kind == "type":
                    text = self._strip_bodies(hsrc, lang, d).strip()
                elif d.kind == "method":
                    continue
                if it.ns:           # keep the declaration's namespace (geo::detail::sq)
                    text = f"namespace {it.ns} {{ {text} }}" if "\n" not in text else \
                        f"namespace {it.ns} {{\n{text}\n}}"
                entries.append((d.name in used or d.receiver in used, text))
            if entries:
                blocks.append((h, entries))
        protos: list[str] = []
        for f in self._other_files(unit, target_rel):
            if is_header(f) or self.is_test_file(f):
                continue
            for it in self._items(self.read(f, root), self.lang_of(f)):
                d = it.decl
                if (it.proto or it.static or d.kind != "func" or d.name in MAIN_NAMES
                        or d.name not in used or d.name in declared or d.name in own):
                    continue
                declared.add(d.name)
                protos.append(f"{d.signature};  /* {f} */")
        lines: list[str] = []
        size = 0
        full = False

        def add(chunk: str) -> bool:
            nonlocal size, full
            if full:
                return False
            if size + len(chunk) + 1 > max_chars:
                lines.append(TRUNCATED)
                full = True
                return False
            lines.append(chunk)
            size += len(chunk) + 1
            return True

        for wanted in (True, False):
            for h, entries in blocks:
                picked = [t for ref, t in entries if ref == wanted]
                if not picked:
                    continue
                if not add(f"// from {h}" + ("" if wanted else " (more)")):
                    break
                for t in picked:
                    if not add(t):
                        break
                add("")
        if protos and not full:
            add("// defined in other files of the unit (no included header declares them)")
            for t in protos:
                if not add(t):
                    break
        text = "\n".join(lines).strip()
        return text + "\n" if text else ""

    def package_identifiers(self, root: Path, unit: Any,
                            exclude_rel: str | None = None) -> set[str]:
        """non-static global names (functions and variables) of the unit's other sources."""
        names: set[str] = set()
        for f in self._other_files(unit, exclude_rel):
            if is_header(f):
                continue
            for it in self._items(self.read(f, root), self.lang_of(f)):
                d = it.decl
                if not it.proto and not it.static and d.kind in ("func", "var") \
                        and d.name not in MAIN_NAMES:
                    names.add(d.name)
        return names

    def _target_names(self, src: str) -> set[str]:
        out: set[str] = set()
        for d in self.decls(src):
            if d.name in MAIN_NAMES:
                continue
            out.add(d.name)
            if d.receiver:
                out.add(d.receiver.split(".")[-1])
        return out

    def _companions(self, target_rel: str) -> set[str]:
        stem = _stem_of(target_rel)
        return {f"test_{stem}", f"{stem}_test", f"{stem}_tests", f"{stem}_unittest", f"t_{stem}"}

    def test_reference(self, root: Path, unit: Any, target_rel: str,
                       max_chars: int = 8000) -> str:
        """existing test programs exercising the target: companion first, then by overlap."""
        src = self.read(target_rel, root)
        names = self._target_names(src)
        comp = self._companions(target_rel)
        scored = []
        for f in unit.test_files:
            tsrc = self.read(f, root)
            if not tsrc:
                continue
            overlap = len(names & self.identifiers(tsrc))
            is_comp = _stem_of(f) in comp
            if overlap or is_comp:
                scored.append((-(10 if is_comp else 0) - overlap, f, tsrc.strip()))
        scored.sort()
        out: list[str] = []
        size = 0
        for _, f, text in scored:
            chunk = f"// from {f} (an existing test program; not compiled with the suite)\n{text}\n"
            if size + len(chunk) > max_chars:
                if not out:
                    out.append(chunk[: max_chars - len(TRUNCATED) - 1] + "\n" + TRUNCATED)
                else:
                    out.append(TRUNCATED)
                break
            out.append(chunk)
            size += len(chunk)
        return "\n".join(out).strip() + "\n" if out else ""

    # -- tests of a unit --------------------------------------------------------------------

    def test_cmd_applies(self, unit: Any) -> bool:
        """whether --test-cmd replaces auto-detection for the unit (unit under --cc-root)."""
        if self.ctx is None or not (self.ctx.setting("test_cmd", "") or ""):
            return False
        root = _cc_root_rel(self.ctx)
        return root is not None and (not root or unit.rel == root
                                     or unit.rel.startswith(root + "/"))

    def test_index(self, root: Path, unit: Any) -> dict[str, dict]:
        out = super().test_index(root, unit)
        if self.test_cmd_applies(unit):
            out[CMD_TEST] = {"file": "", "idents": [], "selectors": []}
        return out

    def declared_tests(self, root: Path, unit: Any) -> set[str]:
        if self.test_cmd_applies(unit):
            return {CMD_TEST}
        return super().declared_tests(root, unit)

    def relevant_tests(self, root: Path, unit: Any, target_rel: str,
                       candidates: set[str]) -> list[str]:
        """test programs referencing a name the target declares, or companion programs."""
        names = self._target_names(self.read(target_rel, root))
        comp = self._companions(target_rel)
        out = []
        for name, info in self.test_index(root, unit).items():
            if name not in candidates:
                continue
            if name == CMD_TEST or (info["file"] and _stem_of(info["file"]) in comp) \
                    or names & set(info["idents"]):
                out.append(name)
        return sorted(out)

    # -- generated suite placement ------------------------------------------------------------

    def suite_basename(self, stem: str) -> str:
        return f"{_stem_of(stem)}_codocs_test{self.suite_ext}"

    def suite_rel(self, unit: Any, stem: str) -> str:
        rel = unit if isinstance(unit, str) else unit.rel
        return _join(_norm(rel), self.suite_basename(stem))

    def target_of_suite(self, unit: Any, suite_rel: str) -> str | None:
        """the unit source a suite `<stem>_codocs_test.<ext>` tests."""
        name = PurePosixPath(suite_rel).name
        stem = _SUITE_NAME_RE.sub("", name)
        if stem == name:
            return None
        cands = [f for f in unit.files if not is_header(f) and _stem_of(f) == stem]
        cands.sort(key=lambda f: (source_language(f) != self.name, f))
        return cands[0] if cands else None

    # -- repair and messages --------------------------------------------------------------------

    def _std(self) -> list[ImportSpec]:
        heads = C_STD_HEADERS if self.name == "c" else CPP_STD_HEADERS
        return [ImportSpec(module=h, kind="angle", text=f"#include <{h}>") for h in heads]

    def _std_names(self) -> dict[str, str]:
        table = _C_STD_NAMES if self.name == "c" else {**_C_STD_NAMES, **_CPP_STD_NAMES}
        out: dict[str, str] = {}
        for header, names in table.items():
            for n in names.split():
                out.setdefault(n, header)
        return out

    def _header_declares(self, header: str, name: str) -> bool:
        rel = self._suffix_match(header, "") if self.ctx is not None else None
        if rel is None:
            return False
        return any(d.name == name for d in self._decls(self.read(rel), self.lang_of(rel),
                                                      prototypes=True))

    def fix_imports(self, src: str, build_errors: list[str], file_basename: str,
                    allowed: list) -> str | None:
        """add `#include`s for undeclared names the compiler reports in that file."""
        missing: list[str] = []
        for line in build_errors:
            m = _ERR_RE.match(line.strip())
            if not m or PurePosixPath(m.group("path")).name != file_basename:
                continue
            for r in _MISSING_RES:
                u = r.search(m.group("msg"))
                if u and u.group(1) not in missing:
                    missing.append(u.group(1))
                    break
        if not missing:
            return None
        present = {(i.kind, i.module) for i in self.imports(src)}
        std = self._std_names()
        allowed_std = {getattr(i, "module", "") for i in allowed
                       if getattr(i, "kind", "") == "angle"}
        add: list[str] = []
        for name in missing:
            line = None
            for imp in allowed:
                if getattr(imp, "kind", "") != "quote":
                    continue
                if self._header_declares(imp.module, name):
                    if ("quote", imp.module) not in present:
                        line = f'#include "{imp.module}"'
                    break
            if line is None and name in std:
                h = std[name]
                if h in allowed_std or h in (C_STD_HEADERS + CPP_STD_HEADERS):
                    if ("angle", h) not in present:
                        line = f"#include <{h}>"
            if line and line not in add:
                add.append(line)
        if not add:
            return None
        return _insert_includes(src, add)

    def fix_allowed(self, source_imports: list) -> list:
        out = list(source_imports)
        have = {(getattr(i, "kind", ""), getattr(i, "module", "")) for i in out}
        out += [i for i in self._std() if (i.kind, i.module) not in have]
        return out

    def default_allowed(self, runner: Any, unit: Any) -> list:
        """the includes of the unit's files plus the standard headers."""
        out: list[ImportSpec] = []
        have: set[tuple[str, str]] = set()
        root = getattr(runner, "module_root", None)
        for f in unit.files:
            for imp in self.imports(self.read(f, root)):
                key = (imp.kind, imp.module)
                if key not in have:
                    have.add(key)
                    out.append(ImportSpec(module=imp.module, kind=imp.kind, text=imp.text))
        out += [i for i in self._std() if (i.kind, i.module) not in have]
        return out

    def failure_message(self, output: str) -> str:
        """the first failed check (or crash) line, then the output without protocol lines."""
        lines = [ln.rstrip() for ln in output.splitlines()
                 if ln.strip() and not ln.startswith("@@CODOCS RUN")]
        verdicts = [ln for ln in lines if ln.startswith("@@CODOCS FAIL")]
        body = [ln for ln in lines if not ln.startswith("@@CODOCS")]
        summary = ""
        if verdicts:
            parts = verdicts[0].split(" ", 3)
            summary = parts[3] if len(parts) > 3 else "test failed"
        elif body:
            summary = body[0].strip()
        text = "\n".join([summary] + [ln for ln in body if ln.strip() != summary]).strip()
        text = text or "test failed"
        return text if len(text) <= MESSAGE_CHARS else text[:MESSAGE_CHARS] + "\n..."

