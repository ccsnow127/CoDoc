    def make_runner(self, ctx: Any) -> Any:
        from codocs.lang.ccrun import CcRunner

        return CcRunner.from_context(self, ctx)

    # -- static facts ---------------------------------------------------------------------------

    def wiki_facts(self, root: Path, rel: str, src: str, ctx: RepoContext) -> WikiFileFacts:
        lang = self.lang_of(rel)
        decls = self._decls(src, lang)
        main = any(d.kind == "func" and d.name in MAIN_NAMES for d in decls)
        is_main = main and not self.is_test_file(rel, src)
        return WikiFileFacts(decls=decls, imports=self.imports(src), is_main=is_main,
                             doc_comment="", loc=ts.line_count(src))

    def graph_facts(self, root: Path, rel: str, src: str, ctx: RepoContext) -> GraphFileFacts:
        lang = self.lang_of(rel)
        p = ts.parse(src, lang)
        items = self._items(src, lang)
        base = PurePosixPath(rel).name
        facts = GraphFileFacts(imports=self.imports(src), is_test=self.is_test_file(rel, src))
        types: dict[str, TypeFact] = {}
        for it in items:
            d = it.decl
            if d.kind == "type" and d.name not in types:
                types[d.name] = TypeFact(line=d.line)
        self._type_details(p, types)
        bodies = {}
        for it in items:
            d = it.decl
            if it.proto or d.kind not in ("func", "method") or it.body is None:
                continue
            if d.kind == "method":
                name = f"{d.receiver}.{d.name}"
                cls = d.receiver
                tf = types.setdefault(d.receiver.split(".")[-1], TypeFact())
                if d.name not in tf.methods:
                    tf.methods.append(d.name)
            else:
                name = f"{d.name}@{base}" if it.static else d.name
                cls = ""
            if name not in bodies:
                # overloads (Vec::scale(int), Vec::scale(int, int)) are one function node
                facts.funcs.append(FuncFact(name=name, kind=d.kind, line=d.line,
                                            end_line=d.end_line, static=it.static, cls=cls,
                                            start=it.node_start, end=d.end))
            bodies.setdefault(name, []).append((it, cls))
        fn_nodes = {p.start(n): n for n in ts.iter_types(p.root, ("function_definition",))}
        for name, defs in bodies.items():
            calls, found = [], False
            for it, cls in defs:
                node = fn_nodes.get(it.node_start)
                if node is None:
                    node = next((n for s, n in fn_nodes.items()
                                 if it.node_start <= s < it.decl.end), None)
                if node is not None:
                    found = True
                    calls += self._body_calls(p, node, cls, types)
            if found:
                facts.calls[name] = calls
        for it in items:
            d = it.decl
            if d.kind != "var" or "=" not in it.text:
                continue
            node = _node_at(p, it.node_start, "declaration")
            if node is None:
                continue
            names = []
            for dcl in node.children_by_field_name("declarator"):
                if dcl.type != "init_declarator" or _innermost(p, dcl) != d.name:
                    continue
                val = _child(dcl, "value")
                if val is None:
                    continue
                for n in ts.iter_types(val, ("identifier",)):
                    t = p.node_text(n)
                    if t not in names:
                        names.append(t)
            if names:
                facts.tables[d.name] = names
        facts.types = types
        return facts

    def _type_details(self, p: ts.Parsed, types: dict[str, TypeFact]) -> None:
        for spec in ts.iter_types(p.root, tuple(_SPECIFIERS)):
            nm, body = _child(spec, "name"), _child(spec, "body")
            if nm is None or body is None:
                continue
            tf = types.get(_seg(p, nm))
            if tf is None:
                continue
            for c in spec.children:
                if c.type == "base_class_clause":
                    for b in c.named_children:
                        if b.type in ("type_identifier", "qualified_identifier",
                                      "template_type"):
                            tf.bases.append(_seg(p, b).split("::")[-1])
            pure = virtual = 0
            for f in body.named_children:
                if f.type == "field_declaration":
                    ty = _child(f, "type")
                    for dcl in f.children_by_field_name("declarator"):
                        if _is_prototype(dcl):
                            nmf = _innermost(p, dcl)
                            if nmf and nmf not in tf.methods:
                                tf.methods.append(nmf)
                            virtual += "virtual" in p.node_text(f)
                            pure += p.node_text(f).replace(" ", "").endswith("=0;")
                            continue
                        nmf = _innermost(p, dcl)
                        if nmf and ty is not None:
                            tf.fields[nmf] = _type_name(p.node_text(ty))
                elif f.type == "function_definition":
                    fd = _func_declarator(_child(f, "declarator"))
                    if fd is not None and _child(fd, "declarator") is not None:
                        nmf = _innermost(p, _child(fd, "declarator"))
                        if nmf and nmf not in tf.methods:
                            tf.methods.append(nmf)
            tf.is_interface = bool(pure) and pure == virtual

    def _locals(self, p: ts.Parsed, fn: Any) -> dict[str, str]:
        out: dict[str, str] = {}
        for n in ts.iter_types(fn, ("declaration", "parameter_declaration",
                                    "optional_parameter_declaration")):
            ty = _child(n, "type")
            if ty is None:
                continue
            tname = _type_name(p.node_text(ty))
            for dcl in n.children_by_field_name("declarator"):
                nm = _innermost(p, dcl)
                if nm:
                    out[nm] = tname
        return out

    def _body_calls(self, p: ts.Parsed, fn: Any, cls: str, types: dict[str, TypeFact]
                    ) -> list[CallFact]:
        body = _child(fn, "body")
        if body is None:
            return []
        local = self._locals(p, fn)
        fields = types.get(cls.split(".")[-1]).fields if cls and cls.split(".")[-1] in types \
            else {}
        out: list[CallFact] = []
        callees: set[int] = set()
        for n in ts.iter_types(body, ("call_expression",)):
            f = _child(n, "function")
            if f is None:
                continue
            line = p.line(n)
            if f.type == "identifier":
                callees.add(p.start(f))
                out.append(CallFact("call", "", p.node_text(f), None, line))
            elif f.type == "qualified_identifier":
                scope, name = _qual_parts(p, f)
                out.append(CallFact("call", scope[-1] if scope else "", name, None, line))
            elif f.type == "template_function":
                out.append(CallFact("call", "", _seg(p, f), None, line))
            elif f.type == "field_expression":
                arg, fld = _child(f, "argument"), _child(f, "field")
                if fld is None:
                    continue
                qual, recv = "", None
                if arg is not None:
                    if arg.type == "this":
                        qual, recv = "this", cls.split(".")[-1] if cls else None
                    elif arg.type == "identifier":
                        qual = p.node_text(arg)
                        recv = local.get(qual) or fields.get(qual)
                    elif arg.type == "field_expression" and _child(arg, "field") is not None:
                        qual = p.node_text(_child(arg, "field"))
                        recv = fields.get(qual)
                    else:
                        qual = _collapse(p.node_text(arg))[:60]
                out.append(CallFact("call", qual, p.node_text(fld), recv or None, line))
        for n in ts.iter_types(body, ("identifier",)):
            par = n.parent
            if par is None or par.type not in _REF_PARENTS or p.start(n) in callees:
                continue
            if par.type == "init_declarator" and _child(par, "value") != n:
                continue
            if par.type == "assignment_expression" and _child(par, "right") != n:
                continue
            name = p.node_text(n)
            if name in local:
                continue
            out.append(CallFact("ref", "", name, None, p.line(n)))
        return out


