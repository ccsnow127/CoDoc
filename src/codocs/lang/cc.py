def _type_name(text: str) -> str:
    """the bare class name of a declared type (`const geom::Vec2 &` -> `Vec2`)."""
    t = re.sub(r"<.*>", "", text)
    t = re.sub(r"\b(?:const|volatile|struct|class|union|enum|typename|static|mutable)\b", " ", t)
    t = t.replace("*", " ").replace("&", " ").strip()
    return t.split("::")[-1].strip().split()[-1] if t.split() else ""


def _node_at(p: ts.Parsed, offset: int, kind: str) -> Any:
    for n in ts.iter_types(p.root, (kind,)):
        if p.start(n) == offset:
            return n
    return None


def _rel_of(root: Path, d: str, path: str) -> str | None:
    """repo rel of a path (absolute or relative to dir d), None outside the repo."""
    p = Path(path)
    if not p.is_absolute():
        p = root / d / p
    try:
        rel = Path(posixpath.normpath(p.as_posix())).relative_to(root).as_posix()
    except ValueError:
        return None
    return "" if rel == "." else rel


def _cc_root_rel(ctx: RepoContext) -> str | None:
    raw = ctx.setting("cc_root", "") or ""
    if not raw:
        return ""
    p = Path(raw).expanduser()
    if not p.is_absolute():
        p = ctx.root / p
    try:
        rel = p.resolve().relative_to(ctx.root).as_posix()
    except ValueError:
        return None
    return "" if rel == "." else rel


def _keep_flags(args: list[str], cwd: Path) -> list[str]:
    """the -I -isystem -iquote -include -D -U -std= -f* -m* flags of a compile command."""
    out: list[str] = []
    it = iter(args[1:] if args else [])
    path_opts = ("-I", "-isystem", "-iquote", "-include")
    for a in it:
        opt = next((o for o in path_opts if a == o), None)
        if opt is not None:
            val = next(it, "")
            if val:
                pth = Path(val)
                out += [opt, str(pth if pth.is_absolute() else (cwd / pth).resolve())]
            continue
        joined = next((o for o in ("-I", "-isystem", "-iquote") if a.startswith(o)
                       and len(a) > len(o)), None)
        if joined is not None:
            pth = Path(a[len(joined):])
            out.append(joined + str(pth if pth.is_absolute() else (cwd / pth).resolve()))
            continue
        if a.startswith(("-D", "-U", "-std=")) or (a.startswith(("-f", "-m")) and not
                                                   a.startswith(("-fprofile", "-fcoverage"))):
            if a in ("-D", "-U"):
                out += [a, next(it, "")]
            else:
                out.append(a)
    return out


def _quick_includes(text: str) -> list[ImportSpec]:
    return [ImportSpec(module=m.group(2).strip(), kind="quote" if m.group(1) == '"' else "angle")
            for m in _INCLUDE_LINE_RE.finditer(text)]


def _insert_includes(src: str, lines: list[str]) -> str:
    """insert include lines after the last leading #include of src (else at the top)."""
    last = None
    for m in _ANY_INCLUDE_RE.finditer(src):
        if src.count("\n", 0, m.start()) > 400:
            break
        last = m
    block = "".join(ln + "\n" for ln in lines)
    if last is None:
        return block + src
    nl = src.find("\n", last.end())
    at = len(src) if nl < 0 else nl + 1
    return src[:at] + block + src[at:]


