@dataclass
class PomInfo:
    group: str = ""
    artifact: str = ""
    packaging: str = "jar"
    modules: list[str] = field(default_factory=list)
    source_dir: str = ""
    test_dir: str = ""
    properties: dict[str, str] = field(default_factory=dict)
    dependencies: list[tuple[str, str, str]] = field(default_factory=list)   # (g, a, scope)
    parent: tuple[str, str] | None = None


def _strip_ns(root: ET.Element) -> None:
    for el in root.iter():
        if isinstance(el.tag, str) and "}" in el.tag:
            el.tag = el.tag.split("}", 1)[1]


def _txt(el: ET.Element | None, path: str) -> str:
    if el is None:
        return ""
    x = el.find(path)
    return (x.text or "").strip() if x is not None and x.text else ""


def read_pom(path: Path) -> PomInfo | None:
    """the static facts of one pom.xml (no inheritance, no profiles); None when unreadable."""
    try:
        root = ET.parse(str(path)).getroot()
    except (OSError, ET.ParseError):
        return None
    _strip_ns(root)
    info = PomInfo(group=_txt(root, "groupId") or _txt(root, "parent/groupId"),
                   artifact=_txt(root, "artifactId"),
                   packaging=_txt(root, "packaging") or "jar")
    info.modules = [(m.text or "").strip() for m in root.findall("modules/module") if m.text]
    for prof in root.findall("profiles/profile/modules/module"):
        if prof.text and prof.text.strip() not in info.modules:
            info.modules.append(prof.text.strip())
    info.source_dir = _txt(root, "build/sourceDirectory")
    info.test_dir = _txt(root, "build/testSourceDirectory")
    props = root.find("properties")
    if props is not None:
        for p in props:
            if isinstance(p.tag, str):
                info.properties[p.tag] = (p.text or "").strip()
    for d in root.findall("dependencies/dependency"):
        info.dependencies.append((_txt(d, "groupId"), _txt(d, "artifactId"),
                                  _txt(d, "scope") or "compile"))
    if root.find("parent") is not None:
        info.parent = (_txt(root, "parent/groupId"), _txt(root, "parent/artifactId"))
    return info


def _pom_dir(base: str, value: str) -> str:
    """a pom path setting (`src/main/java`, `${project.basedir}/src`) as a repo rel."""
    v = value.strip()
    for prefix in ("${project.basedir}", "${basedir}", "${pom.basedir}"):
        if v.startswith(prefix):
            v = v[len(prefix):].lstrip("/")
    if not v or "${" in v or v.startswith("/"):
        return ""
    return _join(base, v)


