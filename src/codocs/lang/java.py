    # -- repair and messages -------------------------------------------------------------

    def fix_imports(self, src: str, build_errors: list[str], file_basename: str,
                    allowed: list) -> str | None:
        present = self.imports(src)
        present_text = {self.format_import(i) for i in present}
        bound = {i.bound for i in present if i.kind in ("single", "static")}
        add: list[ImportSpec] = []
        drop_pkgs: set[str] = set()
        for line in build_errors:
            m = _JAVAC_PATH_RE.match(line)
            if not m or m.group("base") != file_basename:
                continue
            msg = m.group("msg")
            pm = _NO_PKG_RE.search(msg)
            if pm:
                drop_pkgs.add(pm.group("pkg"))
                continue
            sm = _SYMBOL_RE.search(msg)
            if not sm:
                continue
            kind, name = sm.group("kind"), sm.group("name")
            if name in bound:
                continue
            pick = None
            for imp in allowed:
                ik = getattr(imp, "kind", "")
                if kind == "method":
                    if ik == "static" and (imp.name == name or (
                            imp.name == "*" and _ASSERT_NAMES.match(name)
                            and imp.module.endswith("Assertions"))):
                        pick = imp
                        break
                elif ik == "single" and _simple(imp.module) == name:
                    pick = imp
                    break
            if pick is None:
                continue
            text = self.format_import(pick)
            if text in present_text or any(self.format_import(a) == text for a in add):
                continue
            add.append(pick)
            bound.add(name)
        if not add and not drop_pkgs:
            return None
        out = src
        if drop_pkgs:
            p = _parse(out)
            spans = []
            for c in p.root.children:
                if c.type != "import_declaration":
                    continue
                spec = next((s for s in self.imports(p.node_text(c))), None)
                if spec is None:
                    continue
                mod = spec.module
                pkg = mod if spec.kind == "wildcard" else mod.rpartition(".")[0]
                if any(mod == d or pkg == d or mod.startswith(d + ".") for d in drop_pkgs):
                    spans.append(p.span(c))
            if spans:
                out = _cut_spans(out, spans)
        if add:
            out = self._add_imports(out, [self.format_import(a) for a in add])
        return out if out != src else None

    def _add_imports(self, src: str, lines: list[str]) -> str:
        p = _parse(src)
        last = None
        pkg = None
        for c in p.root.children:
            if c.type == "import_declaration":
                last = c
            elif c.type == "package_declaration":
                pkg = c
        text = "\n".join(lines)
        if last is not None:
            e = p.end(last)
            return src[:e] + "\n" + text + src[e:]
        if pkg is not None:
            e = p.end(pkg)
            return src[:e] + "\n\n" + text + src[e:]
        return text + "\n\n" + src

    def fix_allowed(self, source_imports: list) -> list:
        out = list(source_imports)
        have = {self.format_import(i) for i in out}
        for n in JAVA_UTIL:
            spec = ImportSpec(module=f"java.util.{n}", kind="single",
                              text=f"import java.util.{n};")
            if spec.text not in have:
                out.append(spec)
        return out

    def default_allowed(self, runner: Any, unit: Any) -> list:
        out: list[ImportSpec] = []
        seen: set[str] = set()
        root = getattr(runner, "module_root", None)
        for f in unit.files:
            for imp in self.imports(self.read(f, root)):
                text = self.format_import(imp)
                if text not in seen:
                    seen.add(text)
                    out.append(imp)
        for module, kind in JUNIT_ALLOWED:
            if kind == "static*":
                spec = ImportSpec(module=module, name="*", kind="static",
                                  text=f"import static {module}.*;")
            else:
                spec = ImportSpec(module=module, kind="single", text=f"import {module};")
            if spec.text not in seen:
                seen.add(spec.text)
                out.append(spec)
        for spec in self.fix_allowed([]):
            if spec.text not in seen:
                seen.add(spec.text)
                out.append(spec)
        return out

    def failure_message(self, output: str) -> str:
        lines = [ln.rstrip() for ln in output.strip().splitlines() if ln.strip()]
        summary = next((ln.strip() for ln in lines
                        if re.search(r"(?:Error|Exception|Failure)\b[^\s]*:", ln)
                        and not ln.lstrip().startswith("at ")), "")
        frames = [ln for ln in lines if ln.lstrip().startswith("at ")]
        rest = [ln for ln in lines if not ln.lstrip().startswith("at ")]
        body = "\n".join(rest + frames[:8])
        first = rest[0].strip() if rest else ""
        text = body if (not summary or summary == first) else summary + "\n" + body
        text = text or "test failed"
        return text if len(text) <= 2000 else text[:2000] + "\n..."

    def crash_message(self, res: TestResult) -> str:
        for ln in reversed((res.tail or "").splitlines()):
            s = ln.strip()
            if s and ("timed out" in s or "Exception" in s or "Error" in s or "exit" in s):
                return f"did not run: the test JVM exited early ({s[:200]})"
        return "did not run: the test JVM exited early"

    # -- resolution -----------------------------------------------------------------------

    def resolve_imports(self, rel: str, imports: list, ctx: RepoContext) -> list[str]:
        lay = self.layout() if self.ctx is not None else None
        if lay is None:
            return []
        own_pkg = lay.packages.get(rel)
        if own_pkg is None:
            own_pkg = package_of(ctx.read(rel))
        unit_of: dict[str, str] = {}
        for u in lay.units.values():
            for f in u.files:
                unit_of[f] = u.rel
        out: list[str] = []

        def add(f: str | None) -> None:
            if f is not None and f in unit_of and unit_of[f] not in out:
                out.append(unit_of[f])

        for imp in imports:
            kind = getattr(imp, "kind", "")
            if kind in ("single", "static"):
                add(self._class_file(imp.module, lay))
            elif kind == "wildcard":
                for u in lay.units.values():
                    if u.import_path == imp.module and u.rel not in out:
                        out.append(u.rel)
                if not any(u.import_path == imp.module for u in lay.units.values()):
                    add(self._class_file(imp.module, lay))
            elif kind == "simple":
                name = imp.module
                add(lay.classes.get(f"{own_pkg}.{name}" if own_pkg else name))
        return out

