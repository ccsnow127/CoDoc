    # -- static facts ----------------------------------------------------------------------

    def wiki_facts(self, root: Path, rel: str, src: str, ctx: RepoContext) -> WikiFileFacts:
        from codocs.lang.treesitter import line_count

        p = _parse(src)
        is_main = False

        def visit(node) -> None:
            nonlocal is_main
            for m in _members(node):
                if m.type in TYPE_NODES:
                    visit(m)
                elif _is_main(p, m) and "public" in _keyword_mods(p, m):
                    is_main = True

        for c in _top_types(p):
            visit(c)
        doc = ""
        if PurePosixPath(rel).name == "package-info.java":
            for c in p.root.children:
                if c.type == "block_comment" and p.node_text(c).startswith("/**"):
                    doc = self._javadoc(p.node_text(c))
                    break
        return WikiFileFacts(decls=_decls(p), imports=self.imports(src), is_main=is_main,
                             doc_comment=doc, loc=line_count(src))

    @staticmethod
    def _javadoc(text: str) -> str:
        body = text[3:-2] if text.endswith("*/") else text[3:]
        lines = [re.sub(r"^\s*\*\s?", "", ln) for ln in body.splitlines()]
        return "\n".join(ln.rstrip() for ln in lines).strip()

    def graph_facts(self, root: Path, rel: str, src: str, ctx: RepoContext) -> GraphFileFacts:
        from codocs.lang.treesitter import iter_types

        p = _parse(src)
        facts = GraphFileFacts(imports=self.imports(src), is_test=self.is_test_file(rel, src))
        funcs: dict[str, FuncFact] = {}

        def declared(node) -> dict[str, str]:
            """name -> simple declared type for params and locals inside node."""
            out: dict[str, str] = {}
            for n in iter_types(node, ("formal_parameter", "spread_parameter",
                                       "local_variable_declaration", "enhanced_for_statement",
                                       "catch_formal_parameter", "resource")):
                t = n.child_by_field_name("type")
                if t is None:
                    continue
                ty = _base_type(p.node_text(t))
                if n.type == "local_variable_declaration":
                    for d in n.children:
                        if d.type == "variable_declarator":
                            nm = d.child_by_field_name("name")
                            if nm is None:
                                continue
                            val = d.child_by_field_name("value")
                            if ty == "var" and val is not None and \
                                    val.type == "object_creation_expression":
                                vt = val.child_by_field_name("type")
                                ty2 = _base_type(p.node_text(vt)) if vt is not None else ""
                                out[p.node_text(nm)] = ty2
                            elif ty != "var":
                                out[p.node_text(nm)] = ty
                else:
                    nm = n.child_by_field_name("name")
                    if nm is not None and ty != "var":
                        out[p.node_text(nm)] = ty
            return out

        def calls_in(body, fields: dict[str, str], cls_name: str) -> list[CallFact]:
            local = declared(body)
            out: list[CallFact] = []
            for n in iter_types(body, ("method_invocation", "object_creation_expression",
                                       "method_reference", "explicit_constructor_invocation")):
                if n.type == "method_invocation":
                    nm = n.child_by_field_name("name")
                    obj = n.child_by_field_name("object")
                    if nm is None:
                        continue
                    qual, recv = "", None
                    if obj is not None:
                        if obj.type in ("this", "super"):
                            qual = obj.type
                            recv = cls_name if obj.type == "this" else None
                        elif obj.type == "identifier":
                            qual = p.node_text(obj)
                            recv = local.get(qual) or fields.get(qual)
                        elif obj.type == "field_access":
                            o2 = obj.child_by_field_name("object")
                            f2 = obj.child_by_field_name("field")
                            if o2 is not None and o2.type == "this" and f2 is not None:
                                qual = p.node_text(f2)
                                recv = fields.get(qual)
                            else:
                                qual = _collapse(p.node_text(obj))
                        else:
                            qual = _collapse(p.node_text(obj))[:80]
                    out.append(CallFact(kind="call", qual=qual, name=p.node_text(nm),
                                        recv_type=recv, line=p.line(n)))
                elif n.type == "object_creation_expression":
                    ty = n.child_by_field_name("type")
                    if ty is None:
                        continue
                    name = _base_type(p.node_text(ty))
                    out.append(CallFact(kind="call", qual=name, name=name, recv_type=name,
                                        line=p.line(n)))
                elif n.type == "explicit_constructor_invocation":
                    ctor = n.child_by_field_name("constructor")
                    if ctor is not None:
                        out.append(CallFact(kind="call", qual=ctor.type, name=ctor.type,
                                            recv_type=cls_name if ctor.type == "this" else None,
                                            line=p.line(n)))
                else:
                    kids = [c for c in n.children if c.type not in ("::",)]
                    if len(kids) >= 2:
                        q = _collapse(p.node_text(kids[0]))
                        nm = p.node_text(kids[-1])
                        recv = local.get(q) or fields.get(q) or (cls_name if q == "this"
                                                                 else None)
                        out.append(CallFact(kind="ref", qual=q, name=nm, recv_type=recv,
                                            line=p.line(n)))
            return out

        def visit(node, outer: str) -> None:
            simple = _name(p, node)
            if not simple:
                return
            qual = f"{outer}.{simple}" if outer else simple
            tf = TypeFact(is_interface=node.type in ("interface_declaration",
                                                     "annotation_type_declaration"),
                          line=p.line(node))
            sup = node.child_by_field_name("superclass")
            if sup is not None:
                tf.bases.extend(_base_type(p.node_text(c)) for c in sup.named_children)
            for k in ("interfaces",):
                it = node.child_by_field_name(k)
                if it is not None:
                    for tl in iter_types(it, ("type_list",)):
                        tf.bases.extend(_base_type(p.node_text(c)) for c in tl.named_children)
            for c in node.children:
                if c.type == "extends_interfaces":
                    for tl in iter_types(c, ("type_list",)):
                        tf.bases.extend(_base_type(p.node_text(x)) for x in tl.named_children)
            if node.type == "record_declaration":
                params = node.child_by_field_name("parameters")
                if params is not None:
                    for fp in params.named_children:
                        t, n = fp.child_by_field_name("type"), fp.child_by_field_name("name")
                        if t is not None and n is not None:
                            tf.fields[p.node_text(n)] = _base_type(p.node_text(t))
            for m in _members(node):
                if m.type == "field_declaration":
                    t = m.child_by_field_name("type")
                    for d in m.children:
                        if d.type == "variable_declarator" and t is not None:
                            nm = d.child_by_field_name("name")
                            if nm is not None:
                                tf.fields[p.node_text(nm)] = _base_type(p.node_text(t))
            facts.types[qual] = tf
            for m in _members(node):
                if m.type in TYPE_NODES:
                    visit(m, qual)
                    continue
                if m.type not in _METHOD_NODES:
                    continue
                mname = simple if m.type != "method_declaration" else _name(p, m)
                if mname not in tf.methods:
                    tf.methods.append(mname)
                body = m.child_by_field_name("body")
                if body is None:
                    continue
                fname = f"{qual}.{mname}"
                if fname not in funcs:
                    funcs[fname] = FuncFact(
                        name=fname, kind="method", line=p.line(m), end_line=p.end_line(m),
                        static="static" in _keyword_mods(p, m), cls=qual,
                        start=p.start(m), end=p.end(m))
                calls = calls_in(m, tf.fields, simple)
                facts.calls.setdefault(fname, []).extend(calls)

        for c in _top_types(p):
            visit(c, "")
        facts.funcs = list(funcs.values())
        return facts
