class JavaAdapter(LangAdapterBase):
    """Java (Maven modules and plain javac source roots); Gradle builds are static-only."""

    name = "java"
    test_file_patterns = TEST_PATTERNS

    def __init__(self, ctx: RepoContext | None = None):
        super().__init__(ctx)
        self._warned_gradle = False

    # -- files ------------------------------------------------------------------------

    def owns(self, rel: str) -> bool:
        return rel.endswith(".java")

    def _source(self, rel: str, src: str | None) -> str:
        if src is not None:
            return src
        if self.ctx is None:
            return ""
        return self.ctx.read(rel)

    def has_tests(self, src: str) -> bool:
        """a concrete class with a test method (or one extending a base test class)."""
        if not src:
            return False
        p = _parse(src)
        if _test_methods(p):
            return True
        for c in _top_types(p):
            if c.type == "class_declaration" and "abstract" not in _keyword_mods(p, c) \
                    and c.child_by_field_name("superclass") is not None:
                return True
        return False

    def is_test_file(self, rel: str, src: str | None = None) -> bool:
        rel = _norm(rel)
        if not rel.endswith(".java"):
            return False
        name = PurePosixPath(rel).name
        if not any(fnmatchcase(name, g) for g in TEST_PATTERNS):
            return False
        lay = self._layout_or_none()
        if lay is not None:
            mod = self._module_for(rel, lay)
            if mod is not None and mod.mode == "maven" and not _under(rel, mod.test_root):
                return False
            if mod is not None and mod.mode == "gradle":
                return False
        elif "/src/main/" in "/" + rel:
            return False
        text = self._source(rel, src)
        if not text:
            return src is None and "/src/test/" in "/" + rel
        return self.has_tests(text)

    def is_generated(self, src: str, rel: str = "") -> bool:
        if self.include_generated:
            return False
        if "/target/" in "/" + _norm(rel) + "/":
            return True
        head = src
        m = _PKG_RE.search(src)
        if m:
            head = src[:m.start()]
        else:
            head = src[:2000]
        if _GENERATED_RE.search(head):
            return True
        try:
            p = _parse(src)
        except Exception:      # noqa: BLE001 - parsing problems are not generated code
            return False
        for c in _top_types(p):
            if "Generated" in _annotation_names(p, c):
                return True
        return False

    # -- parsing -------------------------------------------------------------------

    def decls(self, src: str) -> list[Decl]:
        return _decls(_parse(src))

    def imports(self, src: str) -> list[ImportSpec]:
        p = _parse(src)
        out: list[ImportSpec] = []
        for c in p.root.children:
            if c.type != "import_declaration":
                continue
            static = any(k.type == "static" for k in c.children)
            wildcard = any(k.type == "asterisk" for k in c.children)
            name_node = next((k for k in c.children
                              if k.type in ("scoped_identifier", "identifier")), None)
            if name_node is None:
                continue
            dotted = p.node_text(name_node)
            text = "import " + ("static " if static else "") + dotted \
                + (".*" if wildcard else "") + ";"
            if static:
                if wildcard:
                    spec = ImportSpec(module=dotted, name="*", kind="static")
                else:
                    cls, _, member = dotted.rpartition(".")
                    spec = ImportSpec(module=cls, name=member, kind="static")
            elif wildcard:
                spec = ImportSpec(module=dotted, kind="wildcard")
            else:
                spec = ImportSpec(module=dotted, kind="single")
            spec.line = p.line(c)
            spec.text = text
            out.append(spec)
        return out

    def format_import(self, imp: Any) -> str:
        text = getattr(imp, "text", "")
        if text:
            return text
        kind = getattr(imp, "kind", "single")
        module = getattr(imp, "module", str(imp))
        if kind == "static":
            return f"import static {module}.{imp.name or '*'};"
        if kind == "wildcard":
            return f"import {module}.*;"
        return f"import {module};"

    def preamble(self, src: str) -> str:
        p = _parse(src)
        node = _package_node(p)
        return _collapse(p.node_text(node)) if node is not None else ""

    def apply_preamble(self, code: str, preamble: str) -> str:
        p = _parse(code)
        node = _package_node(p)
        if node is not None:
            a, b = p.span(node)
            if preamble:
                return code[:a] + preamble + code[b:]
            return _cut_spans(code, [(a, b)]).lstrip("\n")
        if not preamble:
            return code
        return preamble + "\n\n" + code.lstrip("\n")

    # -- tests in source -------------------------------------------------------------

    def test_names(self, src: str, rel: str) -> list[str]:
        if not src:
            return []
        return list(dict.fromkeys(n for n, _, _ in _test_methods(_parse(src))))

    def test_lines(self, src: str, rel: str) -> dict[str, int]:
        out: dict[str, int] = {}
        if not src:
            return out
        p = _parse(src)
        for name, m, _ in _test_methods(p):
            n = m.child_by_field_name("name")
            out.setdefault(name, p.line(n) if n is not None else p.line(m))
        return out

    def remove_tests(self, src: str, names: set[str]) -> str:
        if not names:
            return src
        p = _parse(src)
        short = {n.rsplit("#", 1)[-1] for n in names if "#" not in n}
        spans = []
        for name, m, _ in _test_methods(p):
            if name in names or name.rsplit("#", 1)[-1] in short:
                spans.append((_doc_start(p, m), p.end(m)))
        return _cut_spans(src, spans) if spans else src

    def strip_non_tests(self, src: str) -> str:
        p = _parse(src)
        spans = []

        def visit(node) -> None:
            for m in _members(node):
                if m.type in TYPE_NODES:
                    visit(m)
                elif _is_main(p, m):
                    spans.append((_doc_start(p, m), p.end(m)))

        for c in _top_types(p):
            visit(c)
        return _cut_spans(src, spans) if spans else src

    def normalize_suite(self, src: str, unit: Any, target_rel: str) -> str:
        pkg = getattr(unit, "import_path", "") or ""
        out = self.apply_preamble(src, f"package {pkg};" if pkg else "")
        want = self.suite_class(PurePosixPath(target_rel).name)
        p = _parse(out)
        tops = [c for c in _top_types(p) if c.type == "class_declaration"]
        if not tops:
            return out
        cls = tops[0]
        old = _name(p, cls)
        if not old or old == want:
            return out
        edits: list[tuple[int, int]] = []
        n = cls.child_by_field_name("name")
        edits.append(p.span(n))
        for m in _members(cls):
            if m.type == "constructor_declaration" and _name(p, m) == old:
                edits.append(p.span(m.child_by_field_name("name")))
        for a, b in sorted(edits, reverse=True):
            out = out[:a] + want + out[b:]
        return out

    def mutation_sites(self, src: str) -> list[Mutant]:
        from codocs.lang.treesitter import ancestors, error_spans, in_spans, walk

        p = _parse(src)
        errs = error_spans(p)
        strings = _string_names(p)
        methods = _string_methods(p) | self._repo_string_methods()
        out: list[Mutant] = []

        def add(tok, cat: str, repl: str) -> None:
            a = p.start(tok)
            if in_spans(a, errs):
                return
            orig = p.node_text(tok)
            out.append(Mutant(id=f"m{a}", offset=a, line=p.line(tok),
                              operator=f"{cat}: {orig} -> {repl}", original=orig,
                              replacement=repl))

        for body in _bodies(p):
            for n in walk(body):
                t = n.type
                if t in _ANNOTATIONS:
                    continue
                if t == "binary_expression":
                    op = n.child_by_field_name("operator")
                    if op is None:
                        continue
                    o = op.type
                    if o in _SWAPS:
                        add(op, *_SWAPS[o])
                    elif o in _ARITH:
                        if o == "+" and any(
                                _stringy(p, n.child_by_field_name(k), strings, methods)
                                for k in ("left", "right")
                                if n.child_by_field_name(k) is not None):
                            continue
                        add(op, "arith", _ARITH[o])
                elif t == "assignment_expression":
                    op = n.child_by_field_name("operator")
                    if op is None or op.type not in _ASSIGN:
                        continue
                    if op.type == "+=" and any(
                            _stringy(p, n.child_by_field_name(k), strings, methods)
                            for k in ("left", "right") if n.child_by_field_name(k) is not None):
                        continue
                    add(op, "assign", _ASSIGN[op.type])
                elif t == "update_expression":
                    for c in n.children:
                        if c.type in _INCDEC:
                            add(c, "incdec", _INCDEC[c.type])
                elif t in _BOOLS:
                    if any(a.type in _ANNOTATIONS for a in ancestors(n)):
                        continue
                    add(n, "bool", _BOOLS[t])
        out.sort(key=lambda m: m.offset)
        seen: set[int] = set()
        uniq = []
        for m in out:
            if m.offset not in seen:
                seen.add(m.offset)
                uniq.append(m)
        return uniq

    def _repo_string_methods(self) -> set[str]:
        """names of methods some repository class declares with a string return type (a call
        like `currency.symbol() + n` concatenates; mutating its `+` cannot compile)."""
        if self.ctx is None:
            return set()
        key = ("java", "string-methods")
        hit = self.ctx.cache.get(key)
        if hit is None:
            hit = set()
            for rel in self.ctx.lang_files("java"):
                try:
                    hit |= _string_methods(_parse(self.ctx.read(rel)))
                except Exception:
                    continue
            self.ctx.cache[key] = hit
        return hit

    # -- layout ------------------------------------------------------------------------

    def _layout_or_none(self) -> JavaLayout | None:
        return self.layout() if self.ctx is not None else None

    def layout(self) -> JavaLayout:
        """modules, file roles, packages, the class index and the units (cached per ctx)."""
        if self.ctx is None:
            raise RuntimeError("the Java adapter needs a RepoContext for the build layout")
        key = ("java", "layout")
        hit = self.ctx.cache.get(key)
        if hit is None:
            hit = self.ctx.cache[key] = self._build_layout()
        return hit

    def _build_layout(self) -> JavaLayout:
        ctx = self.ctx
        assert ctx is not None
        lay = JavaLayout()
        poms: dict[str, PomInfo] = {}
        for d, names in ctx.dirs.items():
            if "pom.xml" in names:
                info = read_pom(ctx.root / d / "pom.xml")
                if info is not None:
                    poms[d] = info
        lay.gradle = sorted(d for d, names in ctx.dirs.items() if GRADLE_FILES & set(names))
        aggregator: dict[str, str] = {}
        for d, info in sorted(poms.items()):
            for m in info.modules:
                child = _join(d, m)
                if child.endswith(".xml"):
                    child = _parent(child)
                if child in poms and child != d:
                    aggregator.setdefault(child, d)
        for d, info in sorted(poms.items()):
            if info.packaging == "pom":
                continue
            top, seen = d, {d}
            while top in aggregator and aggregator[top] not in seen:
                top = aggregator[top]
                seen.add(top)
            src_root = _pom_dir(d, info.source_dir) if info.source_dir else ""
            test_root = _pom_dir(d, info.test_dir) if info.test_dir else ""
            enc = info.properties.get("project.build.sourceEncoding", "") or "UTF-8"
            lay.modules[d] = JavaModule(
                rel=d, mode="maven", source_root=src_root or _join(d, "src/main/java"),
                test_root=test_root or _join(d, "src/test/java"), reactor=top, encoding=enc,
                artifact=info.artifact or (PurePosixPath(d).name if d else ctx.root.name),
                deps=list(info.dependencies))
        maven_dirs = sorted(lay.modules, key=lambda x: -len(x))

        loose: list[tuple[str, str | None]] = []    # (rel, gradle build dir or None)
        for rel in ctx.files.get("java", []):
            mod = next((m for m in maven_dirs if _under(rel, m)), None)
            if mod is not None:
                jm = lay.modules[mod]
                if _under(rel, jm.source_root):
                    role = "main"
                elif _under(rel, jm.test_root):
                    role = "test" if self._test_class_file(rel) else "support"
                else:
                    role = "other"
                lay.file_module[rel] = mod
                lay.file_role[rel] = role
                continue
            gradle = next((g for g in sorted(lay.gradle, key=lambda x: -len(x))
                           if _under(rel, g)), None)
            loose.append((rel, gradle))

        for rel, gradle in loose:
            text = ctx.read(rel)
            pkg = package_of(text)
            d = _parent(rel)
            pkg_path = pkg.replace(".", "/")
            if pkg_path and (d == pkg_path or d.endswith("/" + pkg_path)):
                root = d[: len(d) - len(pkg_path)].rstrip("/")
            else:
                root = d
            mode = "plain" if gradle is None else "gradle"
            gfile = ""
            if gradle is not None:
                names = ctx.dirs.get(gradle, [])
                gfile = _join(gradle, next((n for n in sorted(names) if n in GRADLE_FILES), ""))
            key = root
            if key not in lay.modules:
                lay.modules[key] = JavaModule(rel=key, mode=mode, source_root=root,
                                              test_root=root, reactor=root,
                                              artifact=PurePosixPath(root).name
                                              or ctx.root.name, gradle_file=gfile)
            jm = lay.modules[key]
            lay.file_module[rel] = key
            if mode == "gradle":
                lay.file_role[rel] = "test" if "/src/test/" in "/" + rel else "main"
            else:
                lay.file_role[rel] = "test" if self._test_class_file(rel, text) else "main"
            lay.packages[rel] = pkg

        # packages and the class index
        for rel, role in lay.file_role.items():
            if role == "other":
                continue
            text = ctx.read(rel)
            pkg = lay.packages.get(rel)
            if pkg is None:
                pkg = lay.packages[rel] = package_of(text)
            for name in self.top_level_names(text):
                lay.classes.setdefault(f"{pkg}.{name}" if pkg else name, rel)
        ctx.java_classes.update(lay.classes)
        for k, m in lay.modules.items():
            ctx.java_modules[k] = m.to_dict()

        # units: main-source directories
        by_dir: dict[str, list[str]] = {}
        for rel, role in sorted(lay.file_role.items()):
            if role == "main":
                by_dir.setdefault(_parent(rel), []).append(rel)
        for d, files in sorted(by_dir.items()):
            mod = lay.modules[lay.file_module[files[0]]]
            pkg = next((lay.packages[f] for f in files if lay.packages.get(f)), "")
            if not pkg:
                pkg = _rel_to(d, mod.source_root).replace("/", ".")
            lay.units[d] = Unit(
                lang="java", rel=d, name=pkg, import_path=pkg, files=sorted(files),
                build_root=mod.rel if mod.mode == "maven" else mod.source_root,
                extra={"module": mod.rel, "reactor": mod.reactor,
                       "source_root": mod.source_root, "test_root": mod.test_root,
                       "mode": mod.mode, "artifact": mod.artifact,
                       "encoding": mod.encoding})
        self._assign_tests(lay)
        return lay

    def _test_class_file(self, rel: str, text: str | None = None) -> bool:
        name = PurePosixPath(rel).name
        if not any(fnmatchcase(name, g) for g in TEST_PATTERNS):
            return False
        return self.has_tests(text if text is not None else self.ctx.read(rel))

    def _assign_tests(self, lay: JavaLayout) -> None:
        by_pkg: dict[tuple[str, str], list[Unit]] = {}
        for u in lay.units.values():
            by_pkg.setdefault((u.extra["module"], u.import_path), []).append(u)
        unit_classes: dict[str, Unit] = {}
        for u in lay.units.values():
            for f in u.files:
                for name in self.top_level_names(self.ctx.read(f)):
                    unit_classes[f"{u.import_path}.{name}" if u.import_path else name] = u
        tests: dict[str, set[str]] = {}
        for rel, role in lay.file_role.items():
            if role != "test":
                continue
            mod = lay.file_module[rel]
            jm = lay.modules[mod]
            if jm.mode == "gradle":
                continue
            pkg = lay.packages.get(rel, "")
            hits: set[str] = set()
            if jm.mode == "maven":
                own = by_pkg.get((mod, pkg), [])
            else:
                own = [u for (m, p), us in by_pkg.items() for u in us
                       if p == pkg and lay.modules[m].mode == "plain"]
            hits.update(u.rel for u in own)
            for imp in self.imports(self.ctx.read(rel)):
                if imp.kind == "wildcard":
                    cands = [u for (m, p), us in by_pkg.items() for u in us if p == imp.module]
                else:
                    u = unit_classes.get(imp.module)
                    cands = [u] if u is not None else []
                for u in cands:
                    um = lay.modules[u.extra["module"]]
                    if (jm.mode == "maven" and u.extra["module"] == mod) or \
                            (jm.mode == "plain" and um.mode == "plain"):
                        hits.add(u.rel)
            for h in hits:
                tests.setdefault(h, set()).add(rel)
        for rel, u in lay.units.items():
            u.test_files = sorted(tests.get(rel, set()))

    def _module_for(self, rel: str, lay: JavaLayout) -> JavaModule | None:
        key = lay.file_module.get(rel)
        if key is not None:
            return lay.modules[key]
        mods = [m for m in lay.modules.values() if m.mode == "maven" and _under(rel, m.rel)]
        if mods:
            return max(mods, key=lambda m: len(m.rel))
        return None

    def module(self, unit: Any) -> JavaModule | None:
        lay = self._layout_or_none()
        if lay is None:
            return None
        return lay.modules.get(unit.extra.get("module", "")) if getattr(unit, "extra", None) \
            else None

    def top_level_names(self, src: str) -> list[str]:
        if not src:
            return []
        p = _parse(src)
        return [n for n in (_name(p, c) for c in _top_types(p)) if n]

    def test_classes(self, src: str) -> list[str]:
        """FQCNs of the top-level classes of a test file that can be run (static view)."""
        if not src:
            return []
        p = _parse(src)
        pkg = _package(p)
        out = []
        tested = {n.split("#", 1)[0].split("$", 1)[0] for n, _, _ in _test_methods(p)}
        for c in _top_types(p):
            if c.type != "class_declaration" or "abstract" in _keyword_mods(p, c):
                continue
            fq = f"{pkg}.{_name(p, c)}" if pkg else _name(p, c)
            if fq in tested or c.child_by_field_name("superclass") is not None:
                out.append(fq)
        if not out:
            tops = [c for c in _top_types(p) if c.type == "class_declaration"]
            if tops:
                out.append(f"{pkg}.{_name(p, tops[0])}" if pkg else _name(p, tops[0]))
        return out

    def units(self) -> dict[str, Unit]:
        return self.layout().units

    def unit(self, rel: str) -> Unit | None:
        return self.layout().units.get(_norm(rel))

    # -- units and targets -------------------------------------------------------------

    async def discover(self, runner: Any, subtree: str | None = None,
                       packages: list[str] | None = None) -> dict[str, Unit]:
        if self.ctx is None:
            root = getattr(runner, "module_root", None)
            if root is None:
                raise RuntimeError("Java discovery needs a RepoContext or a runner")
            self.ctx = RepoContext.build(root, ["java"])
        lay = self.layout()
        units = dict(lay.units)
        sub = _norm(subtree)
        if sub:
            units = {k: v for k, v in units.items() if _under(k, sub)}
        if packages:
            wanted = [_norm(p) for p in packages]
            units = {k: v for k, v in units.items()
                     if any(k == p or not p or k.startswith(p + "/") for p in wanted)}
        if any(u.extra.get("mode") == "gradle" for u in units.values()) \
                and not self._warned_gradle:
            self._warned_gradle = True
            files = sorted({lay.modules[u.extra["module"]].gradle_file for u in units.values()
                            if u.extra.get("mode") == "gradle"})
            log.warning("Gradle builds are not supported yet (found %s); their Java files are "
                        "covered statically by the wiki and bizlogic only",
                        files[0] if files else "build.gradle")
        return dict(sorted(units.items()))

    def file_status(self, rel: str, unit: Any) -> str | None:
        name = PurePosixPath(rel).name
        if name in ("package-info.java", "module-info.java"):
            return "no-decls"
        if getattr(unit, "extra", {}).get("mode") == "gradle":
            return "unsupported-build"
        return None

    # -- context for prompts ---------------------------------------------------------

    def suite_class(self, stem: str) -> str:
        base = stem[:-5] if stem.endswith(".java") else stem
        return f"{base}CodocsTest"

    def _outline(self, p, node, indent: str = "", public_only: bool = False) -> list[str]:
        """a type's header, fields, enum constants and member signatures (no bodies)."""
        lines = [indent + _type_signature(p, node) + " {"]
        inner = indent + "    "
        consts = []
        for m in _members(node):
            t = m.type
            if t == "enum_constant":
                consts.append(_collapse(p.node_text(m.child_by_field_name("name")))
                              + (_collapse(p.node_text(m.child_by_field_name("arguments")))
                                 if m.child_by_field_name("arguments") is not None else ""))
                continue
            if consts:
                lines.append(inner + ", ".join(consts) + ";")
                consts = []
            if public_only and t not in TYPE_NODES:
                mods = _keyword_mods(p, m)
                if node.type != "interface_declaration" and not ({"public", "protected"} & set(
                        mods)):
                    continue
            if t in ("field_declaration", "constant_declaration"):
                lines.append(inner + _collapse(self._masked_text(p, m)))
            elif t in _METHOD_NODES:
                sig = _method_signature(p, m)
                lines.append(inner + sig + ";")
            elif t == "annotation_type_element_declaration":
                lines.append(inner + _collapse(self._masked_text(p, m)))
            elif t in TYPE_NODES:
                lines.extend(self._outline(p, m, inner, public_only))
        if consts:
            lines.append(inner + ", ".join(consts) + ";")
        lines.append(indent + "}")
        return lines

    @staticmethod
    def _masked_text(p, node, indent: bool = False) -> str:
        """node text without its comments (from the start of its line with indent=True)."""
        from codocs.lang.treesitter import iter_types

        a, b = p.span(node)
        text = p.text[a:b]
        if indent:
            ls = p.text.rfind("\n", 0, a) + 1
            if not p.text[ls:a].strip():
                text = p.text[ls:a] + text
                a = ls
        cuts = sorted((p.start(c) - a, p.end(c) - a)
                      for c in iter_types(node, _COMMENTS, prune=_COMMENTS))
        for x, y in reversed(cuts):
            text = text[:x] + text[y:]
        return text

    def _type_blocks(self, rel: str, src: str, wanted: set[str] | None,
                     public_only: bool = False) -> list[tuple[str, str, str]]:
        """(rel, type name, outline) for the file's top-level types (in `wanted`, if given)."""
        p = _parse(src)
        out = []
        for c in _top_types(p):
            name = _name(p, c)
            if wanted is not None and name not in wanted:
                continue
            out.append((rel, name, "\n".join(self._outline(p, c, "", public_only))))
        return out

    def package_context(self, root: Path, unit: Any, target_rel: str,
                        max_chars: int = 12000) -> str:
        src = self.read(target_rel, root)
        used = self.identifiers(src) if src else set()
        blocks: list[tuple[str, str, str]] = []
        seen: set[tuple[str, str]] = set()

        def push(items: list[tuple[str, str, str]]) -> None:
            for it in items:
                key = (it[0], it[1])
                if key not in seen:
                    seen.add(key)
                    blocks.append(it)

        others = self._other_files(unit, target_rel)
        for f in others:
            fsrc = self.read(f, root)
            names = set(self.top_level_names(fsrc))
            push(self._type_blocks(f, fsrc, names & used))
        lay = self._layout_or_none()
        if lay is not None and src:
            for imp in self.imports(src):
                for crel, cname in self._import_targets(imp, used, lay):
                    if crel == target_rel or lay.file_role.get(crel) != "main":
                        continue
                    push(self._type_blocks(crel, self.read(crel, root), {cname}))
        # the rest of the package's public api, while room remains
        for f in others:
            push(self._type_blocks(f, self.read(f, root), None, public_only=True))
        lines: list[str] = []
        size = 0
        current = None
        for f, _type_name, text in blocks:
            head = ([""] if lines else []) + [f"// {f}"] if f != current else []
            chunk = head + [text]
            add = sum(len(c) + 1 for c in chunk)
            if size + add > max_chars - len(TRUNCATED) - 1:
                lines.append(TRUNCATED)
                break
            lines.extend(chunk)
            size += add
            current = f
        return "\n".join(lines) + "\n" if lines else ""

    def _import_targets(self, imp: ImportSpec, used: set[str], lay: JavaLayout
                        ) -> list[tuple[str, str]]:
        """(file rel, top-level type name) of the project types an import brings in and uses."""
        out: list[tuple[str, str]] = []
        if imp.kind == "wildcard":
            for fq, rel in sorted(lay.classes.items()):
                pkg, _, name = fq.rpartition(".")
                if pkg == imp.module and name in used:
                    out.append((rel, name))
            return out
        if imp.kind == "single" and _simple(imp.module) not in used:
            return out
        hit = self._class_key(imp.module, lay)
        if hit is not None:
            out.append((lay.classes[hit], _simple(hit)))
        return out

    def _class_key(self, fqcn: str, lay: JavaLayout) -> str | None:
        """the class-index key of a (possibly nested) FQCN: its top-level class."""
        name = fqcn.replace("$", ".")
        while name:
            if name in lay.classes:
                return name
            if "." not in name:
                return None
            name = name.rsplit(".", 1)[0]
        return None

    def _class_file(self, fqcn: str, lay: JavaLayout) -> str | None:
        """file of a (possibly nested) FQCN through the class index."""
        key = self._class_key(fqcn, lay)
        return lay.classes[key] if key is not None else None

    def package_identifiers(self, root: Path, unit: Any,
                            exclude_rel: str | None = None) -> set[str]:
        names: set[str] = set()
        for f in self._other_files(unit, exclude_rel):
            names.update(self.top_level_names(self.read(f, root)))
        test_dir = self._test_dir(unit)
        lay = self._layout_or_none()
        if lay is not None and test_dir is not None:
            for rel, role in lay.file_role.items():
                if role in ("test", "support") and _parent(rel) == test_dir:
                    names.update(self.top_level_names(self.read(rel, root)))
        return names

    def _test_dir(self, unit: Any) -> str | None:
        extra = getattr(unit, "extra", {}) or {}
        src_root = extra.get("source_root")
        test_root = extra.get("test_root")
        if src_root is None or test_root is None:
            return None
        return _join(test_root, _rel_to(unit.rel, src_root))

    def _companions(self, target_rel: str, src: str | None = None) -> set[str]:
        base = PurePosixPath(target_rel).name.removesuffix(".java")
        names = {base}
        if src:
            names.update(self.top_level_names(src))
        out = set()
        for n in names:
            out.update({f"{n}Test", f"{n}Tests", f"{n}TestCase", f"Test{n}"})
        return out

    def test_reference(self, root: Path, unit: Any, target_rel: str,
                       max_chars: int = 8000) -> str:
        src = self.read(target_rel, root)
        target_types = set(self.top_level_names(src))
        companions = self._companions(target_rel, src)
        files = list(unit.test_files)
        files.sort(key=lambda f: (PurePosixPath(f).name.removesuffix(".java")
                                  not in companions, f))
        picked: list[tuple[str, str]] = []
        example: tuple[int, str, str] | None = None
        for f in files:
            tsrc = self.read(f, root)
            if not tsrc:
                continue
            p = _parse(tsrc)
            is_comp = PurePosixPath(f).name.removesuffix(".java") in companions
            idents_file = self.identifiers(tsrc)
            if not is_comp and not (target_types & idents_file):
                continue
            tests = {(m.start_byte, m.end_byte) for _, m, _ in _test_methods(p)}

            def visit(cls, f=f, p=p, tests=tests, is_comp=is_comp) -> None:
                nonlocal example
                for m in _members(cls):
                    if m.type in TYPE_NODES:
                        if m.type == "class_declaration" and "Nested" not in \
                                _annotation_names(p, m):
                            picked.append((f, self._masked_text(p, m, indent=True).rstrip()))
                        else:
                            visit(m)
                        continue
                    if m.type in _COMMENTS or m.type in ("{", "}", ";"):
                        continue
                    text = self._masked_text(p, m, indent=True).rstrip()
                    if not text.strip():
                        continue
                    if (m.start_byte, m.end_byte) in tests:
                        if is_comp and target_types & self.identifiers(text) and (
                                example is None or len(text) < example[0]):
                            example = (len(text), f, text)
                        continue
                    if m.type in ("field_declaration", "method_declaration",
                                  "constructor_declaration", "static_initializer", "block"):
                        if m.type == "method_declaration" and not (
                                SETUP_ANNOTATIONS & set(_annotation_names(p, m))) and not \
                                is_comp and not (target_types & self.identifiers(text)):
                            continue
                        picked.append((f, text))

            for c in _top_types(p):
                visit(c)
        if example is not None and len(example[2]) <= max_chars // 3:
            picked.insert(0, (example[1], "// example test of the target from the existing "
                              "suite\n" + example[2]))
        lines: list[str] = []
        size = 0
        current = None
        for f, text in picked:
            chunk = ([f"// from {f}"] if f != current else []) + [text, ""]
            add = sum(len(c) + 1 for c in chunk)
            if size + add > max_chars:
                lines.append(TRUNCATED)
                break
            lines.extend(chunk)
            size += add
            current = f
        return "\n".join(lines).strip() + "\n" if lines else ""

    def allowed_third_party(self, root: Path, unit: Any) -> list[str]:
        mod = self.module(unit)
        if mod is None or mod.mode != "maven":
            return []
        return sorted({f"{g}:{a}" for g, a, _ in mod.deps if g and a})

    # -- tests of a unit -----------------------------------------------------------------

    def test_index(self, root: Path, unit: Any) -> dict[str, dict]:
        out: dict[str, dict] = {}
        from codocs.lang.treesitter import iter_types

        for f in sorted(unit.test_files):
            src = self.read(f, root)
            if not src:
                continue
            p = _parse(src)
            for name, m, cls in _test_methods(p):
                fields_text = " ".join(self._masked_text(p, x) for x in _members(cls)
                                       if x.type == "field_declaration")
                idents = self.identifiers(self._masked_text(p, m) + "\n" + fields_text)
                sel = set()
                for n in iter_types(m, ("method_invocation", "field_access")):
                    k = n.child_by_field_name("name") or n.child_by_field_name("field")
                    if k is not None:
                        sel.add(p.node_text(k))
                entry = out.setdefault(name, {"file": f, "idents": [], "selectors": []})
                entry["idents"] = sorted(set(entry["idents"]) | idents)
                entry["selectors"] = sorted(set(entry["selectors"]) | sel)
        return out

    def _visible(self, test_src: str, target_pkg: str, target_types: set[str]) -> bool:
        """whether a test file can name the target's types (same package, import or FQCN)."""
        if package_of(test_src) == target_pkg:
            return True
        for imp in self.imports(test_src):
            if imp.kind == "wildcard" and imp.module == target_pkg:
                return True
            if imp.kind in ("single", "static"):
                pkg, _, name = imp.module.rpartition(".")
                if pkg == target_pkg and name in target_types:
                    return True
        from codocs.lang.treesitter import mask_c_like

        masked = mask_c_like(test_src)
        return any(f"{target_pkg}.{t}" in masked for t in target_types) if target_pkg else False

    def relevant_tests(self, root: Path, unit: Any, target_rel: str,
                       candidates: set[str]) -> list[str]:
        src = self.read(target_rel, root)
        target_types = set(self.top_level_names(src))
        for d in self.decls(src):
            if d.kind == "type":
                target_types.add(_simple(d.name))
        companions = self._companions(target_rel, src)
        target_pkg = package_of(src)
        index = self.test_index(root, unit)
        visible: dict[str, bool] = {}
        class_idents: dict[str, set[str]] = {}
        lay = self._layout_or_none()
        out = []
        for name in sorted(candidates):
            cls = name.split("#", 1)[0]
            top = cls.split("$", 1)[0]
            if _simple(top) in companions:
                out.append(name)
                continue
            info = index.get(name)
            if info is not None:
                f = info["file"]
                idents = set(info["idents"])
            else:
                f = self._class_file(top, lay) if lay is not None else None
                if f is None:
                    f = next((t for t in unit.test_files
                              if _simple(top) in self.top_level_names(self.read(t, root))),
                             None)
                if f is None:
                    continue
                if f not in class_idents:
                    class_idents[f] = self.identifiers(self.read(f, root))
                idents = class_idents[f]
            if f not in visible:
                visible[f] = self._visible(self.read(f, root), target_pkg, target_types)
            if visible[f] and target_types & idents:
                out.append(name)
        return sorted(out)

