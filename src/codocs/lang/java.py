# -- small helpers ---------------------------------------------------------------------


def _norm(rel: str | None) -> str:
    rel = (rel or "").strip().strip("/")
    while rel.startswith("./"):
        rel = rel[2:]
    if rel in ("", "."):
        return ""
    rel = posixpath.normpath(rel)
    return "" if rel == "." else rel


def _join(a: str, b: str) -> str:
    return _norm(posixpath.join(a, b)) if a else _norm(b)


def _under(rel: str, root: str) -> bool:
    return not root or rel == root or rel.startswith(root + "/")


def _rel_to(rel: str, root: str) -> str:
    if not root:
        return rel
    return "" if rel == root else rel[len(root) + 1:]


def _parent(rel: str) -> str:
    p = posixpath.dirname(rel)
    return "" if p == "." else p


def _collapse(text: str) -> str:
    return " ".join(text.split())


def _parse(src: str):
    from codocs.lang import treesitter as ts

    return ts.parse(src, "java")


def _simple(name: str) -> str:
    return name.rsplit(".", 1)[-1]


def _base_type(text: str) -> str:
    """`java.util.List<String>[]` -> `List` (simple name of the declared type)."""
    t = re.sub(r"<.*>", "", text).replace("[]", "").replace("...", "").strip()
    t = t.split()[-1] if t.split() else t
    return _simple(t)


# -- parsing -----------------------------------------------------------------------------


def package_of(src: str) -> str:
    """the file's package name ("" for the default package)."""
    from codocs.lang.treesitter import mask_c_like

    m = _PKG_RE.search(mask_c_like(src))
    return m.group(1) if m else ""


def _package(p) -> str:
    for c in p.root.children:
        if c.type == "package_declaration":
            for k in c.children:
                if k.type in ("scoped_identifier", "identifier"):
                    return p.node_text(k)
    return ""


def _package_node(p):
    for c in p.root.children:
        if c.type == "package_declaration":
            return c
    return None


def _modifiers(node):
    for c in node.children:
        if c.type == "modifiers":
            return c
    return None


def _annotation_names(p, node) -> list[str]:
    """simple names of the annotations on a declaration."""
    mods = _modifiers(node)
    out = []
    if mods is None:
        return out
    for a in mods.children:
        if a.type in _ANNOTATIONS:
            n = a.child_by_field_name("name")
            if n is not None:
                out.append(_simple(p.node_text(n)))
    return out


def _keyword_mods(p, node) -> list[str]:
    mods = _modifiers(node)
    if mods is None:
        return []
    return [p.node_text(c) for c in mods.children if c.type not in _ANNOTATIONS
            and c.type not in _COMMENTS]


def _members(type_node) -> list:
    body = type_node.child_by_field_name("body")
    if body is None:
        return []
    out = []
    for c in body.children:
        if c.type == "enum_body_declarations":
            out.extend(c.children)
        else:
            out.append(c)
    return out


def _name(p, node) -> str:
    n = node.child_by_field_name("name")
    return p.node_text(n) if n is not None else ""


def _doc_start(p, node) -> int:
    """char offset of the comments right above node (javadoc), else of node itself."""
    start = p.start(node)
    prev = node.prev_sibling
    while prev is not None and prev.type in _COMMENTS:
        gap = p.text[p.end(prev):start]
        if gap.strip() or gap.count("\n") > 1:
            break
        start = p.start(prev)
        prev = prev.prev_sibling
    return start


def _type_signature(p, node) -> str:
    parts: list[str] = []
    for c in node.children:
        t = c.type
        if t == "modifiers":
            parts.extend(_keyword_mods(p, node))
        elif t in ("class", "interface", "enum", "record", "@interface"):
            parts.append(t)
        elif c == node.child_by_field_name("name"):
            parts.append(p.node_text(c))
        elif t in ("type_parameters", "formal_parameters") and parts:
            parts[-1] += _collapse(p.node_text(c))
        elif t in ("superclass", "super_interfaces", "extends_interfaces", "permits"):
            parts.append(p.node_text(c))
        elif t in _BODY_NODES:
            break
    return _collapse(" ".join(parts))


def _method_signature(p, node) -> str:
    parts: list[str] = []
    name = node.child_by_field_name("name")
    for c in node.children:
        t = c.type
        if t == "modifiers":
            parts.extend(_keyword_mods(p, node))
        elif t in ("block", "constructor_body", ";"):
            break
        elif t in _COMMENTS:
            continue
        elif t == "formal_parameters" and parts:
            parts[-1] += _collapse(p.node_text(c))
        elif name is not None and c == name:
            parts.append(p.node_text(c))
        else:
            parts.append(p.node_text(c))
    return _collapse(" ".join(parts))


def _has_body(node) -> bool:
    return node.child_by_field_name("body") is not None


def _decls(p) -> list[Decl]:
    out: list[Decl] = []

    def visit(node, outer: str) -> None:
        simple = _name(p, node)
        if not simple:
            return
        qual = f"{outer}.{simple}" if outer else simple
        out.append(Decl(kind="type", name=qual, receiver=outer, start=_doc_start(p, node),
                        end=p.end(node), line=p.line(node), end_line=p.end_line(node),
                        signature=_type_signature(p, node)))
        for m in _members(node):
            if m.type in TYPE_NODES:
                visit(m, qual)
            elif m.type in _METHOD_NODES and _has_body(m):
                mname = simple if m.type != "method_declaration" else _name(p, m)
                out.append(Decl(kind="method", name=mname, receiver=qual,
                                start=_doc_start(p, m), end=p.end(m), line=p.line(m),
                                end_line=p.end_line(m), signature=_method_signature(p, m)))

    for c in p.root.children:
        if c.type in TYPE_NODES:
            visit(c, "")
    return out


def _top_types(p) -> list:
    return [c for c in p.root.children if c.type in TYPE_NODES]


def _is_test_method(p, node) -> bool:
    return node.type == "method_declaration" and bool(
        TEST_ANNOTATIONS & set(_annotation_names(p, node)))


def _test_methods(p) -> list[tuple[str, Any, Any]]:
    """(runner-level name, method node, class node) of every static test method."""
    pkg = _package(p)
    out: list[tuple[str, Any, Any]] = []

    def visit(cls, binary: str) -> None:
        for m in _members(cls):
            if _is_test_method(p, m):
                out.append((f"{binary}#{_name(p, m)}", m, cls))
            elif m.type == "class_declaration" and "Nested" in _annotation_names(p, m):
                visit(m, f"{binary}${_name(p, m)}")

    for c in _top_types(p):
        if c.type != "class_declaration" or "abstract" in _keyword_mods(p, c):
            continue
        name = _name(p, c)
        visit(c, f"{pkg}.{name}" if pkg else name)
    return out


def _is_main(p, node) -> bool:
    """`static void main(String[] args)` (or String...)."""
    if node.type != "method_declaration" or _name(p, node) != "main":
        return False
    if "static" not in _keyword_mods(p, node):
        return False
    t = node.child_by_field_name("type")
    if t is None or p.node_text(t) != "void":
        return False
    params = node.child_by_field_name("parameters")
    if params is None:
        return False
    ps = [c for c in params.named_children if c.type in ("formal_parameter", "spread_parameter")]
    if len(ps) != 1:
        return False
    text = _collapse(p.node_text(ps[0]))
    return bool(re.match(r"^(?:final\s+)?(?:java\.lang\.)?String\s*(?:\[\s*\]|\.\.\.)", text)
                or re.match(r"^(?:final\s+)?(?:java\.lang\.)?String\s+\w+\s*\[\s*\]", text))


def _cut_spans(text: str, spans: list[tuple[int, int]]) -> str:
    """remove char spans, each widened to its whole lines when only blanks surround it."""
    cuts: list[tuple[int, int]] = []
    for a, b in sorted(spans):
        ls = text.rfind("\n", 0, a) + 1
        if not text[ls:a].strip():
            a = ls
        le = text.find("\n", b)
        le = len(text) if le < 0 else le
        if not text[b:le].strip():
            b = min(le + 1, len(text))
        if cuts and a < cuts[-1][1]:
            cuts[-1] = (cuts[-1][0], max(b, cuts[-1][1]))
        else:
            cuts.append((a, b))
    out, pos = [], 0
    for a, b in cuts:
        out.append(text[pos:a])
        pos = b
    out.append(text[pos:])
    result = "".join(out)
    return re.sub(r"\n{3,}", "\n\n", result)


def _string_names(p) -> set[str]:
    """names declared (params, locals, fields, for-each vars) with a string-like type."""
    from codocs.lang.treesitter import iter_types

    names: set[str] = set()
    kinds = ("formal_parameter", "spread_parameter", "local_variable_declaration",
             "field_declaration", "enhanced_for_statement", "catch_formal_parameter")
    for n in iter_types(p.root, kinds):
        t = n.child_by_field_name("type")
        if t is None:
            continue
        ttext = _collapse(p.node_text(t))
        is_str = ttext in STRING_TYPES
        if n.type in ("local_variable_declaration", "field_declaration"):
            for d in n.children:
                if d.type != "variable_declarator":
                    continue
                nm = d.child_by_field_name("name")
                if nm is None or d.child_by_field_name("dimensions") is not None:
                    continue
                val = d.child_by_field_name("value")
                if is_str or (ttext == "var" and val is not None and _stringy(p, val, names)):
                    names.add(p.node_text(nm))
        else:
            nm = n.child_by_field_name("name")
            if nm is not None and is_str and n.child_by_field_name("dimensions") is None:
                names.add(p.node_text(nm))
    return names


def _string_methods(p) -> set[str]:
    """names of the methods a file declares with a string return type."""
    from codocs.lang.treesitter import iter_types

    out: set[str] = set()
    for m in iter_types(p.root, ("method_declaration",)):
        ty, nm = m.child_by_field_name("type"), m.child_by_field_name("name")
        if ty is not None and nm is not None and m.child_by_field_name("dimensions") is None \
                and _collapse(p.node_text(ty)) in STRING_TYPES:
            out.add(p.node_text(nm))
    return out


def _stringy(p, node, names: set[str], methods: frozenset[str] | set[str] = frozenset()
             ) -> bool:
    """whether an expression is (statically) a String; methods: names of methods declared
    to return a string type (this file or the repository)."""
    t = node.type
    if t == "string_literal":
        return True
    if t == "identifier":
        return p.node_text(node) in names
    if t == "field_access":
        f = node.child_by_field_name("field")
        return f is not None and p.node_text(f) in names
    if t == "parenthesized_expression":
        return any(_stringy(p, c, names, methods) for c in node.named_children)
    if t == "binary_expression":
        op = node.child_by_field_name("operator")
        if op is not None and op.type == "+":
            return any(_stringy(p, node.child_by_field_name(k), names, methods)
                       for k in ("left", "right") if node.child_by_field_name(k) is not None)
        return False
    if t == "method_invocation":
        n = node.child_by_field_name("name")
        return n is not None and (p.node_text(n) in _STRING_METHODS or
                                  p.node_text(n) in methods)
    if t == "ternary_expression":
        return any(_stringy(p, node.child_by_field_name(k), names, methods)
                   for k in ("consequence", "alternative")
                   if node.child_by_field_name(k) is not None)
    if t == "cast_expression":
        ty = node.child_by_field_name("type")
        return ty is not None and _collapse(p.node_text(ty)) in STRING_TYPES
    return False


def _bodies(p) -> list:
    """method/constructor/initializer bodies (outermost only), incl. enum-constant bodies."""
    out: list = []

    def visit_type(node) -> None:
        body = node.child_by_field_name("body")
        if body is None:
            return
        for m in _members(node):
            if m.type in TYPE_NODES:
                visit_type(m)
            elif m.type in _METHOD_NODES:
                b = m.child_by_field_name("body")
                if b is not None:
                    out.append(b)
            elif m.type == "static_initializer":
                out.extend(c for c in m.children if c.type == "block")
            elif m.type == "block":
                out.append(m)
            elif m.type == "enum_constant":
                cb = m.child_by_field_name("body")
                if cb is not None:
                    for k in cb.children:
                        if k.type in _METHOD_NODES and k.child_by_field_name("body") is not None:
                            out.append(k.child_by_field_name("body"))
                        elif k.type == "block":
                            out.append(k)

    for c in _top_types(p):
        visit_type(c)
    return out


