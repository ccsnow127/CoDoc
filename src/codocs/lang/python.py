def _type_text(s: _Src, node) -> str:
    return s.text(node).replace(" ", "") if node is not None else ""


def _string_names(s: _Src, scope) -> set[str]:
    """names bound to string/sequence literals (or annotated so) directly in a scope."""
    from codocs.lang import treesitter as ts

    names: set[str] = set()
    if scope is None:
        return names
    prune = ("function_definition", "class_definition", "lambda")
    for node in ts.iter_types(scope, ("assignment", "typed_parameter",
                                      "typed_default_parameter"), prune=prune):
        if node.type == "assignment":
            typ = node.child_by_field_name("type")
            val = _assign_value(node)
            if _type_text(s, typ).startswith(_STR_TYPES) or (
                    val is not None and _literal_stringish(s, val)):
                names.update(s.text(i) for i in _assigned(node))
        else:
            typ = node.child_by_field_name("type")
            ident = next((c for c in node.named_children if c.type == "identifier"), None)
            if ident is not None and _type_text(s, typ).startswith(_STR_TYPES):
                names.add(s.text(ident))
    return names


def _literal_stringish(s: _Src, node) -> bool:
    while node is not None and node.type == "parenthesized_expression":
        node = node.named_children[0] if node.named_children else None
    if node is None:
        return False
    if node.type in _STRINGISH:
        return True
    if node.type == "call":
        fn = node.child_by_field_name("function")
        if fn is not None and fn.type == "identifier" and s.text(fn) in _STR_FUNCS:
            return True
        if fn is not None and fn.type == "attribute":
            attr = fn.child_by_field_name("attribute")
            return attr is not None and s.text(attr) in _STR_METHODS
        return False
    if node.type == "binary_operator":
        op = node.child_by_field_name("operator")
        if op is not None and op.type in ("+", "%"):
            return (_literal_stringish(s, node.child_by_field_name("left"))
                    or _literal_stringish(s, node.child_by_field_name("right")))
    return False


def _stringish(s: _Src, node, names: set[str]) -> bool:
    while node is not None and node.type == "parenthesized_expression":
        node = node.named_children[0] if node.named_children else None
    if node is None:
        return False
    if node.type == "identifier":
        return s.text(node) in names
    if node.type == "binary_operator":
        op = node.child_by_field_name("operator")
        if op is not None and op.type == "+":
            return (_stringish(s, node.child_by_field_name("left"), names)
                    or _stringish(s, node.child_by_field_name("right"), names))
    return _literal_stringish(s, node)


def py_mutation_sites(src: str) -> list[Mutant]:
    """mutable operators inside def bodies only."""
    from codocs.lang import treesitter as ts

    if not src.strip():
        return []
    s = _Src(src)
    errors = ts.error_spans(s.p)
    module_names = _string_names(s, s.p.root)
    scope_names: dict[int, set[str]] = {}
    out: list[Mutant] = []

    def names_for(func) -> set[str]:
        key = func.id
        if key not in scope_names:
            local = _string_names(s, _body(func))
            params = func.child_by_field_name("parameters")
            if params is not None:
                local |= _string_names(s, params)
            scope_names[key] = local | module_names
        return scope_names[key]

    def add(op, cat: str, repl: str) -> None:
        a = s.start(op)
        if ts.in_spans(a, errors):
            return
        orig = s.text(op)
        out.append(Mutant(id=f"m{a}", offset=a, line=s.line(op),
                          operator=f"{cat}: {orig} -> {repl}", original=orig, replacement=repl))

    stack: list[tuple[Any, bool, Any]] = [(s.p.root, False, None)]
    while stack:
        node, in_body, func = stack.pop()
        t = node.type
        if t in _PRUNE_MUT or node.is_error:
            continue
        if in_body:
            if t == "comparison_operator":
                for op in node.children_by_field_name("operators"):
                    key = _WS_RE.sub(" ", s.text(op))
                    if key in _CMP:
                        add(op, "cmp", _CMP[key])
            elif t == "boolean_operator":
                op = node.child_by_field_name("operator")
                if op is not None and op.type in _LOGIC:
                    add(op, "logic", _LOGIC[op.type])
            elif t == "binary_operator":
                op = node.child_by_field_name("operator")
                if op is not None and op.type in _ARITH:
                    if not (op.type == "+" and (
                            _stringish(s, node.child_by_field_name("left"), names_for(func))
                            or _stringish(s, node.child_by_field_name("right"),
                                          names_for(func)))):
                        add(op, "arith", _ARITH[op.type])
            elif t == "augmented_assignment":
                op = node.child_by_field_name("operator")
                if op is not None and op.type in _ASSIGN:
                    if not (op.type == "+=" and (
                            _stringish(s, node.child_by_field_name("left"), names_for(func))
                            or _stringish(s, node.child_by_field_name("right"),
                                          names_for(func)))):
                        add(op, "assign", _ASSIGN[op.type])
            elif t in ("true", "false"):
                text = s.text(node)
                if text in _BOOLS:
                    add(node, "bool", _BOOLS[text])
        kids = node.children
        if t == "function_definition":
            items = []
            for i, c in enumerate(kids):
                field_name = node.field_name_for_child(i)
                if field_name == "body":
                    items.append((c, True, node))
                elif field_name not in ("parameters", "return_type", "name"):
                    items.append((c, in_body, func))
            stack.extend(reversed(items))
            continue
        if t == "lambda":
            items = []
            for i, c in enumerate(kids):
                if node.field_name_for_child(i) == "parameters":
                    continue
                items.append((c, in_body, func))
            stack.extend(reversed(items))
            continue
        stack.extend((c, in_body, func) for c in reversed(kids))
    out.sort(key=lambda m: m.offset)
    return out


