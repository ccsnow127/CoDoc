    def fix_imports(self, src: str, build_errors: list[str], file_basename: str,
                    allowed: list) -> str | None:
        """add allowed imports for NameErrors; drop imports of missing modules/names."""
        present = py_imports(src)
        bound = {i.bound for i in present}
        add: list[ImportSpec] = []
        drop_mods: set[str] = set()
        drop_names: set[tuple[str, str]] = set()
        for line in build_errors:
            mm = _ERR_LINE_RE.match(line.strip())
            if not mm or PurePosixPath(mm.group("path")).name != file_basename:
                continue
            msg = mm.group("msg")
            n = _NAME_ERR_RE.search(msg)
            if n:
                name = n.group(1)
                if name in bound:
                    continue
                spec = next((a for a in allowed if isinstance(a, ImportSpec) and
                             a.bound == name), None)
                if spec is not None:
                    add.append(spec)
                    bound.add(name)
                continue
            n = _NO_MODULE_RE.search(msg)
            if n:
                drop_mods.add(n.group(1))
                continue
            n = _CANNOT_IMPORT_RE.search(msg)
            if n:
                drop_names.add((n.group(2), n.group(1)))
        if not (add or drop_mods or drop_names):
            return None

        def dropped(spec: ImportSpec) -> bool:
            if (spec.module, spec.name) in drop_names:
                return True
            full = f"{spec.module}.{spec.name}" if spec.kind == "from" else spec.module
            for mod in drop_mods:
                if spec.module == mod or spec.module.startswith(mod + ".") or full == mod:
                    return True
            return False

        out = src
        if drop_mods or drop_names:
            s = _Src(src)
            edits: list[tuple[int, int, str]] = []
            for st in s.p.root.named_children:
                if st.type not in ("import_statement", "import_from_statement"):
                    continue
                specs = py_imports(s.text(st))
                keep = [sp for sp in specs if not dropped(sp)]
                if len(keep) == len(specs):
                    continue
                a, b = s.line_start(s.start(st)), s.line_end(max(s.start(st), s.end(st) - 1))
                if not keep:
                    edits.append((a, b, ""))
                elif keep[0].kind == "from":
                    names = ", ".join(sp.name + (f" as {sp.alias}" if sp.alias else "")
                                      for sp in keep)
                    edits.append((a, b, f"from {keep[0].module} import {names}\n"))
                else:
                    names = ", ".join(sp.module + (f" as {sp.alias}" if sp.alias else "")
                                      for sp in keep)
                    edits.append((a, b, f"import {names}\n"))
            for a, b, text in sorted(edits, reverse=True):
                out = out[:a] + text + out[b:]
        if add:
            text = "".join(format_import(sp) + "\n" for sp in add)
            s = _Src(out) if out.strip() else None
            pos = 0
            if s is not None:
                sts = _statements(s.p.root)
                last = None
                for st in sts:
                    if st.type in ("import_statement", "import_from_statement",
                                   "future_import_statement"):
                        last = st
                    elif last is not None or not _is_docstring(st):
                        break
                    else:
                        last = st
                if last is not None:
                    pos = s.line_end(max(s.start(last), s.end(last) - 1))
            out = out[:pos] + text + out[pos:]
        return out if out != src else None

    def runtime_import_errors(self, res: Any, rel: str) -> list[str]:
        """`rel:line: NameError: ...` lines for NameErrors raised in a frame of rel by failing
        tests: a missing import used only inside a function fails at run time, not at import,
        and fix_imports repairs it the same way."""
        out: list[str] = []
        tests = getattr(res, "tests", None) or {}
        for tid, text in (getattr(res, "output", None) or {}).items():
            if tests.get(tid) != "fail" or "NameError" not in (text or ""):
                continue
            name = ""
            for ln in text.splitlines():
                m = _E_NAME_ERR_RE.match(ln)
                if m:
                    name = m.group(1)
                    continue
                m = _TB_LOC_RE.match(ln.strip())
                if m and name:
                    if m.group("exc") == "NameError" and _same_file(m.group("path"), rel):
                        out.append(f"{rel}:{m.group('line')}: NameError: name '{name}' is not "
                                   "defined")
                    name = ""
        return list(dict.fromkeys(out))

    def broken_mutant(self, mutated: str, res: Any) -> str:
        """a mutant whose test run failed to build: 'invalid' only when it does not parse; a
        mutant that raises while its module is imported is detected by every test ('killed')."""
        try:
            bad = _parse(mutated).root.has_error
        except Exception:
            bad = True
        errors = " ".join(getattr(res, "build_errors", None) or [])
        if bad or _NO_BUILD_RE.search(errors):
            return "invalid"
        return "killed"

    def fix_allowed(self, source_imports: list) -> list:
        out = list(source_imports)
        have = {i.module for i in out if isinstance(i, ImportSpec) and i.kind == "import"}
        out += [ImportSpec(module=m, kind="import", text=f"import {m}") for m in FIX_STD
                if m not in have]
        return out

    def _absolute(self, rel: str, spec: ImportSpec) -> ImportSpec | None:
        if not spec.module.startswith("."):
            return spec
        mod = self.module_name(rel)
        parts = mod.split(".")
        if PurePosixPath(rel).name != "__init__.py":
            parts = parts[:-1]
        dots = len(spec.module) - len(spec.module.lstrip("."))
        if dots - 1 > len(parts):
            return None
        base = parts[: len(parts) - (dots - 1)]
        rest = spec.module[dots:]
        module = ".".join(base + ([rest] if rest else []))
        if not module:
            return None
        return ImportSpec(module=module, name=spec.name, alias=spec.alias, line=spec.line,
                          text="", kind=spec.kind)

    def default_allowed(self, runner: Any, unit: Any) -> list:
        """the unit's imports (made absolute), its modules' public names, pytest, stdlib."""
        root = getattr(runner, "module_root", None)
        out: list[ImportSpec] = []
        seen: set[tuple] = set()

        def add(spec: ImportSpec | None) -> None:
            if spec is None or spec.module == "__future__" or spec.name == "*":
                return
            key = (spec.module, spec.name, spec.alias, spec.kind)
            if key not in seen:
                seen.add(key)
                out.append(spec)

        files = [f for f in unit.files if PurePosixPath(f).name != "conftest.py"]
        for f in files:
            for spec in py_imports(self.read(f, root)):
                add(self._absolute(f, spec))
        add(ImportSpec(module="pytest", kind="import", text="import pytest"))
        for m in FIX_STD:
            add(ImportSpec(module=m, kind="import", text=f"import {m}"))
        for f in files:
            mod = self.module_name(f)
            if not mod:
                continue
            add(ImportSpec(module=mod, kind="import", text=f"import {mod}"))
            for d in py_decls(self.read(f, root)):
                if d.kind != "method" and "." not in d.name and not d.name.startswith("_"):
                    add(ImportSpec(module=mod, name=d.name, kind="from",
                                   text=f"from {mod} import {d.name}"))
        return out

    def failure_message(self, output: str) -> str:
        """the exception line of a pytest failure, then its output without separators."""
        lines = [ln.rstrip() for ln in output.splitlines()]
        kept = [ln for ln in lines if ln.strip() and not re.fullmatch(r"[_=\-]{3,}.*[_=\-]{3,}",
                                                                      ln.strip())]
        body = "\n".join(kept).strip()
        summary = ""
        for ln in kept:
            m = re.match(r"^E\s+(.*)$", ln)
            if m and re.match(r"[\w.]+(Error|Exception|Exit|Failed)\b", m.group(1)):
                summary = m.group(1).strip()
                break
        if not summary:
            for ln in kept:
                m = re.match(r"^E\s+(.*)$", ln)
                if m and m.group(1).strip():
                    summary = m.group(1).strip()
                    break
        first = body.splitlines()[0].strip() if body else ""
        if not summary or summary == first:
            text = body or "test failed"
        else:
            text = summary + ("\n" + body if body else "")
        return text if len(text) <= 2000 else text[:2000] + "\n..."

    def crash_message(self, res: Any) -> str:
        for ln in reversed((res.tail or "").splitlines()):
            if ln.strip().startswith("Timeout ("):
                return f"did not run: the test process timed out ({ln.strip()[:200]})"
        for ln in reversed((res.tail or "").splitlines()):
            s = ln.strip()
            if s.startswith("Timeout (") or "timed out" in s:
                return f"did not run: the test process timed out ({s[:200]})"
            if "Fatal Python error" in s or "Segmentation fault" in s:
                return f"did not run: the test process crashed ({s[:200]})"
        return super().crash_message(res)

