def _toml(path: Path) -> dict:
    try:
        import tomllib  # type: ignore[import-not-found]
    except ImportError:  # pragma: no cover - python < 3.11
        try:
            import tomli as tomllib  # type: ignore[import-not-found,no-redef]
        except ImportError:
            return {}
    try:
        return tomllib.loads(path.read_text(encoding="utf-8", errors="replace"))
    except (OSError, ValueError):
        return {}


def _ini(path: Path) -> configparser.ConfigParser | None:
    cp = configparser.ConfigParser(interpolation=None)
    try:
        cp.read_string(path.read_text(encoding="utf-8", errors="replace"))
    except (OSError, configparser.Error):
        return None
    return cp


def _words(value: Any) -> list[str]:
    if value is None:
        return []
    if isinstance(value, (list, tuple)):
        return [str(v) for v in value]
    return str(value).split()


def _lines(value: Any) -> list[str]:
    if value is None:
        return []
    if isinstance(value, (list, tuple)):
        return [str(v) for v in value]
    return [ln.strip() for ln in str(value).splitlines() if ln.strip()]


def _dist_name(spec: str) -> str:
    m = _REQ_RE.match(spec)
    return m.group(1).lower().replace("-", "_") if m else ""


def read_project_config(root: Path, rel: str, names: list[str]) -> dict:
    """pytest options, src-layout roots and declared dependencies of a project root dir."""
    base = root / rel if rel else root
    cfg: dict = {"pytest_config": "", "ini": {}, "src_roots": [], "deps": [], "scripts": []}
    pyproject = _toml(base / "pyproject.toml") if "pyproject.toml" in names else {}
    setup_cfg = _ini(base / "setup.cfg") if "setup.cfg" in names else None

    def join(name: str) -> str:
        return f"{rel}/{name}" if rel else name

    # pytest configuration, pytest's own precedence
    for name in ("pytest.ini", ".pytest.ini"):
        if name in names:
            cp = _ini(base / name)
            cfg["pytest_config"] = join(name)
            if cp is not None and cp.has_section("pytest"):
                cfg["ini"] = dict(cp.items("pytest"))
            break
    else:
        opts = pyproject.get("tool", {}).get("pytest", {}).get("ini_options")
        if isinstance(opts, dict):
            cfg["pytest_config"], cfg["ini"] = join("pyproject.toml"), dict(opts)
        else:
            tox = _ini(base / "tox.ini") if "tox.ini" in names else None
            if tox is not None and tox.has_section("pytest"):
                cfg["pytest_config"], cfg["ini"] = join("tox.ini"), dict(tox.items("pytest"))
            elif setup_cfg is not None and setup_cfg.has_section("tool:pytest"):
                cfg["pytest_config"] = join("setup.cfg")
                cfg["ini"] = dict(setup_cfg.items("tool:pytest"))

    # explicit src-layout configuration
    roots: list[str] = []
    tool = pyproject.get("tool", {}) if isinstance(pyproject.get("tool"), dict) else {}
    st = tool.get("setuptools", {}) if isinstance(tool.get("setuptools"), dict) else {}
    pdir = st.get("package-dir")
    if isinstance(pdir, dict) and isinstance(pdir.get(""), str):
        roots.append(pdir[""])
    find = st.get("packages", {})
    if isinstance(find, dict) and isinstance(find.get("find"), dict):
        roots.extend(_words(find["find"].get("where")))
    if setup_cfg is not None and setup_cfg.has_option("options", "package_dir"):
        for ln in _lines(setup_cfg.get("options", "package_dir")):
            key, sep, val = ln.partition("=")
            if sep and not key.strip():
                roots.append(val.strip())
    poetry = tool.get("poetry", {}) if isinstance(tool.get("poetry"), dict) else {}
    for p in poetry.get("packages", []) or []:
        if isinstance(p, dict) and p.get("from"):
            roots.append(str(p["from"]))
    hatch = tool.get("hatch", {}).get("build", {}).get("targets", {}).get("wheel", {}) \
        if isinstance(tool.get("hatch"), dict) else {}
    for p in (hatch.get("packages", []) if isinstance(hatch, dict) else []) or []:
        if isinstance(p, str) and p.startswith("src/"):
            roots.append("src")
    cfg["src_roots"] = [r.strip().strip("/") for r in roots if r and r.strip().strip("/")]

    # declared dependencies
    deps: list[str] = []
    project = pyproject.get("project", {}) if isinstance(pyproject.get("project"), dict) else {}
    deps.extend(_lines(project.get("dependencies")))
    for group in (project.get("optional-dependencies") or {}).values():
        deps.extend(_lines(group))
    for group in (pyproject.get("dependency-groups") or {}).values():
        deps.extend(g for g in _lines(group) if isinstance(g, str))
    for key in ("dependencies", "dev-dependencies"):
        deps.extend(k for k in (poetry.get(key) or {}) if k.lower() != "python")
    for group in (poetry.get("group") or {}).values():
        if isinstance(group, dict):
            deps.extend(k for k in (group.get("dependencies") or {}) if k.lower() != "python")
    if setup_cfg is not None:
        if setup_cfg.has_option("options", "install_requires"):
            deps.extend(_lines(setup_cfg.get("options", "install_requires")))
        if setup_cfg.has_section("options.extras_require"):
            for _, v in setup_cfg.items("options.extras_require"):
                deps.extend(_lines(v))
    cfg["deps"] = deps
    scripts = project.get("scripts") or {}
    cfg["scripts"] = [str(v) for v in scripts.values()] if isinstance(scripts, dict) else []
    cfg["scripts"] += [str(v) for v in (poetry.get("scripts") or {}).values()
                       if isinstance(v, str)]
    return cfg


def _parent(rel: str) -> str:
    p = PurePosixPath(rel).parent.as_posix()
    return "" if p == "." else p


def _join(d: str, name: str) -> str:
    return f"{d}/{name}" if d else name


def _under(rel: str, root: str) -> bool:
    return not root or rel == root or rel.startswith(root + "/")


def _relto(rel: str, root: str) -> str:
    if not root:
        return rel
    return "" if rel == root else rel[len(root) + 1:]


def _ancestors(d: str) -> list[str]:
    """d, its parent, ..., "" (the repo root)."""
    out = [d]
    while d:
        d = _parent(d)
        out.append(d)
    return out


def _common(paths: list[str]) -> str:
    parts = [p.split("/") if p else [] for p in paths]
    if not parts:
        return ""
    out: list[str] = []
    for segs in zip(*parts):
        if all(s == segs[0] for s in segs):
            out.append(segs[0])
        else:
            break
    return "/".join(out)


