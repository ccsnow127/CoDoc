# -- tree-sitter helpers ---------------------------------------------------------------


def _parse(src: str):
    from codocs.lang import treesitter as ts

    return ts.parse(src, "python")


def _unwrap(node):
    """the expression of an expression_statement (older grammars wrap statements in one)."""
    if node is not None and node.type == "expression_statement" and node.named_child_count == 1:
        return node.named_children[0]
    return node


def _definition(node):
    """(def/class node, outer node) of a statement, unwrapping decorated_definition."""
    if node.type == "decorated_definition":
        d = node.child_by_field_name("definition")
        return d, node
    if node.type in ("function_definition", "class_definition"):
        return node, node
    return None, node


def _decorators(outer) -> list:
    if outer.type != "decorated_definition":
        return []
    return [c for c in outer.children if c.type == "decorator"]


def _name(node) -> str:
    n = node.child_by_field_name("name")
    return n.text.decode("utf-8", "surrogateescape") if n is not None else ""


def _body(node):
    return node.child_by_field_name("body")


def _statements(block) -> list:
    """the statements of a block/module (comments excluded), in order."""
    if block is None:
        return []
    return [c for c in block.named_children if c.type != "comment"]


def _is_docstring(node) -> bool:
    node = _unwrap(node)
    return node is not None and node.type in ("string", "concatenated_string")


def _is_main_guard(node) -> bool:
    if node.type != "if_statement":
        return False
    cond = node.child_by_field_name("condition")
    if cond is None or cond.type != "comparison_operator":
        return False
    parts = [c.text.decode("utf-8", "replace") for c in cond.named_children]
    return "__name__" in parts and any(p.strip("'\"") == "__main__" for p in parts if p[:1] in "'\"")


class _Src:
    """a parsed module with cached helpers (comment spans, line offsets)."""

    def __init__(self, src: str):
        from codocs.lang import treesitter as ts

        self.src = src
        self.p = _parse(src)
        self._comments: list[tuple[int, int]] | None = None
        self._ts = ts
        self._line_starts: list[int] | None = None

    def text(self, node) -> str:
        return self.p.node_text(node)

    def start(self, node) -> int:
        return self.p.start(node)

    def end(self, node) -> int:
        return self.p.end(node)

    def line(self, node) -> int:
        return self.p.line(node)

    @property
    def comments(self) -> list[tuple[int, int]]:
        if self._comments is None:
            self._comments = self._ts.masked_spans(self.p, {"comment"})
        return self._comments

    def clean(self, a: int, b: int) -> str:
        """src[a:b] with comments removed and whitespace collapsed."""
        spans = [(max(x, a) - a, min(y, b) - a) for x, y in self.comments if x < b and y > a]
        text = self._ts.blank(self.src[a:b], spans)
        text = _WS_RE.sub(" ", text).strip()
        text = re.sub(r"([(\[{]) ", r"\1", text)
        return re.sub(r" ([)\]}])", r"\1", text)

    def line_start(self, offset: int) -> int:
        return self.src.rfind("\n", 0, offset) + 1

    def line_end(self, offset: int) -> int:
        """offset just past the newline ending the line of offset (or len(src))."""
        nl = self.src.find("\n", offset)
        return len(self.src) if nl < 0 else nl + 1

    def first_line(self, node) -> str:
        a = self.start(node)
        nl = self.src.find("\n", a)
        return self.src[a: nl if nl >= 0 else len(self.src)].strip()

    def lead_start(self, parent, outer) -> int:
        """start of the contiguous comment lines directly above a statement (else its start)."""
        start = self.start(outer)
        kids = parent.children if parent is not None else []
        try:
            i = next(k for k, c in enumerate(kids) if c.id == outer.id)
        except StopIteration:
            return start
        row = outer.start_point[0]
        j = i - 1
        while j >= 0 and kids[j].type == "comment" and kids[j].end_point[0] == row - 1:
            # a trailing comment of the previous statement's line is not a doc comment
            if j > 0 and kids[j - 1].end_point[0] == kids[j].start_point[0]:
                break
            start = self.start(kids[j])
            row = kids[j].start_point[0]
            j -= 1
        return start

    def header(self, node) -> str:
        """`def f(...) -> T:` / `class C(B):` with comments removed, whitespace collapsed."""
        body = _body(node)
        end = self.start(body) if body is not None else self.end(node)
        head = self.clean(self.start(node), end)
        if not head.endswith(":"):
            k = head.rfind(":")
            head = head[: k + 1] if k >= 0 else head
        return head

    def signature(self, node, outer) -> str:
        decos = [self.clean(self.start(d), self.end(d)) for d in _decorators(outer)]
        return "\n".join(decos + [self.header(node)])


def _target_names(node) -> list:
    """identifier nodes bound by an assignment target (plain names, tuple targets split)."""
    if node is None:
        return []
    if node.type == "identifier":
        return [node]
    if node.type in ("pattern_list", "tuple_pattern", "list_pattern", "expression_list",
                     "tuple", "list", "parenthesized_expression"):
        out = []
        for c in node.named_children:
            out.extend(_target_names(c))
        return out
    return []


def _assigned(node) -> list:
    """identifier nodes a (possibly chained) assignment binds."""
    out = []
    while node is not None and node.type == "assignment":
        out.extend(_target_names(node.child_by_field_name("left")))
        node = node.child_by_field_name("right")
    return out


def _assign_value(node):
    """the right-most value of a chained assignment."""
    while node is not None and node.type == "assignment":
        nxt = node.child_by_field_name("right")
        if nxt is None:
            return None
        node = nxt
    return node


_COMPOUND = frozenset({"if_statement", "try_statement", "with_statement"})
_CLAUSES = frozenset({"elif_clause", "else_clause", "except_clause", "except_group_clause",
                      "finally_clause"})


def _sub_blocks(node) -> list:
    """the blocks of an if/try/with statement, its clauses' blocks included, in order."""
    out = []
    for c in node.named_children:
        if c.type == "block":
            out.append(c)
        elif c.type in _CLAUSES:
            out.extend(_sub_blocks(c))
    return out


def _module_statements(root) -> list[tuple[Any, Any]]:
    """(statement, parent block) at module level, inside module-level if/try/with too.

    the `if __name__ == "__main__":` guard is not descended: its definitions only exist when the
    module runs as a script.
    """
    out: list[tuple[Any, Any]] = []

    def walk(block) -> None:
        for st in block.named_children:
            if st.type == "comment":
                continue
            if st.type in _COMPOUND and not _is_main_guard(st):
                for b in _sub_blocks(st):
                    walk(b)
                continue
            out.append((st, block))

    walk(root)
    return out


def _decl_items(s: _Src) -> list[tuple[Decl, Any, Any]]:
    """(decl, def/assignment node, outer node) for every top-level declaration."""
    out: list[tuple[Decl, Any, Any]] = []

    def add_def(node, outer, parent, receiver: str) -> None:
        name = _name(node)
        if not name:
            return
        start = s.lead_start(parent, outer)
        if node.type == "class_definition":
            qual = f"{receiver}.{name}" if receiver else name
            out.append((Decl(kind="type", name=qual, start=start, end=s.end(outer),
                             line=s.line(node), end_line=s.p.end_line(outer),
                             signature=s.signature(node, outer)), node, outer))
            body = _body(node)
            for st in _statements(body):
                d, o = _definition(st)
                if d is not None:
                    if d.type == "function_definition":
                        mname = _name(d)
                        if mname:
                            out.append((Decl(kind="method", name=mname, receiver=qual,
                                             start=s.lead_start(body, o), end=s.end(o),
                                             line=s.line(d), end_line=s.p.end_line(o),
                                             signature=s.signature(d, o)), d, o))
                    else:
                        add_def(d, o, body, qual)
            return
        out.append((Decl(kind="func", name=name, start=start, end=s.end(outer), line=s.line(node),
                         end_line=s.p.end_line(outer), signature=s.signature(node, outer)),
                    node, outer))

    root = s.p.root
    imported: set[str] | None = None
    cond: set[int] = set()              # out indices added by conditional statements

    def add_stmt(st, parent, nested: bool) -> None:
        nonlocal imported
        d, outer = _definition(st)
        if d is not None:
            add_def(d, outer, parent, "")
            return
        node = _unwrap(st)
        if node is None or node.type != "assignment":
            return
        if nested and imported is None:
            imported = {i.bound for i in py_imports(s.src)}
        start = s.lead_start(parent, st)
        seen: set[str] = set()
        for ident in _assigned(node):
            name = s.text(ident)
            if name in seen or (nested and name in (imported or set())):
                # a conditional fallback for an import (`except ImportError: json = None`)
                continue
            seen.add(name)
            out.append((Decl(kind="var", name=name, start=start, end=s.end(st), line=s.line(st),
                             end_line=s.p.end_line(st), signature=s.first_line(st)), node, st))

    for st, parent in _module_statements(root):
        nested = parent.id != root.id
        k = len(out)
        add_stmt(st, parent, nested)
        if nested:
            cond.update(range(k, len(out)))
    if not cond:
        return out
    # a name defined in several branches (`if win32: def f ... else: def f`) is one decl
    seen_keys = {(d.kind, d.receiver, d.name) for i, (d, _, _) in enumerate(out) if i not in cond}
    kept: list[tuple[Decl, Any, Any]] = []
    for i, item in enumerate(out):
        key = (item[0].kind, item[0].receiver, item[0].name)
        if i in cond:
            if key in seen_keys:
                continue
            seen_keys.add(key)
        kept.append(item)
    return kept


def py_decls(src: str) -> list[Decl]:
    """top-level declarations of a module in source order."""
    if not src.strip():
        return []
    return [d for d, _, _ in _decl_items(_Src(src))]


def _dotted(node) -> str:
    return re.sub(r"\s+", "", node.text.decode("utf-8", "surrogateescape"))


def py_imports(src: str) -> list[ImportSpec]:
    """every import statement of a module (nested ones included), one spec per bound name."""
    from codocs.lang import treesitter as ts

    if not src.strip():
        return []
    s = _Src(src)
    out: list[ImportSpec] = []
    kinds = ("import_statement", "import_from_statement", "future_import_statement")
    for node in ts.iter_types(s.p.root, kinds, prune=("string", "comment")):
        text = s.clean(s.start(node), s.end(node))
        line = s.line(node)
        if node.type == "import_statement":
            for c in node.children_by_field_name("name"):
                if c.type == "aliased_import":
                    mod = c.child_by_field_name("name")
                    alias = c.child_by_field_name("alias")
                    out.append(ImportSpec(module=_dotted(mod), alias=_dotted(alias), line=line,
                                          text=text, kind="import"))
                else:
                    out.append(ImportSpec(module=_dotted(c), line=line, text=text, kind="import"))
            continue
        if node.type == "future_import_statement":
            module = "__future__"
        else:
            m = node.child_by_field_name("module_name")
            module = _dotted(m) if m is not None else ""
        names = node.children_by_field_name("name")
        if any(c.type == "wildcard_import" for c in node.children):
            out.append(ImportSpec(module=module, name="*", line=line, text=text, kind="from"))
        for c in names:
            if c.type == "aliased_import":
                n = c.child_by_field_name("name")
                a = c.child_by_field_name("alias")
                out.append(ImportSpec(module=module, name=_dotted(n), alias=_dotted(a),
                                      line=line, text=text, kind="from"))
            else:
                out.append(ImportSpec(module=module, name=_dotted(c), line=line, text=text,
                                      kind="from"))
    return out


def format_import(imp: ImportSpec) -> str:
    """canonical one-name statement of an import spec."""
    if imp.kind == "from":
        s = f"from {imp.module} import {imp.name}"
    else:
        s = f"import {imp.module}"
    return s + (f" as {imp.alias}" if imp.alias else "")


def _matches(name: str, patterns: list[str] | tuple[str, ...]) -> bool:
    """pytest's python_functions / python_classes rule: prefix, or glob when it has one."""
    for p in patterns:
        if name.startswith(p) or (_GLOB_CHARS & set(p) and fnmatchcase(name, p)):
            return True
    return False


def _base_names(s: _Src, cls) -> list[str]:
    sup = cls.child_by_field_name("superclasses")
    if sup is None:
        return []
    return [s.text(c) for c in sup.named_children if c.type != "keyword_argument"]


def _is_unittest(s: _Src, cls) -> bool:
    return any(b.rsplit(".", 1)[-1] in _UNITTEST_BASES for b in _base_names(s, cls))


def _is_fixture(s: _Src, outer) -> bool:
    """whether a decorated def is a pytest fixture (`@pytest.fixture`, `@fixture(...)`)."""
    for dec in _decorators(outer):
        expr = next((c for c in dec.named_children if c.type != "comment"), None)
        if expr is not None and expr.type == "call":
            expr = expr.child_by_field_name("function")
        if expr is None:
            continue
        text = _WS_RE.sub("", s.text(expr))
        if text == "fixture" or text.endswith(".fixture"):
            return True
    return False


def _alias_of(s: _Src, st) -> tuple[str, str] | None:
    """(name, aliased name) of a plain `name = other` statement."""
    node = _unwrap(st)
    if node is None or node.type != "assignment" or node.child_by_field_name("type") is not None:
        return None
    left, right = node.child_by_field_name("left"), node.child_by_field_name("right")
    if left is None or right is None or left.type != "identifier" or right.type != "identifier":
        return None
    return s.text(left), s.text(right)


class _TestDef:
    """one statically collected test: its local id and the statement that defines it."""

    __slots__ = ("local", "node", "outer", "cls", "func")

    def __init__(self, local: str, node, outer, cls, func: str = ""):
        self.local = local
        self.node = node        # the def node (the assignment of an alias)
        self.outer = outer      # the statement to cut (decorators included)
        self.cls = cls          # the class the test is collected under, None at module level
        self.func = func        # the function an alias names


def _collect_tests(s: _Src, functions=("test",), classes=("Test",)) -> list[_TestDef]:
    """pytest's collection, statically: module functions (in if/try blocks too) and aliases,
    Test* classes with their nested Test* classes and inherited test methods, unittest
    classes; fixtures named test_* are not tests. duplicates (one id per branch) are kept."""
    stmts = _module_statements(s.p.root)
    funcs: dict[str, bool] = {}             # module function -> is a fixture
    class_defs: dict[str, Any] = {}
    for st, _parent in stmts:
        d, outer = _definition(st)
        if d is None:
            continue
        if d.type == "function_definition":
            funcs.setdefault(_name(d), _is_fixture(s, outer))
        else:
            class_defs.setdefault(_name(d), d)

    def is_unit(cls, seen: frozenset) -> bool:
        if _is_unittest(s, cls):
            return True
        for b in _base_names(s, cls):
            base = class_defs.get(b)
            if base is not None and base.id not in seen and is_unit(base, seen | {base.id}):
                return True
        return False

    def members(cls, seen: frozenset) -> list[tuple[str, Any, Any, str]]:
        """(name, node, outer, aliased function) of own then inherited class members."""
        own: list[tuple[str, Any, Any, str]] = []
        for st in _statements(_body(cls)):
            md, mo = _definition(st)
            if md is not None and md.type == "function_definition":
                if not _is_fixture(s, mo):
                    own.append((_name(md), md, mo, ""))
                continue
            al = _alias_of(s, st)
            if al is not None:
                own.append((al[0], st, st, al[1]))
            elif _unwrap(st) is not None and _unwrap(st).type == "assignment" and \
                    s.text(_unwrap(st)).replace(" ", "") == "__test__=False":
                own.append(("__test__", st, st, "False"))
        names = {m[0] for m in own}
        for b in _base_names(s, cls):
            base = class_defs.get(b)
            if base is None or base.id in seen:
                continue
            for m in members(base, seen | {base.id}):
                if m[0] not in names:
                    names.add(m[0])
                    own.append(m)
        return own

    out: list[_TestDef] = []

    def visit_class(cls, prefix: str, top: bool) -> None:
        unit = top and is_unit(cls, frozenset({cls.id}))
        if not unit and not _matches(_name(cls), classes):
            return
        ms = members(cls, frozenset({cls.id}))
        if any(m[0] == "__test__" and m[3] == "False" for m in ms):
            return
        if not unit and any(m[0] == "__init__" for m in ms):
            return
        method_names = {m[0] for m in ms if not m[3]}
        for name, node, outer, alias in ms:
            if name == "__test__" or (alias and alias not in method_names):
                continue
            ok = name.startswith("test") if unit else _matches(name, functions)
            if ok:
                out.append(_TestDef(f"{prefix}::{name}" if prefix else name, node, outer, cls,
                                    alias))
        if unit:
            return
        for st in _statements(_body(cls)):
            d, _o = _definition(st)
            if d is not None and d.type == "class_definition":
                visit_class(d, f"{prefix}::{_name(d)}", False)

    for st, _parent in stmts:
        d, outer = _definition(st)
        if d is None:
            al = _alias_of(s, st)
            if al is not None and al[1] in funcs and not funcs[al[1]] and \
                    _matches(al[0], functions):
                out.append(_TestDef(al[0], st, st, None, al[1]))
            continue
        if d.type == "function_definition":
            if _matches(_name(d), functions) and not _is_fixture(s, outer):
                out.append(_TestDef(_name(d), d, outer, None))
            continue
        visit_class(d, _name(d), True)
    return out


def _test_defs(src: str, functions=("test",), classes=("Test",)) -> list[tuple[str, Any, Any, Any]]:
    """(local id, def node, outer node, class node | None) of the static tests of a module."""
    if not src.strip():
        return []
    seen: set[str] = set()
    out: list[tuple[str, Any, Any, Any]] = []
    for t in _collect_tests(_Src(src), functions, classes):
        if t.local not in seen:
            seen.add(t.local)
            out.append((t.local, t.node, t.outer, t.cls))
    return out


def _removal_edits(s: _Src, doomed: set[int]) -> list[tuple[int, int, str]]:
    """edits deleting the doomed statements; an emptied test class goes too, an emptied
    if/try/with block keeps a `pass`."""
    edits: list[tuple[int, int, str]] = []

    def finish(block, cut: list, kept: list) -> None:
        for i, st in enumerate(cut):
            text = " " * st.start_point[1] + "pass\n" if not kept and i == 0 else ""
            edits.append((s.lead_start(block, st), s.end(st), text))

    def walk(block) -> tuple[list, list]:
        cut, kept = [], []
        for st in _statements(block):
            if st.id in doomed:
                cut.append(st)
                continue
            d, _o = _definition(st)
            if d is not None and d.type == "class_definition":
                body = _body(d)
                c2, k2 = walk(body)
                if c2 and not [k for k in k2 if not (_is_docstring(k) or
                                                     k.type == "pass_statement")]:
                    cut.append(st)
                    continue
                finish(body, c2, k2)
            elif st.type in _COMPOUND:
                for b in _sub_blocks(st):
                    c2, k2 = walk(b)
                    finish(b, c2, k2)
            kept.append(st)
        return cut, kept

    root = s.p.root
    cut, _kept = walk(root)
    edits.extend((s.lead_start(root, st), s.end(st), "") for st in cut)
    return edits


def _same_file(path: str, rel: str) -> bool:
    """whether a traceback path (absolute, or relative to some root) names the repo file rel."""
    path = path.replace("\\", "/")
    return path == rel or path.endswith("/" + rel) or rel.endswith("/" + path)


def _fold(test_id: str) -> str:
    """a pytest id without its parameter part: `f.py::test_x[1-2]` -> `f.py::test_x`."""
    head, sep, tail = test_id.partition("::")
    k = tail.find("[")
    if sep and k >= 0:
        tail = tail[:k]
    return head + sep + tail


def _local(name: str) -> str:
    """the in-file part of a runner-level name (`tests/t.py::C::m` -> `C::m`)."""
    name = _fold(name)
    if "::" in name:
        head, _, rest = name.partition("::")
        if head.endswith((".py", ".pyi")) or "/" in head:
            return rest
    return name


def _cut(s: _Src, spans: list[tuple[int, int]] | list[tuple[int, int, str]]) -> str:
    """the source with whole-line spans removed or replaced by a span's text (overlaps merged;
    extra blank lines folded)."""
    if not spans:
        return s.src
    full = sorted((s.line_start(sp[0]), s.line_end(max(sp[0], sp[1] - 1)),
                   sp[2] if len(sp) > 2 else "") for sp in spans)
    merged: list[list] = []
    for a, b, text in full:
        if merged and a <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], b)
            merged[-1][2] += text
        else:
            merged.append([a, b, text])
    out = s.src
    for a, b, text in reversed(merged):
        out = out[:a] + text + out[b:] if text else _join_cut(out[:a], out[b:])
    return out


def _blank_run(lines: list[str]) -> int:
    n = 0
    for ln in lines:
        if ln.strip():
            break
        n += 1
    return n


def _join_cut(before: str, after: str) -> str:
    """before + after with at most two blank lines where a cut joined them."""
    if not after.strip():
        return before.rstrip() + "\n" if before.strip() else ""
    a_lines = after.split("\n")
    lead = _blank_run(a_lines)
    if not before.strip():
        return "\n".join(a_lines[lead:])
    b_lines = before.split("\n")[:-1]           # before ends with a newline (a line start)
    trail = _blank_run(list(reversed(b_lines)))
    keep = max(0, min(lead, 2 - trail))
    return before + "\n".join(a_lines[lead - keep:])


def _main_guards(s: _Src) -> list:
    return [st for st in s.p.root.named_children if _is_main_guard(st)]


