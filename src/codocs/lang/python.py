class _Model:
    """projects, import roots, module names, units and test association of the repo's Python."""

    def __init__(self, ctx: RepoContext):
        from codocs.lang.registry import scan_files

        self.ctx = ctx
        files = ctx.files.get("python")
        if files is None:
            files = scan_files(ctx.root, None, out_dir=ctx.out_dir)[0].get("python", [])
        self.files: list[str] = sorted(files)
        self.fileset = set(self.files)
        self.dirs = ctx.dirs
        self.markers = {d for d, names in ctx.dirs.items() if any(m in names for m in MARKERS)}
        self.configs: dict[str, dict] = {}
        self._marker_of: dict[str, str | None] = {}
        self._imports: dict[str, list[ImportSpec]] = {}
        self.kind: dict[str, str] = {}             # rel -> source | test | support
        self.units: dict[str, Unit] = {}
        self.project_of_dir: dict[str, str] = {}    # unit dir / test file -> project root
        self.projects: dict[str, dict] = {}
        self.fallback_dirs: dict[str, list[str]] = {}
        self.module_of: dict[str, str] = {}
        self.script_dirs: set[str] = set()
        self.package_roots: dict[str, str] = {}     # unit dir -> import root it is a package of
        self._build()

    # -- configuration ---------------------------------------------------------------

    def marker_of(self, d: str) -> str | None:
        if d not in self._marker_of:
            hit = None
            for a in _ancestors(d):
                if a in self.markers:
                    hit = a
                    break
            self._marker_of[d] = hit
        return self._marker_of[d]

    def config(self, proj: str | None) -> dict:
        if proj is None or proj not in self.markers:
            return {"pytest_config": "", "ini": {}, "src_roots": [], "deps": [], "scripts": []}
        if proj not in self.configs:
            self.configs[proj] = read_project_config(self.ctx.root, proj,
                                                     self.dirs.get(proj, []))
        return self.configs[proj]

    def patterns(self, rel: str) -> tuple[list[str], list[str], list[str]]:
        """(python_files, python_functions, python_classes) for a file's project."""
        ini = self.config(self.marker_of(_parent(rel)))["ini"]
        return (_words(ini.get("python_files")) or list(PY_TEST_PATTERNS),
                _words(ini.get("python_functions")) or ["test"],
                _words(ini.get("python_classes")) or ["Test"])

    def is_test(self, rel: str) -> bool:
        name = PurePosixPath(rel).name
        if name == "conftest.py":
            return False
        if name.startswith("test_") and name.endswith(SUITE_SUFFIX):
            return True
        return any(fnmatchcase(name, g) for g in self.patterns(rel)[0])

    def is_support(self, rel: str) -> bool:
        if PurePosixPath(rel).name == "conftest.py":
            return True
        if self.is_test(rel):
            return False
        d = _parent(rel)
        proj = self.marker_of(d)
        segs = _relto(d, proj).split("/") if proj is not None else d.split("/")
        return any(seg in TEST_DIRS for seg in segs if seg)

    def has_init(self, d: str) -> bool:
        return "__init__.py" in self.dirs.get(d, [])

    def is_dir(self, d: str) -> bool:
        return d in self.dirs

    # -- import roots ------------------------------------------------------------------

    def marker_roots(self, proj: str) -> list[str]:
        cfg = self.config(proj)
        roots: list[str] = []
        for r in cfg["src_roots"]:
            roots.append(_join(proj, r))
        if self.is_dir(_join(proj, "src")):
            roots.append(_join(proj, "src"))
        for r in _words(cfg["ini"].get("pythonpath")):
            r = r.strip().strip("/")
            roots.append(proj if r in ("", ".") else _join(proj, r))
        roots.append(proj)
        out: list[str] = []
        for r in roots:
            r = re.sub(r"/\./|/\.$", "/", r).strip("/")
            if (r == proj or self.is_dir(r)) and r not in out:
                out.append(r)
        return out

    @staticmethod
    def _chain_root(d: str, roots: list[str], has_init) -> str | None:
        """the first root whose __init__.py chain from d reaches it (d != root)."""
        for r in roots:
            if d == r or not _under(d, r):
                continue
            cur, ok = d, True
            while cur != r:
                if not has_init(cur):
                    ok = False
                    break
                cur = _parent(cur)
            if ok:
                return r
        return None

    def basedir(self, rel: str) -> str:
        """the first ancestor-or-self dir of a file without __init__.py (pytest's rootdir rule)."""
        d = _parent(rel)
        while d and self.has_init(d):
            d = _parent(d)
        return d

    def roots_for(self, rel: str) -> list[str]:
        """import roots used to resolve a file's absolute imports."""
        proj = self.project(rel)
        info = self.projects.get(proj)
        roots = list(info["import_roots"]) if info else []
        if self.marker_of(_parent(rel)) is None:
            for a in _ancestors(_parent(rel)):
                for r in (a, _join(a, "src")):
                    if r not in roots and (r == a or self.is_dir(r)):
                        roots.append(r)
        b = self.basedir(rel)
        if b not in roots:
            roots.append(b)
        return roots

    # -- resolution ----------------------------------------------------------------------

    def module_file(self, roots: list[str], dotted: str) -> tuple[str, str] | None:
        """(file rel, root) of a dotted module under the first root that has it."""
        path = dotted.replace(".", "/")
        for r in roots:
            for cand in (_join(r, path + ".py"), _join(r, path + "/__init__.py")):
                if cand in self.fileset:
                    return cand, r
        return None

    def imports_of(self, rel: str) -> list[ImportSpec]:
        if rel not in self._imports:
            self._imports[rel] = py_imports(self.ctx.read(rel))
        return self._imports[rel]

    def third_party(self, rel: str) -> set[str]:
        proj = self.project(rel)
        return set(self.projects.get(proj, {}).get("deps", []))

    def resolve_spec(self, rel: str, spec: ImportSpec, *, fallback: list[str] | None = None
                     ) -> list[tuple[str, bool]]:
        """(file rel, binds a module) pairs an import resolves to inside the repo.

        a `from m import x` that names a submodule gives (that file, True); one that names an
        attribute gives (m's file, False). `fallback` collects dirs added by the unique-basename
        fallback (they act as import roots for that file).
        """
        if spec.kind not in ("import", "from") or spec.module == "__future__":
            return []
        mod = spec.module
        if mod.startswith("."):
            dots = len(mod) - len(mod.lstrip("."))
            base = _parent(rel)
            for _ in range(dots - 1):
                base = _parent(base)
            rest = mod[dots:]
            roots = [base]
            dotted = rest
        else:
            roots = self.roots_for(rel)
            dotted = mod
        out: list[tuple[str, bool]] = []
        if spec.kind == "from" and spec.name and spec.name != "*":
            sub = f"{dotted}.{spec.name}" if dotted else spec.name
            hit = self.module_file(roots, sub)
            if hit:
                return [(hit[0], True)]
        if dotted:
            hit = self.module_file(roots, dotted)
        else:
            init = _join(roots[0], "__init__.py")
            hit = (init, roots[0]) if init in self.fileset else None
        if hit:
            out.append((hit[0], spec.kind == "import"))
            return out
        if mod.startswith("."):
            return out
        top = dotted.split(".", 1)[0]
        if top in getattr(sys, "stdlib_module_names", ()) or top in self.third_party(rel):
            return out
        fb = self.ctx.py_modules.get(f"basename:{top}")
        if not fb:
            return out
        froot = _parent(fb) if not fb.endswith("/__init__.py") else _parent(_parent(fb))
        if fallback is not None and froot not in fallback:
            fallback.append(froot)
        if spec.kind == "from" and spec.name and spec.name != "*":
            hit = self.module_file([froot], f"{dotted}.{spec.name}")
            if hit:
                return [(hit[0], True)]
        hit = self.module_file([froot], dotted)
        if hit:
            out.append((hit[0], spec.kind == "import"))
        return out

    def resolve_files(self, rel: str, specs: list, *, fallback: list[str] | None = None
                      ) -> list[str]:
        out: list[str] = []
        for spec in specs:
            if not isinstance(spec, ImportSpec):
                continue
            for f, _ in self.resolve_spec(rel, spec, fallback=fallback):
                if f not in out:
                    out.append(f)
        return out

    def reexport(self, init_rel: str, name: str, depth: int = 0) -> tuple[str, str] | None:
        """(defining file, its name) of a name a package __init__.py re-exports
        (`from .core.models import Item`), followed through nested __init__ files."""
        if depth > 6 or not init_rel.endswith("__init__.py"):
            return None
        specs = self.imports_of(init_rel)
        for spec in specs:
            if spec.kind != "from" or spec.name == "*" or spec.bound != name:
                continue
            for f, is_module in self.resolve_spec(init_rel, spec):
                if is_module or f == init_rel:
                    return (f, "") if is_module else None
                if f.endswith("__init__.py"):
                    return self.reexport(f, spec.name, depth + 1) or (f, spec.name)
                return f, spec.name
        for spec in specs:
            if spec.kind != "from" or spec.name != "*":
                continue
            for f, _ in self.resolve_spec(init_rel, spec):
                if f == init_rel:
                    continue
                if f.endswith("__init__.py"):
                    hit = self.reexport(f, name, depth + 1)
                    if hit:
                        return hit
                if any(d.name == name for d in py_decls(self.ctx.read(f))
                       if d.kind != "method"):
                    return f, name
        return None

    def test_targets(self, rel: str, fallback: list[str] | None = None) -> list[str]:
        """repo files a test (or conftest) file's imports reach, re-exports followed."""
        out: list[str] = []
        for spec in self.imports_of(rel):
            for f, is_module in self.resolve_spec(rel, spec, fallback=fallback):
                if f not in out:
                    out.append(f)
                if f.endswith("__init__.py") and spec.kind == "from" and not is_module \
                        and spec.name != "*":
                    hit = self.reexport(f, spec.name)
                    if hit and hit[0] not in out:
                        out.append(hit[0])
        return out

    def conftest_chain(self, rel: str) -> list[str]:
        """the conftest.py files pytest loads for a test file (inside its project)."""
        proj = self.marker_of(_parent(rel)) or ""
        out = []
        for a in reversed(_ancestors(_parent(rel))):
            c = _join(a, "conftest.py")
            if _under(a, proj) and c in self.fileset and c != rel:
                out.append(c)
        return out

    def unit_dir_of(self, rel: str) -> str | None:
        d = _parent(rel)
        return d if d in self.units and rel in self.units[d].files else None

    def project(self, rel: str) -> str:
        """project root of a file (marker project, else the association-derived one)."""
        m = self.marker_of(_parent(rel))
        if m is not None:
            return m
        if rel in self.project_of_dir:
            return self.project_of_dir[rel]
        d = _parent(rel)
        if d in self.project_of_dir:
            return self.project_of_dir[d]
        return d

    # -- build -----------------------------------------------------------------------------

    def _build(self) -> None:
        for rel in self.files:
            if PurePosixPath(rel).name == "setup.py" and _parent(rel) in self.markers:
                self.kind[rel] = "config"
                continue
            self.kind[rel] = ("support" if self.is_support(rel) else
                              "test" if self.is_test(rel) else "source")
        sources: dict[str, list[str]] = {}
        support: dict[str, list[str]] = {}
        for rel, k in self.kind.items():
            if k == "source":
                sources.setdefault(_parent(rel), []).append(rel)
            elif k == "support" and PurePosixPath(rel).name == "conftest.py":
                support.setdefault(_parent(rel), []).append(rel)
        # unique-basename fallback index and dotted module names (filled below)
        counts: dict[str, list[str]] = {}
        for rel in self.files:
            if self.kind[rel] != "source":
                continue
            p = PurePosixPath(rel)
            name = p.parent.name if p.name == "__init__.py" else p.stem
            if name:
                counts.setdefault(name, []).append(rel)
        for name, rels in counts.items():
            if len(rels) == 1:
                self.ctx.py_modules[f"basename:{name}"] = rels[0]

        # marker projects: import roots now
        for proj in sorted({self.marker_of(d) for d in sources} - {None}):
            cfg = self.config(proj)
            self.projects[proj] = {
                "import_roots": self.marker_roots(proj), "pytest_config": cfg["pytest_config"],
                "pytest_addopts": cfg["ini"].get("addopts"),
                "python_files": _words(cfg["ini"].get("python_files")) or list(PY_TEST_PATTERNS),
                "python_functions": _words(cfg["ini"].get("python_functions")) or ["test"],
                "python_classes": _words(cfg["ini"].get("python_classes")) or ["Test"],
                "marker": True, "deps": self._deps(proj, cfg),
                "scripts": cfg["scripts"],
            }
        for d in sources:
            proj = self.marker_of(d)
            if proj is not None:
                self._place(d, self.projects[proj]["import_roots"])
            else:
                self._place_loose(d)

        # units with their own-dir tests first, then association
        tests = [r for r in self.files if self.kind[r] == "test"]
        assoc: dict[str, set[str]] = {d: set() for d in sources}
        refs: dict[str, set[str]] = {}
        def reached(files: list[str]) -> set[str]:
            out: set[str] = set()
            for f in files:
                d = _parent(f)
                if d in sources and f in sources[d]:
                    out.add(d)
                elif f.endswith("__init__.py") and d in sources:
                    out.add(d)
            return out

        for t in tests:
            fb: list[str] = []
            hit = reached(self.test_targets(t, fallback=fb))
            if _parent(t) in sources:
                hit.add(_parent(t))
            if not hit:
                # a test using only conftest fixtures belongs where its conftests' imports go
                for c in self.conftest_chain(t):
                    hit |= reached(self.test_targets(c, fallback=fb))
            tm = self.marker_of(_parent(t))
            kept: set[str] = set()
            for d in hit:
                um = self.marker_of(d)
                if um is not None and not _under(t, um):
                    continue
                if um is None and tm is not None and _parent(t) != d:
                    # a marker project's test only reaches loose code through the fallback
                    if not fb:
                        continue
                kept.add(d)
            for d in kept:
                assoc[d].add(t)
            refs[t] = kept
            self.fallback_dirs[t] = fb

        # loose projects: common ancestors, nested ones merged into the outer
        loose = [d for d in sources if self.marker_of(d) is None]
        cand: dict[str, str] = {}
        for d in loose:
            cand[d] = _common([d] + [_parent(t) for t in assoc[d]])
        for t, ds in refs.items():
            lds = [d for d in ds if d in cand]
            if lds and self.marker_of(_parent(t)) is None:
                cand[t] = _common([_parent(t)] + lds)
        roots = sorted(set(cand.values()), key=lambda r: (r.count("/") if r else -1, r))
        outer: dict[str, str] = {}
        for r in roots:
            outer[r] = next((o for o in roots if _under(r, o)), r)
        for key, r in cand.items():
            self.project_of_dir[key] = outer[r]
        for proj in sorted(set(outer.values())):
            members = [d for d in loose if self.project_of_dir.get(d) == proj]
            iroots: list[str] = []
            if self.is_dir(_join(proj, "src")):
                iroots.append(_join(proj, "src"))
            iroots.append(proj)
            for d in members:
                pr = self.package_roots.get(d)
                if pr is not None and pr not in iroots and _under(pr, proj):
                    iroots.append(pr)
            for d in members:
                if d in self.script_dirs and d not in iroots:
                    iroots.append(d)
            cfg = self.config(None)
            self.projects[proj] = {
                "import_roots": iroots, "pytest_config": "",
                "python_files": list(PY_TEST_PATTERNS), "python_functions": ["test"],
                "python_classes": ["Test"], "marker": False, "deps": self._deps(proj, cfg),
                "scripts": [],
            }
        for proj, info in self.projects.items():
            self.ctx.py_projects[proj] = {k: v for k, v in info.items()}

        for d in sorted(sources):
            proj = self.project(_join(d, "x.py"))
            info = self.projects[proj]
            ipath = self._package_name(d)
            own = [d] if d in self.script_dirs else []
            iroots = list(info["import_roots"]) + [r for r in own if r not in info["import_roots"]]
            files = sorted(sources[d] + support.get(d, []))
            self.units[d] = Unit(
                lang="python", rel=d, name=ipath, import_path=ipath, files=files,
                test_files=sorted(assoc[d]), build_root=proj,
                extra={"import_roots": iroots, "project_root": proj,
                       "pytest_config": info["pytest_config"],
                       "package": d not in self.script_dirs},
            )
            if info.get("pytest_addopts"):
                self.units[d].extra["pytest_addopts"] = info["pytest_addopts"]
        for rel in self.files:
            if rel not in self.module_of:
                self.module_of[rel] = self._module_name(rel)
        for rel in sorted(self.module_of):
            self.ctx.py_modules.setdefault(self.module_of[rel], rel)

    def _package_name(self, d: str) -> str:
        if d in self.script_dirs or d not in self.package_roots:
            return PurePosixPath(d).name if d else self.ctx.root.name
        return _relto(d, self.package_roots[d]).replace("/", ".")

    def _place(self, d: str, roots: list[str]) -> None:
        r = self._chain_root(d, roots, self.has_init)
        if r is None:
            self.script_dirs.add(d)
        else:
            self.package_roots[d] = r
        self._name_files(d)

    def _place_loose(self, d: str) -> None:
        if not d or not self.has_init(d):
            self.script_dirs.add(d)
        else:
            top = d
            while top:
                up = _parent(top)
                if not up or not self.has_init(up):
                    break
                top = up
            self.package_roots[d] = _parent(top)
        self._name_files(d)

    def _name_files(self, d: str) -> None:
        for rel in self.dirs.get(d, []):
            if rel.endswith(".py"):
                full = _join(d, rel)
                self.module_of[full] = self._module_name(full)

    def _module_name(self, rel: str) -> str:
        d = _parent(rel)
        p = PurePosixPath(rel)
        if d in self.package_roots and d not in self.script_dirs:
            pkg = _relto(d, self.package_roots[d]).replace("/", ".")
            return pkg if p.name == "__init__.py" else f"{pkg}.{p.stem}"
        if d not in self.script_dirs and self.has_init(d):
            # a test package: dotted from its basedir
            b = self.basedir(rel)
            pkg = _relto(d, b).replace("/", ".")
            return pkg if p.name == "__init__.py" else f"{pkg}.{p.stem}"
        return (PurePosixPath(d).name or self.ctx.root.name) if p.name == "__init__.py" \
            else p.stem

    def _deps(self, proj: str, cfg: dict) -> list[str]:
        names = [_dist_name(x) for x in cfg["deps"]]
        for d, files in self.dirs.items():
            if not _under(d, proj):
                continue
            for f in files:
                if fnmatchcase(f, "requirements*.txt"):
                    try:
                        text = (self.ctx.root / _join(d, f)).read_text(encoding="utf-8",
                                                                      errors="replace")
                    except OSError:
                        continue
                    for ln in text.splitlines():
                        ln = ln.split("#", 1)[0].strip()
                        if ln and not ln.startswith("-"):
                            names.append(_dist_name(ln))
        return sorted({n for n in names if n})


