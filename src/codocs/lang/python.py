    def package_context(self, root: Path, unit: Any, target_rel: str,
                        max_chars: int = 12000) -> str:
        """signatures of the project modules the target imports, then of its unit's modules."""
        src = self._target_src(root, target_rel)
        used = self.identifiers(src) if src.strip() else set()
        m = self.model
        imported: list[str] = []
        if m is not None and src.strip():
            for f in m.resolve_files(target_rel, py_imports(src)):
                if f != target_rel and m.kind.get(f) == "source" and f not in imported:
                    imported.append(f)
        first: list[tuple[str, str, str]] = []
        later: list[tuple[str, str, str]] = []
        seen: set[tuple[str, str]] = set()
        for f in imported:
            for name, _kind, full, short in _entries(self.read(f, root)):
                if (f, short) in seen:
                    continue
                if name in used:
                    seen.add((f, short))
                    first.append((f, full, short))
        for f in imported:
            for name, _kind, full, short in _entries(self.read(f, root)):
                if (f, short) in seen or name.startswith("_"):
                    continue
                seen.add((f, short))
                later.append((f, short, short))
        rest_used: list[tuple[str, str, str]] = []
        rest: list[tuple[str, str, str]] = []
        for f in self._other_files(unit, target_rel):
            if f in imported or PurePosixPath(f).name == "conftest.py":
                continue
            for name, _kind, full, short in _entries(self.read(f, root)):
                if name.startswith("_") or (f, short) in seen:
                    continue
                seen.add((f, short))
                (rest_used if name in used else rest).append(
                    (f, full if name in used else short, short))
        return _emit(first + later + rest_used + rest, max_chars)

    def package_identifiers(self, root: Path, unit: Any,
                            exclude_rel: str | None = None) -> set[str]:
        names: set[str] = set()
        for f in self._other_files(unit, exclude_rel):
            for d in py_decls(self.read(f, root)):
                if d.kind != "method" and "." not in d.name:
                    names.add(d.name)
        return names

    def _conftests(self, unit: Any) -> list[str]:
        m = self.model
        if m is None:
            return []
        proj = unit.extra.get("project_root", unit.build_root) if hasattr(unit, "extra") else ""
        dirs: list[str] = []
        for target in [unit.rel] + [_parent(t) for t in unit.test_files]:
            for a in reversed(_ancestors(target)):
                if _under(a, proj) and a not in dirs:
                    dirs.append(a)
        return [_join(d, "conftest.py") for d in dirs if _join(d, "conftest.py") in m.fileset]

    def test_reference(self, root: Path, unit: Any, target_rel: str,
                       max_chars: int = 8000) -> str:
        """conftest fixtures, helpers of the unit's tests touching the target, one example."""
        src = self._target_src(root, target_rel)
        tnames = {d.name for d in py_decls(src) if "." not in d.name and d.kind != "method"}
        tnames |= {d.name for d in py_decls(src) if d.kind == "method"}
        stem = PurePosixPath(target_rel).stem
        companions = {f"test_{stem}.py", f"{stem}_test.py"}
        picked: list[tuple[str, str]] = []
        for f in self._conftests(unit):
            text = self.read(f, root).strip()
            if text:
                picked.append((f, text))
        scored: list[tuple[float, str, str]] = []
        example: tuple[int, str, str] | None = None
        for f in unit.test_files:
            tsrc = self.read(f, root)
            if not tsrc.strip():
                continue
            s = _Src(tsrc)
            tests = {local for local, _, _, _ in self._defs(tsrc, f)}
            for local, d, outer, _cls in self._defs(tsrc, f):
                if PurePosixPath(f).name not in companions:
                    continue
                text = s.text(outer).strip()
                bare, sel, _ = _usage(s, [outer])
                if (bare | sel) & tnames and (example is None or len(text) < example[0]):
                    example = (len(text), f, text)
            for dcl in py_decls(tsrc):
                if dcl.kind == "method" or "." in dcl.name or dcl.name in tests:
                    continue
                text = tsrc[dcl.start:dcl.end].strip()
                used = self.identifiers(text) if text else set()
                score = 3.0 * len(used & tnames) + (2.0 if PurePosixPath(f).name in companions
                                                    else 0.0)
                if used & tnames:
                    scored.append((score, f, text))
        scored.sort(key=lambda x: (-x[0], x[1]))
        picked += [(f, t) for _, f, t in scored]
        if example is not None and len(example[2]) <= max_chars // 3:
            picked.append((example[1], "# example test of the target from the existing suite\n"
                           + example[2]))
        lines: list[str] = []
        size = 0
        current = None
        for f, text in picked:
            chunk = ([f"# from {f}"] if f != current else []) + [text, ""]
            add = sum(len(c) + 1 for c in chunk)
            if size + add > max_chars:
                lines.append(TRUNCATED)
                break
            lines.extend(chunk)
            size += add
            current = f
        return "\n".join(lines).strip() + "\n" if lines else ""

    def allowed_third_party(self, root: Path, unit: Any) -> list[str]:
        m = self.model
        if m is None:
            return []
        proj = unit.extra.get("project_root", "") if hasattr(unit, "extra") else ""
        return list(m.projects.get(proj, {}).get("deps", []))

    # -- tests of a unit ----------------------------------------------------------------

    def test_index(self, root: Path, unit: Any) -> dict[str, dict]:
        """test id -> {"file", "idents", "selectors", "chains"} over the unit's test files."""
        out: dict[str, dict] = {}
        for f in sorted(unit.test_files):
            tsrc = self.read(f, root)
            if not tsrc.strip():
                continue
            s = _Src(tsrc)
            prel = self._prel(f)
            defs = self._defs(tsrc, f)
            for local, _d, outer, cls in defs:
                nodes = [outer]
                if cls is not None:
                    tests = {_name(x) for _, x, _, c in defs
                             if c is not None and c.id == cls.id}
                    for st in _statements(_body(cls)):
                        md, _ = _definition(st)
                        if md is not None and md.type == "function_definition" and \
                                _name(md) in tests:
                            continue
                        nodes.append(st)
                bare, sel, chains = _usage(s, nodes)
                out[f"{prel}::{local}"] = {"file": f, "idents": sorted(bare),
                                           "selectors": sorted(sel), "chains": sorted(chains)}
        return out

    def _bindings(self, test_rel: str, tsrc: str, target_rel: str, declared: set[str]
                  ) -> tuple[set[str], set[str]]:
        """(names bound from the target, names/chains naming the target module) in a test."""
        m = self.model
        bound: set[str] = set()
        aliases: set[str] = set()
        if m is None:
            return bound, aliases
        for spec in py_imports(tsrc):
            for f, is_module in m.resolve_spec(test_rel, spec):
                if f != target_rel and f.endswith("__init__.py") and spec.kind == "from" and \
                        not is_module and spec.name != "*":
                    hit = m.reexport(f, spec.name)       # `from pkg import Name` re-exported
                    if hit and hit[0] == target_rel:
                        if not hit[1]:
                            aliases.add(spec.bound)
                        elif hit[1] in declared:
                            bound.add(spec.bound)
                    continue
                if f != target_rel:
                    continue
                if spec.kind == "import":
                    aliases.add(spec.alias or spec.module)
                elif is_module:
                    aliases.add(spec.bound)
                elif spec.name == "*":
                    bound |= declared
                elif spec.name in declared:
                    bound.add(spec.bound)
        return bound, aliases

    def relevant_tests(self, root: Path, unit: Any, target_rel: str,
                       candidates: set[str]) -> list[str]:
        """companion-file tests, and tests whose body uses a name the target declares."""
        src = self._target_src(root, target_rel)
        decls = py_decls(src)
        declared = {d.name for d in decls if d.kind != "method" and "." not in d.name}
        if PurePosixPath(target_rel).name == "__init__.py":
            # a package's public names are its re-exports too
            declared |= {i.bound for i in py_imports(src) if i.kind == "from" and
                         i.name != "*" and i.bound and not i.bound.startswith("_")}
        methods = [(d.receiver.split(".")[0], d.name) for d in decls if d.kind == "method"]
        fixtures: dict[str, dict] | None = None
        stem = PurePosixPath(target_rel).stem
        companions = {f"test_{stem}.py", f"{stem}_test.py"}
        index = self.test_index(root, unit)
        by_file: dict[str, tuple[set[str], set[str]]] = {}
        prel_files = {self._prel(f): f for f in unit.test_files}
        out = []
        for name in sorted(candidates):
            info = index.get(name) or index.get(_fold(name))
            if info is None:
                head = _fold(name).split("::", 1)[0]
                f = prel_files.get(head)
                if f is not None and PurePosixPath(f).name in companions:
                    out.append(name)
                continue
            f = info["file"]
            if PurePosixPath(f).name in companions:
                out.append(name)
                continue
            if f not in by_file:
                by_file[f] = self._bindings(f, self.read(f, root), target_rel, declared)
            bound, aliases = by_file[f]
            idents = set(info["idents"])
            sel = set(info["selectors"])
            hit = bool(idents & bound)
            if not hit:
                for chain in info.get("chains", []):
                    for a in aliases:
                        if chain.startswith(a + ".") and \
                                chain[len(a) + 1:].split(".", 1)[0] in declared:
                            hit = True
                            break
                    if hit:
                        break
            if not hit:
                hit = any(meth in sel and cls in idents for cls, meth in methods)
            if not hit and self.model is not None:
                # fixtures from conftest.py: their bodies and imports count for the test
                if fixtures is None:
                    fixtures = {}
                for c in self.model.conftest_chain(f):
                    if c not in fixtures:
                        fixtures[c] = self._fixture_usage(root, c, target_rel, declared)
                fb, fs, fc = set(), set(), set()
                fbound: set[str] = set()
                fal: set[str] = set()
                for c in self.model.conftest_chain(f):
                    info_c = fixtures[c]
                    for fx in idents & set(info_c["fixtures"]):
                        u = info_c["fixtures"][fx]
                        fb |= u[0]
                        fs |= u[1]
                        fc |= u[2]
                        fbound |= info_c["bound"]
                        fal |= info_c["aliases"]
                if fb or fs or fc:
                    hit = bool(fb & fbound) or any(
                        ch.startswith(a + ".") and ch[len(a) + 1:].split(".", 1)[0] in declared
                        for ch in fc for a in fal) or any(
                        meth in (sel | fs) and cls in (idents | fb) for cls, meth in methods)
            if hit:
                out.append(name)
        return sorted(out)

    def _fixture_usage(self, root: Path, conftest: str, target_rel: str, declared: set[str]
                       ) -> dict:
        """fixtures of a conftest.py with their usage, and the conftest's target bindings."""
        csrc = self.read(conftest, root)
        out: dict = {"fixtures": {}, "bound": set(), "aliases": set()}
        if not csrc.strip():
            return out
        s = _Src(csrc)
        for st, _parent in _module_statements(s.p.root):
            d, outer = _definition(st)
            if d is not None and d.type == "function_definition" and _is_fixture(s, outer):
                out["fixtures"][_name(d)] = _usage(s, [outer])
        out["bound"], out["aliases"] = self._bindings(conftest, csrc, target_rel, declared)
        return out

