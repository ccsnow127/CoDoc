    def graph_facts(self, root: Path, rel: str, src: str, ctx: RepoContext) -> GraphFileFacts:
        """functions, call/ref sites with light receiver typing, classes, imports, tables."""
        facts = GraphFileFacts(is_test=self.is_test_file(rel) or
                               PurePosixPath(rel).name == "conftest.py")
        if not src.strip():
            return facts
        s = _Src(src)
        facts.imports = py_imports(src)
        imported = {i.bound for i in facts.imports if i.kind == "from" and i.name != "*"}
        modules = {i.bound for i in facts.imports if i.kind == "import"} | {
            i.bound for i in facts.imports if i.kind == "from" and i.name and
            i.name[:1].islower()}
        top_funcs: set[str] = set()
        classes: dict[str, Any] = {}

        def visit_class(node, outer, qual: str) -> None:
            classes[qual] = (node, outer)
            for st in _statements(_body(node)):
                d, o = _definition(st)
                if d is not None and d.type == "class_definition":
                    visit_class(d, o, f"{qual}.{_name(d)}")

        defs: list[tuple[str, str, Any, Any, str]] = []   # name, kind, node, outer, cls
        for st, _parent in _module_statements(s.p.root):
            d, o = _definition(st)
            if d is None:
                continue
            if d.type == "function_definition":
                if _name(d) in top_funcs:
                    continue        # the same function in another branch of an if/try
                top_funcs.add(_name(d))
                defs.append((_name(d), "func", d, o, ""))
            elif _name(d) not in classes:
                visit_class(d, o, _name(d))
        for qual, (node, _outer) in classes.items():
            tf = TypeFact(bases=_base_names(s, node), line=s.line(node))
            for st in _statements(_body(node)):
                d, o = _definition(st)
                if d is not None and d.type == "function_definition":
                    tf.methods.append(_name(d))
                    defs.append((f"{qual}.{_name(d)}", "method", d, o, qual))
                elif _unwrap(st) is not None and _unwrap(st).type == "assignment":
                    a = _unwrap(st)
                    typ = a.child_by_field_name("type")
                    for ident in _assigned(a):
                        tf.fields[s.text(ident)] = s.text(typ) if typ is not None else \
                            self._value_type(s, _assign_value(a)) or ""
            sup = node.child_by_field_name("superclasses")
            tf.is_interface = any(b.rsplit(".", 1)[-1] in ("Protocol", "ABC")
                                  for b in tf.bases) or (sup is not None and
                                                         "ABCMeta" in s.text(sup))
            facts.types[qual] = tf
        # self.x = Cls(...) in methods types the field
        for name, kind, d, _o, cls in defs:
            if kind != "method":
                continue
            for a in self._assignments(d):
                left = a.child_by_field_name("left")
                if left is not None and left.type == "attribute":
                    obj = left.child_by_field_name("object")
                    attr = left.child_by_field_name("attribute")
                    if obj is not None and s.text(obj) == "self" and attr is not None:
                        typ = a.child_by_field_name("type")
                        t = s.text(typ) if typ is not None else \
                            self._value_type(s, _assign_value(a))
                        if t and not facts.types[cls].fields.get(s.text(attr)):
                            facts.types[cls].fields[s.text(attr)] = t
        known = top_funcs | set(classes) | imported
        for name, kind, d, o, cls in defs:
            facts.funcs.append(FuncFact(name=name, kind=kind, line=s.line(d),
                                        end_line=s.p.end_line(o), cls=cls, start=s.start(d),
                                        end=s.end(d)))
            facts.calls[name] = self._calls(s, d, cls, facts.types, known, modules)
        # dispatch tables: module-level containers holding function names
        for st in s.p.root.named_children:
            a = _unwrap(st)
            if a is None or a.type != "assignment":
                continue
            val = _assign_value(a)
            if val is None or val.type not in ("dictionary", "list", "tuple", "set"):
                continue
            held = []
            from codocs.lang import treesitter as ts

            for x in ts.iter_types(val, ("identifier",), prune=("string", "comment")):
                t = s.text(x)
                if t in top_funcs or t in imported:
                    held.append(t)
            if held:
                for ident in _assigned(a):
                    facts.tables[s.text(ident)] = list(dict.fromkeys(held))
        return facts

    @staticmethod
    def _assignments(func) -> list:
        from codocs.lang import treesitter as ts

        return list(ts.iter_types(_body(func), ("assignment",),
                                  prune=("function_definition", "class_definition", "lambda")))

    @staticmethod
    def _value_type(s: _Src, val) -> str:
        """`Cls(...)` / `mod.Cls(...)` -> its class text (capitalised callee), else ""."""
        if val is None or val.type != "call":
            return ""
        fn = val.child_by_field_name("function")
        if fn is None or fn.type not in ("identifier", "attribute"):
            return ""
        text = re.sub(r"\s+", "", s.text(fn))
        return text if text.rsplit(".", 1)[-1][:1].isupper() else ""

    def _calls(self, s: _Src, d, cls: str, types: dict[str, TypeFact], known: set[str],
               modules: set[str]) -> list[CallFact]:
        from codocs.lang import treesitter as ts

        local: dict[str, str] = {}
        params = d.child_by_field_name("parameters")
        if params is not None:
            for p in params.named_children:
                if p.type in ("typed_parameter", "typed_default_parameter"):
                    ident = next((c for c in p.named_children if c.type == "identifier"), None)
                    typ = p.child_by_field_name("type")
                    if ident is not None and typ is not None:
                        local[s.text(ident)] = s.text(typ)
        bound_locals: set[str] = set(local)
        if params is not None:
            for x in ts.iter_types(params, ("identifier",)):
                bound_locals.add(s.text(x))
        for a in self._assignments(d):
            for ident in _assigned(a):
                bound_locals.add(s.text(ident))
                typ = a.child_by_field_name("type")
                t = s.text(typ) if typ is not None else self._value_type(s, _assign_value(a))
                if t:
                    local[s.text(ident)] = t
        out: list[CallFact] = []
        callees: set[int] = set()
        body = _body(d)
        if body is None:
            return out
        for c in ts.iter_types(body, ("call",), prune=("string", "comment")):
            fn = c.child_by_field_name("function")
            if fn is None:
                continue
            callees.add(fn.id)
            line = s.line(c)
            if fn.type == "identifier":
                out.append(CallFact(kind="call", qual="", name=s.text(fn), line=line))
            elif fn.type == "attribute":
                obj = fn.child_by_field_name("object")
                attr = fn.child_by_field_name("attribute")
                if obj is None or attr is None:
                    continue
                name = s.text(attr)
                if obj.type == "call" and obj.child_by_field_name("function") is not None and \
                        s.text(obj.child_by_field_name("function")) == "super":
                    out.append(CallFact(kind="call", qual="super", name=name,
                                        recv_type=cls or None, line=line))
                    continue
                qual = re.sub(r"\s+", "", s.text(obj))
                if not re.fullmatch(r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*", qual):
                    continue
                recv = None
                if qual in ("self", "cls"):
                    recv = cls or None
                elif qual in local:
                    recv = local[qual]
                elif qual.startswith("self.") and cls and qual.count(".") == 1:
                    recv = types.get(cls, TypeFact()).fields.get(qual[5:]) or None
                out.append(CallFact(kind="call", qual=qual, name=name, recv_type=recv,
                                    line=line))
        for x in ts.iter_types(body, ("identifier", "attribute"), prune=("string", "comment")):
            if x.id in callees:
                continue
            par = x.parent
            if x.type == "identifier":
                if par is not None and par.type == "attribute":
                    continue
                t = s.text(x)
                if t in known and t not in bound_locals:
                    out.append(CallFact(kind="ref", qual="", name=t, line=s.line(x)))
            else:
                obj = x.child_by_field_name("object")
                attr = x.child_by_field_name("attribute")
                if obj is not None and attr is not None and obj.type == "identifier" and \
                        s.text(obj) in modules and s.text(obj) not in bound_locals:
                    out.append(CallFact(kind="ref", qual=s.text(obj), name=s.text(attr),
                                        line=s.line(x)))
        return out
