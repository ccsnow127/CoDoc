def _class_block(s: _Src, node, outer, indent: str = "") -> list[str]:
    """a class header with its fields and member signatures (no bodies)."""
    lines = [indent + ln for ln in s.signature(node, outer).split("\n")]
    inner = indent + "    "
    n0 = len(lines)
    for st in _statements(_body(node)):
        if _is_docstring(st):
            continue
        d, o = _definition(st)
        if d is not None and d.type == "function_definition":
            sig = s.signature(d, o).split("\n")
            sig[-1] += " ..."
            lines.extend(inner + ln for ln in sig)
        elif d is not None:
            lines.extend(_class_block(s, d, o, inner))
        elif _unwrap(st) is not None and _unwrap(st).type == "assignment":
            lines.append(inner + s.first_line(st))
    if len(lines) == n0:
        lines.append(inner + "...")
    return lines


def _entries(src: str) -> list[tuple[str, str, str, str]]:
    """(name, kind, full text, short text) of a module's top-level items."""
    if not src.strip():
        return []
    s = _Src(src)
    out = []
    for d, node, outer in _decl_items(s):
        if d.kind == "method" or "." in d.name:
            continue
        if d.kind == "type":
            out.append((d.name, d.kind, "\n".join(_class_block(s, node, outer)), d.signature))
        else:
            out.append((d.name, d.kind, d.signature, d.signature))
    return out


def _emit(entries: list[tuple[str, str, str]], max_chars: int, head: str = "# ") -> str:
    """`# <rel>` headed blocks of (file, full, short) entries within a char budget."""
    lines: list[str] = []
    size = 0
    current = None
    for f, full, short in entries:
        hd = (([""] if lines else []) + [f"{head}{f}"]) if f != current else []
        room = max_chars - size - len(TRUNCATED) - 1
        chunk = hd + [full]
        if sum(len(c) + 1 for c in chunk) > room:
            chunk = hd + [short]
        add = sum(len(c) + 1 for c in chunk)
        if add > room:
            lines.append(TRUNCATED)
            break
        lines.extend(chunk)
        size += add
        current = f
    return "\n".join(lines) + "\n" if lines else ""


def _usage(s: _Src, nodes) -> tuple[set[str], set[str], set[str]]:
    """(bare names, attribute names, dotted attribute chains) used inside nodes."""
    from codocs.lang import treesitter as ts

    bare: set[str] = set()
    sel: set[str] = set()
    chains: set[str] = set()
    for n in nodes:
        for x in ts.iter_types(n, ("identifier", "attribute"), prune=("string", "comment")):
            par = x.parent
            if x.type == "identifier":
                if par is not None and par.type == "attribute" and \
                        par.child_by_field_name("attribute") is not None and \
                        par.child_by_field_name("attribute").id == x.id:
                    sel.add(s.text(x))
                elif par is not None and par.type == "keyword_argument" and \
                        par.child_by_field_name("name") is not None and \
                        par.child_by_field_name("name").id == x.id:
                    continue
                else:
                    bare.add(s.text(x))
                continue
            obj = par.child_by_field_name("object") if par is not None and \
                par.type == "attribute" else None
            if obj is not None and obj.id == x.id:
                continue
            text = re.sub(r"\s+", "", s.text(x))
            if re.fullmatch(r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)+", text):
                chains.add(text)
    return bare, sel, chains


def _docstring_text(s: _Src, block) -> str:
    sts = _statements(block)
    if not sts or not _is_docstring(sts[0]):
        return ""
    node = _unwrap(sts[0])
    parts = [c for c in node.named_children if c.type == "string_content"]
    if parts:
        return "".join(s.text(c) for c in parts).strip()
    return s.text(node).strip("'\"rRbBuUfF \n")


