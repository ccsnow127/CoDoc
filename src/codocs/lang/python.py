class PythonAdapter(LangAdapterBase):
    """the Python adapter; bound to a RepoContext for everything beyond parsing."""

    name = "python"
    test_file_patterns = PY_TEST_PATTERNS

    # -- model ---------------------------------------------------------------------------

    @property
    def model(self) -> _Model | None:
        if self.ctx is None:
            return None
        key = ("python", "model")
        m = self.ctx.cache.get(key)
        if m is None:
            m = self.ctx.cache[key] = _Model(self.ctx)
        return m

    def _need_model(self, runner: Any = None) -> _Model:
        """the model of this adapter's context, else of the runner's bound adapter."""
        m = self.model
        if m is None:
            other = getattr(runner, "adapter", None)
            m = other.model if other is not None and other is not self and \
                getattr(other, "ctx", None) is not None else None
        if m is None:
            raise ValueError("the Python adapter is not bound to a RepoContext "
                             "(use codocs.lang.adapter('python', ctx))")
        return m

    def unit(self, rel: str) -> Unit | None:
        m = self.model
        return m.units.get((rel or "").strip("/")) if m is not None else None

    def project_root(self, rel: str) -> str:
        m = self.model
        return m.project(rel) if m is not None else ""

    def module_name(self, rel: str) -> str:
        m = self.model
        if m is not None:
            return m.module_of.get(rel) or m._module_name(rel)
        return PurePosixPath(rel).stem

    def _prel(self, rel: str) -> str:
        return _relto(rel, self.project_root(rel))

    def _patterns(self, rel: str) -> tuple[list[str], list[str], list[str]]:
        m = self.model
        if m is None:
            return list(PY_TEST_PATTERNS), ["test"], ["Test"]
        return m.patterns(rel)

    # -- files and parsing -----------------------------------------------------------------

    def is_test_file(self, rel: str, src: str | None = None) -> bool:
        m = self.model
        if m is not None:
            return m.is_test(rel)
        name = PurePosixPath(rel).name
        return name != "conftest.py" and any(fnmatchcase(name, g) for g in PY_TEST_PATTERNS)

    def is_generated(self, src: str, rel: str = "") -> bool:
        if self.include_generated:
            return False
        name = PurePosixPath(rel).name if rel else ""
        if name and any(fnmatchcase(name, g) for g in _GEN_NAMES):
            return True
        return any(_GEN_RE.search(ln) for ln in src.splitlines()[:30])

    def decls(self, src: str) -> list[Decl]:
        return py_decls(src)

    def imports(self, src: str) -> list[ImportSpec]:
        return py_imports(src)

    def format_import(self, imp: Any) -> str:
        return format_import(imp) if isinstance(imp, ImportSpec) else super().format_import(imp)

    def preamble(self, src: str) -> str:
        """shebang, encoding cookie and `from __future__` imports (inserted verbatim)."""
        lines = src.splitlines()
        head = []
        if lines and lines[0].startswith("#!"):
            head.append(lines[0])
        for ln in lines[:2]:
            if _COOKIE_RE.match(ln) and ln not in head:
                head.append(ln)
        futures = []
        if src.strip():
            s = _Src(src)
            futures = [s.text(st) for st in s.p.root.named_children
                       if st.type == "future_import_statement"]
        parts = head + futures
        return "\n".join(parts) + "\n" if parts else ""

    def apply_preamble(self, code: str, preamble: str) -> str:
        """code with its own shebang/cookie/future lines replaced by the original preamble."""
        if not preamble.strip():
            return code
        pre = preamble.splitlines()
        head = [ln for ln in pre[:2] if ln.startswith("#!") or _COOKIE_RE.match(ln)]
        futures = "\n".join(pre[len(head):]).strip()
        lines = code.splitlines(keepends=True)
        k = 0
        while k < min(2, len(lines)) and (lines[k].startswith("#!") or _COOKIE_RE.match(lines[k])):
            k += 1
        body = "".join(lines[k:])
        if body.strip():
            s = _Src(body)
            cuts = [(s.start(st), s.end(st)) for st in s.p.root.named_children
                    if st.type == "future_import_statement"]
            body = _cut(s, cuts)
        body = body.lstrip("\n")
        if futures:
            insert = 0
            if body.strip():
                s = _Src(body)
                sts = _statements(s.p.root)
                if sts and _is_docstring(sts[0]):
                    insert = s.line_end(max(s.start(sts[0]), s.end(sts[0]) - 1))
            sep = "\n" if insert else ""
            body = body[:insert] + sep + futures + "\n" + ("\n" if body[insert:].strip() else "") \
                + body[insert:].lstrip("\n")
        return "".join(ln + "\n" for ln in head) + body

    # -- tests in source -----------------------------------------------------------------

    def _defs(self, src: str, rel: str):
        _, funcs, classes = self._patterns(rel)
        return _test_defs(src, funcs, classes)

    def unlisted_failures(self, res: Any, src: str, rel: str) -> list[str]:
        """failing ids pytest collected from the suite file that static discovery does not list
        (they can never be pruned, so the suite must not count as green with them)."""
        prel = self._prel(rel)
        names = set(self.test_names(src, rel))
        return sorted(n for n, v in (getattr(res, "tests", None) or {}).items()
                      if v == "fail" and _fold(n) not in names
                      and _fold(n).split("::", 1)[0] == prel)

    def test_names(self, src: str, rel: str) -> list[str]:
        prel = self._prel(rel)
        return [f"{prel}::{local}" for local, _, _, _ in self._defs(src, rel)]

    def test_lines(self, src: str, rel: str) -> dict[str, int]:
        prel = self._prel(rel)
        return {f"{prel}::{local}": d.start_point[0] + 1 for local, d, _, _ in
                self._defs(src, rel)}

    def remove_tests(self, src: str, names: set[str]) -> str:
        """drop those tests (decorators and leading comments too); emptied test classes go, and
        so do aliases of a removed test function."""
        wanted = {_local(n) for n in names}
        if not wanted or not src.strip():
            return src
        s = _Src(src)
        # every function/class may hold a wanted id (the project's patterns are not known here)
        return self._remove(s, wanted, _collect_tests(s, ("",), ("",)))

    def _remove(self, s: _Src, wanted: set[str], defs: list[_TestDef]) -> str:
        doomed: set[int] = set()
        gone_funcs: set[str] = set()
        for t in defs:
            if t.local in wanted:
                doomed.add(t.outer.id)
                if not t.func and t.node.type == "function_definition":
                    gone_funcs.add(_name(t.node))
        if not doomed:
            return s.src
        # `test_alias = test_x` would raise NameError once test_x is gone
        for t in defs:
            if t.func and t.func in gone_funcs:
                doomed.add(t.outer.id)
        for st, _parent in _module_statements(s.p.root):
            al = _alias_of(s, st)
            if al is not None and al[1] in gone_funcs:
                doomed.add(st.id)
        return _cut(s, _removal_edits(s, doomed))

    def strip_non_tests(self, src: str) -> str:
        if not src.strip():
            return src
        s = _Src(src)
        return _cut(s, [(s.start(g), s.end(g)) for g in _main_guards(s)])

    def mutation_sites(self, src: str) -> list[Mutant]:
        return py_mutation_sites(src)

    # -- units and targets ---------------------------------------------------------------

    async def discover(self, runner: Any, subtree: str | None = None,
                       packages: list[str] | None = None) -> dict[str, Unit]:
        model = self._need_model(runner)
        units = dict(model.units)
        sub = (subtree or "").strip().strip("/")
        if sub and sub != ".":
            units = {k: v for k, v in units.items() if _under(k, sub)}
        if packages:
            wanted = [p.strip().strip("/") for p in packages]
            units = {k: v for k, v in units.items()
                     if any(k == p or (p and k.startswith(p + "/")) or p in ("", ".")
                            for p in wanted)}
        return dict(sorted(units.items()))

