_FENCE_RE = re.compile(r"^```[ \t]*([\w+#.-]*)[^\n]*\n(.*?)^```[ \t]*$", re.MULTILINE | re.DOTALL)


_ID_LINE_RE = re.compile(r"\b(?:IDENTIFICATION|ID)\s+DIVISION\b|\b(?:PROGRAM|FUNCTION)-ID\b",
                         re.I)


def _reference_form(lines: list[str]) -> bool:
    """the code is in fixed reference format: its first IDENTIFICATION / PROGRAM-ID line has
    a sequence area (digits or blanks), a blank indicator and code from column 8."""
    for ln in lines:
        if _ID_LINE_RE.search(ln) and not ln.lstrip().startswith("*"):
            head = ln[:6]
            return len(ln) > 8 and (head.isdigit() or not head.strip()) and ln[6] == " " \
                and ln[7] != " "
    return False


def _display_form(lines: list[str]) -> bool:
    """the code is in display form (columns 7-72): every line starts with a blank or an
    indicator (`*`, `/`, `-`, `D `), and the first IDENTIFICATION / PROGRAM-ID line starts
    in area A (display columns 2-5)."""
    first = None
    for ln in lines:
        if not ln.strip():
            continue
        if ln[0] not in " \t*/-" and not (ln[0] in "Dd" and ln[1:2] in (" ", "")):
            return False
        if first is None and ln[0] in " \t" and _ID_LINE_RE.search(ln):
            first = ln.expandtabs(8)
    return first is not None and 1 <= len(first) - len(first.lstrip()) <= 4


def place_fixed(code: str) -> str:
    """generated code for a fixed-format target in strict reference format. reference form
    (sequence area blanked, identification area dropped) and display form (six blank columns
    put back) keep every line where the writer put it, so continuation operands, comment-
    entries and `1000-INIT.` paragraphs stay in their area; flush-left code goes through
    reflow_fixed."""
    from codocs.cobol.reflow import keep_fixed, reflow_fixed
    from codocs.cobol.source import expand_tabs_fixed

    lines = code.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    if _reference_form(lines):
        ref = [("      " + expand_tabs_fixed(ln)[6:72]).rstrip() for ln in lines]
    elif _display_form(lines):
        ref = [expand_tabs_fixed("      " + ln).rstrip() if ln.strip() else "" for ln in lines]
    else:
        return reflow_fixed(_for_reflow(code))
    kept = keep_fixed(ref)
    return kept if kept is not None else reflow_fixed("\n".join(ref))


def _for_reflow(code: str) -> str:
    """generated code made readable for reflow_fixed: reference form loses its sequence and
    identification areas (cobc ignores both); flush-left comment lines (`*` first) become
    fixed-format comment lines, except a `*` operator that continues an unfinished
    expression on a deeper line (`COMPUTE X = A` / `    * B.`)."""
    from codocs.cobol.reflow import _ends_sentence

    lines = code.replace("\r\n", "\n").split("\n")
    if _reference_form(lines):
        out = []
        for ln in lines:
            ln = ln.expandtabs(8)
            out.append(("      " + ln[6:72]).rstrip())  # a sequence-only line is blank
        return "\n".join(out)
    out = []
    open_, last = False, 0  # the last code line left its sentence open; its indent
    for ln in lines:
        ln = ln.expandtabs(8).rstrip()
        s = ln.lstrip()
        indent = len(ln) - len(s)
        if s.startswith("*") and not s.startswith("*>"):
            if not (open_ and indent > last and _operand_continuation(s[1:])):
                out.append("      *" + s[1:])
                continue
            ln = " " * (indent if indent != 6 else 7) + s  # never in the indicator column
        out.append(ln)
        if s and not s.startswith(("*>", ">>")):
            open_, last = not _ends_sentence(s), indent
    return "\n".join(out)


_OPERAND_RE = re.compile(r"^\*?\s*[A-Za-z0-9(+\-'\"]")
_CONT_FOLLOW = {"AND", "OR", "NOT", "ON", "SIZE", "ROUNDED", "END-COMPUTE", "THEN", "TO",
                "GIVING", "FROM", "BY", "INTO", "=", ">", "<", ">=", "<=", "<>"}


def _operand_continuation(rest: str) -> bool:
    """*rest* (the text after a leading `*`) reads as the operand of a multiplication (or,
    with a second `*`, an exponentiation): one operand, or an operand followed by an
    operator or a keyword, not prose such as `* set the flag`."""
    if not _OPERAND_RE.match(rest):
        return False
    toks = rest.lstrip("*").split()
    if len(toks) < 2:
        return True
    second = toks[1].upper().rstrip(".")
    return second in _CONT_FOLLOW or second[:1] in "+-*/()"


def _signal_name(sig: int) -> str:
    import signal

    try:
        return f"signal {signal.Signals(sig).name}"
    except ValueError:
        return f"signal {sig}"


def _safe(path: str) -> str:
    parts = [p for p in PurePosixPath(path.replace("\\", "/")).parts if p not in ("/", ".", "..")]
    return "/".join(parts) or "file"


def _is_comment(line: str) -> bool:
    s = line.rstrip()
    return s.lstrip().startswith("*>") or (len(s) > 6 and s[6] in "*/")


def _procedure_test_ids(src: str) -> list[str]:
    """ids of `TEST <id> PASS|FAIL` literals in the PROCEDURE DIVISION (comments skipped)."""
    out: list[str] = []
    inside = False
    for ln in src.split("\n"):
        if _is_comment(ln):
            continue
        if re.search(r"\bPROCEDURE\s+DIVISION\b", ln, re.I):
            inside = True
        if not inside:
            continue
        for m in _TEST_LIT_RE.finditer(ln):
            if m.group(1) not in out:
                out.append(m.group(1))
    return out


def _line_offsets(src: str) -> list[int]:
    """char offset of the start of every physical line (1-based index), plus the end."""
    out = [0, 0]
    pos = 0
    for ln in src.split("\n"):
        pos += len(ln) + 1
        out.append(pos)
    return out


def _off(starts: list[int], line: int) -> int:
    line = max(1, min(line, len(starts) - 1))
    return starts[line]


def _data_decls(toks: list, lines: list, starts: list[int]) -> list[Decl]:
    """one var Decl per inline level-01/77 entry of the program's first DATA DIVISION."""
    out: list[Decl] = []
    section = ""
    in_data = False
    k = 0
    n = len(toks)
    while k < n:
        t = toks[k]
        nxt = toks[k + 1].up if k + 1 < n else ""
        if t.kind == "W" and nxt == "DIVISION":
            if t.up == "DATA":
                in_data = True
            elif t.up == "PROCEDURE":
                break
            k += 2
            continue
        if not in_data:
            k += 1
            continue
        if t.kind == "W" and nxt == "SECTION":
            section = t.up
            k += 2
            continue
        if t.up in ("COPY", "EXEC"):
            end = "END-EXEC" if t.up == "EXEC" else None
            while k < n and (toks[k].kind != "P" if end is None else toks[k].up != end):
                k += 1
            k += 1
            continue
        first_in_line = k == 0 or toks[k - 1].li != t.li or toks[k - 1].kind == "P"
        if section in _DATA_SECTIONS and first_in_line and t.kind == "W" and \
                t.up.lstrip("0") in ("1", "77") and t.up.isdigit() and k + 1 < n:
            name_tok = toks[k + 1]
            end = k + 1
            while end < n and toks[end].kind != "P":
                end += 1
            last = toks[end].line if end < n else name_tok.line
            # the subordinate entries (levels 02-49, 66, 88) belong to the record
            j = end + 1
            while j < n:
                tj = toks[j]
                if tj.kind == "W" and (tj.up in ("COPY", "EXEC", "FD", "SD", "RD")
                                       or (j + 1 < n and toks[j + 1].up in ("SECTION",
                                                                           "DIVISION"))):
                    break
                lead = j == 0 or toks[j - 1].kind == "P"
                if lead and tj.kind == "W" and tj.up.isdigit() and \
                        tj.up.lstrip("0") in ("1", "77", "78"):
                    break
                if tj.kind == "P":
                    last = tj.line
                j += 1
            name = name_tok.up if name_tok.kind == "W" else ""
            if name and name != "FILLER" and name not in ("REDEFINES",):
                sig = lines[t.li].text.strip() if t.li < len(lines) else f"{t.text} {name}"
                out.append(Decl(kind="var", name=name, start=_off(starts, t.line),
                                end=_off(starts, last + 1), line=t.line, end_line=last,
                                signature=sig))
            k = end + 1
            continue
        k += 1
    return out


def _para_decls(prog: Any, toks: list, lines: list, starts: list[int], last_line: int
                ) -> list[Decl]:
    """one method Decl per non-trivial paragraph or section (duplicates collapse)."""
    heads = sorted((p.line, p.name, p.kind) for p in prog.paragraphs if p.name != "(entry)")
    out: list[Decl] = []
    seen: set[str] = set()
    pid = prog.program_id.upper()
    for i, (ln, name, kind) in enumerate(heads):
        nxt = heads[i + 1][0] if i + 1 < len(heads) else last_line + 1
        body = [t for t in toks if ln <= t.line < nxt and t.kind != "P"
                and not (t.line == ln and t.up in (name, "SECTION"))]
        if not body or all(t.up in _TRIVIAL for t in body) or name in seen:
            continue
        seen.add(name)
        end = max((t.line for t in body), default=ln)
        sig = f"{name} SECTION." if kind == "section" else f"{name}."
        out.append(Decl(kind="method", name=name, receiver=pid, start=_off(starts, ln),
                        end=_off(starts, end + 1), line=ln, end_line=end, signature=sig))
    return out


