    def test_refine_messages(self, target_rel: str, unit: Any, source: str, context: str,
                             taken: set[str], third_party: list[str], best: Any, last: Any, *,
                             attempt: int = 0, last_round: int = 0,
                             reference: str = "") -> tuple[str, str]:
        from codocs.cobol.testprompts import refine_user
        from codocs.tesearch.prompts import (
            _build_errors,
            _fmt_mut,
            mark_failing,
            mark_source,
            refine_system,
        )
        from codocs.tesearch.prompts_lang import _last_block, _source_header

        t, prog, src, cbs, callees, dialect = self._prompt_inputs(target_rel)
        shown = self.prompt_source(source)
        if best is not None and (best.uncovered or best.survivors):
            marked = f"{_source_header('*>')}\n" + \
                mark_source(shown, best.uncovered, best.survivors, "*>").rstrip()
        else:
            marked = f"[TARGET SOURCE]\n{shown.rstrip()}"
        best_block = last_block = ""
        fixing = False
        suite = self.suite_rel(unit, self.stem(target_rel))
        if best is not None:
            cov = f"n/a ({best.cov_note})" if getattr(best, "cov_note", "") else \
                f"{best.cov:.3f}"
            header = (f"[CURRENT BEST PLAN - size={best.size} green={best.green_size} "
                      f"coverage={cov} mutation={_fmt_mut(best)} (killed {best.killed} of "
                      f"{best.mutants_valid} valid mutants) score={best.score:.3f}]")
            plan = best.suite_src or best.green_src
            lines = self.test_lines(plan, suite) if best.failing else None
            best_block = f"{header}\n{mark_failing(plan, best.failing, '*>', lines=lines)}"
            if last is not None and last is not best and not last.build_ok:
                last_block = ("[LAST ATTEMPT - did NOT BUILD; avoid these errors]\n"
                              f"{_build_errors(last.build_errors)}")
            elif last is not None and last is not best:
                last_block = _last_block(last, last_round)
        elif last is not None:
            fixing = True
            last_block = ("[LAST ATTEMPT - did NOT BUILD; build errors]\n"
                          f"{_build_errors(last.build_errors)}\n\n[LAST ATTEMPT PLAN]\n"
                          f"{(last.suite_src or '').rstrip()}")
        user = refine_user(target_rel, self._package_line(target_rel, unit), t, prog, src, cbs,
                           callees, dialect, marked_source=marked, best_block=best_block,
                           last_block=last_block, fixing=fixing, attempt=attempt,
                           reference=reference, language=self._language())
        return refine_system("cobol"), user

