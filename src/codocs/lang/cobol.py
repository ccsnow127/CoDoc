    async def testgen_oneshot(self, loop: Any, target: Any, unit: Any) -> Any:
        """spec programs: one LLM call, the spec delivered (status spec); unit/batch without
        cobc: status no-toolchain without an LLM call; else None (run the loop)."""
        from codocs.cobol import bundle
        from codocs.llm import LLMError
        from codocs.tesearch.loop import SuiteResult, SuiteRound, _write
        from codocs.tesearch.measure import Measurement

        mode = self.testgen_mode(target, unit)
        if mode == "loop":
            return None
        s = loop.settings
        result = SuiteResult(pkg=target.pkg, file=target.file, stem=target.stem, status="ok",
                             threshold=float(s.test_threshold), max_rounds=1, lang=self.name)
        if mode.startswith("skip:"):
            result.status = mode.split(":", 1)[1]
            result.error = "cobc not available: unit and batch programs are not tested"
            return result
        wd = loop.work_dir(unit, target.stem)
        for old in wd.glob("round_*"):
            shutil.rmtree(old, ignore_errors=True)
        source = self.read(target.file, loop.module_root)
        system, user = self.spec_messages(target.file, unit, source)
        try:
            reply = await loop.llm.complete(system, user, tag=f"testgen {target.file} spec",
                                            max_tokens=max(self.test_max_tokens,
                                                           int(s.max_tokens)))
        except LLMError as e:
            result.status, result.error = "error", str(e)
            return result
        text = self.normalize_suite(self.extract_code(reply), unit, target.file)
        b = bundle.parse_bundle(text)
        cases = len((b.plan.get("cases") or []) if b is not None else [])
        m = Measurement(build_ok=True, size=cases, green_size=0, suite_src=text)
        rd = wd / "round_1"
        _write(rd / "prompt.txt", f"=== SYSTEM ===\n{system}\n\n=== USER ===\n{user}\n")
        _write(rd / "reply.txt", reply)
        _write(rd / "suite.cbt", text)
        _write(rd / "measure.json", json.dumps(m.to_dict(), indent=2, ensure_ascii=False))
        self.deliver_spec(loop.out_dir, unit, target.stem, text)
        t = self.testability(target.file)
        kind = getattr(t, "spec_kind", "") or "CICS/DB2"
        result.status = "spec"
        result.rounds = [SuiteRound(round=1, suite=text, measurement=m)]
        result.best_round = 1
        result.best_score = 0.0
        result.best_size = 0
        result.cov_note = f"spec: not executable ({kind})"
        if b is not None and b.error:
            result.error = b.error
        return result

    def deliver_spec(self, out_dir: Path, unit: Any, stem: str, text: str) -> list[Path]:
        """OUT/tests/<pkg>/<STEM>_codocs_spec.json (plan) and .md (spec markdown)."""
        from codocs.cobol import bundle

        base = Path(out_dir) / "tests" / unit.dir_name
        base.mkdir(parents=True, exist_ok=True)
        b = bundle.parse_bundle(text)
