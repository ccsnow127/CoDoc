    def deliver_extra(self, path: Path, green_src: str) -> None:
        """expand a delivered bundle next to it: <STEM>_codocs_test/{plan.json, driver,
        stubs.cbl, fixtures/..., README.md}."""
        from codocs.cobol import bundle

        b = bundle.parse_bundle(green_src)
        if b is None:
            return
        d = Path(path).with_suffix("")
        shutil.rmtree(d, ignore_errors=True)
        d.mkdir(parents=True, exist_ok=True)
        (d / "plan.json").write_text(json.dumps(b.plan, indent=2, sort_keys=True,
                                                ensure_ascii=False) + "\n", encoding="utf-8")
        test = bundle.to_generated(b)
        driver = ""
        if test.driver_source:
            driver = f"{(test.driver_name or 'TDRIVER')}.cbl"
            (d / driver).write_text(test.driver_source, encoding="utf-8")
        if test.stubs_source:
            (d / "stubs.cbl").write_text(test.stubs_source, encoding="utf-8")
        records = self._fixture_records(test)
        loaded: list[str] = []
        for fx in test.inputs:
            p = d / "fixtures" / _safe(fx.path)
            p.parent.mkdir(parents=True, exist_ok=True)
            data = records.get(id(fx))
            if data is not None:
                p.write_bytes(data)
            else:
                p.write_text(fx.content, encoding="utf-8")
                if any(isinstance(r, dict) for r in fx.records or []):
                    loaded.append(_safe(fx.path))
        (d / "README.md").write_text(self._bundle_readme(b, test, driver, d, loaded),
                                     encoding="utf-8")

    def _fixture_records(self, test: Any) -> dict[int, bytes]:
        """id(fixture) -> the record bytes the harness writes for a line-sequential input
        (field maps encoded through the FD record layout); other inputs are absent. Needs a
        working cobc (the record layout follows the program's build dialect)."""
        runner = self._runner
        if runner is None or self.ctx is None or not runner.cobc_ok() or \
                test.program_id not in self.index().programs:
            return {}
        from codocs.cobol.harness import _LINE_SEQ, encode_record, fixture_records

        h = runner.harness
        if test.testability is None:
            test.testability = self.testability(self.index().programs[test.program_id].path)
        uses = h._file_uses(test)
        out: dict[int, bytes] = {}
        for fx in test.inputs:
            owner, f = h._match_file(fx, uses)
            if f is None or (f.organization or "SEQUENTIAL") != _LINE_SEQ:
                continue
            layouts = h._layouts(owner, f)
            out[id(fx)] = b"".join(encode_record(r, layouts)[0] + b"\n"
                                   for r in fixture_records(fx))
        return out

    def _bundle_readme(self, b: Any, test: Any, driver: str, d: Path | None = None,
                       loaded: list[str] | None = None) -> str:
        """how to build and run the expanded bundle by hand, from the bundle directory: the
        target plus every repo program the harness links (CALL / FUNCTION closure minus the
        programs replaced by stubs) and the stubs the harness keeps."""
        from codocs.cobol.harness import DIALECTS, plan_stubs

        target = b.target
        flags = "-std=ibm -frelax-syntax-checks"
        runner = self._runner
        pid = b.program
        index = self.index() if self.ctx is not None else None
        known = pid if index is not None and pid in index.programs else None
        if runner is not None and known and runner.cobc_ok():
            flags = " ".join(DIALECTS.get(runner.dialect(pid), [])) or flags

        def repo(rel: str) -> str:
            rel = str(PurePosixPath(rel))
            return "$REPO" if rel in ("", ".") else f"$REPO/{rel}"

        incs = ""
        if index is not None:
            dirs = sorted({str(PurePosixPath(cb.path).parent) for cb in index.copybooks.values()})
            incs = " ".join(f"-I {repo(x)}" for x in dirs)
        sources = [repo(target)]
        stubs = ""
        notes: list[str] = []
        if known:
            tb = self.testability(target)
            plan = plan_stubs(index, pid, test.stubs_source or "",
                              tb.callees if tb is not None else None)
            for c in plan.linked:
                prog = index.programs.get(c)
                if prog is not None and repo(prog.path) not in sources:
                    sources.append(repo(prog.path))
            if plan.chunks:
                stubs = "stubs.cbl"
                if plan.skipped and d is not None:
                    stubs = "stubs_linked.cbl"
                    (d / stubs).write_text("".join(c for c, _ in plan.chunks),
                                           encoding="utf-8")
            notes = list(plan.skipped)
            if plan.replaced:
                notes.append("replaced by stubs: " + ", ".join(plan.replaced))
        elif test.stubs_source:
            stubs = "stubs.cbl"
        cmd = " ".join(x for x in ("cobc -x", flags, incs) if x)
        lines = [f"# Generated test of `{target}` (program `{pid}`, mode {b.mode})", "",
                 "Run these commands from this directory, with `REPO` set to the repository "
                 "root (paths of programs and copybooks are relative to it):", "", "```sh",
                 "REPO=/path/to/repository"]
        if driver:
            lines += [" ".join([cmd, "-o tdriver", driver, *sources] + ([stubs] if stubs
                                                                        else [])),
                      "./tdriver"]
        else:
            lines += [" ".join([cmd, "-o program", *sources] + ([stubs] if stubs else [])),
                      "./program"]
        lines += ["```", ""]
        if notes:
            lines += ["Stub notes (the harness applies the same rules):", ""]
            lines += [f"- {n}" for n in notes]
            lines.append("")
        if test.inputs:
            lines += ["Map the fixture files with DD environment variables (the paths are "
                      "relative to this directory):", ""]
            lines += [f"- `DD_{fx.dd}=fixtures/{_safe(fx.path)}`" for fx in test.inputs]
            lines.append("")
        if test.expected_files:
            lines += ["Output files the plan checks (expected records in `plan.json`):", ""]
            lines += [f"- `DD_{fx.dd}={_safe(fx.path)}`" for fx in test.expected_files]
            lines.append("")
        if loaded:
            lines += ["These fixtures hold the plan's field maps as JSON lines: before the "
                      "run the harness encodes them through the program's record layout and "
                      "loads files that are not line sequential with a generated loader "
                      "program, which this bundle does not reproduce: "
                      + ", ".join(f"`fixtures/{x}`" for x in loaded), ""]
        return "\n".join(lines)

