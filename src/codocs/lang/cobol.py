    def failure_message(self, output: str) -> str:
        """the case's `TEST <id> FAIL ...` line first, then the log without RUN/PASS lines."""
        lines = [ln.rstrip() for ln in (output or "").splitlines() if ln.strip()]
        fail = [ln for ln in lines if re.search(r"\bTEST\s+\S+\s+FAIL\b", ln, re.I)]
        rest = [ln for ln in lines if ln not in fail
                and not re.search(r"\bTEST\s+\S+\s+(?:RUN|PASS)\b", ln, re.I)]
        text = "\n".join(fail[:1] + rest)
        return text if len(text) <= MESSAGE_CHARS else text[:MESSAGE_CHARS] + "\n..."

    def crash_message(self, res: TestResult) -> str:
        from codocs.cobol.harness import _SIGNAL_MESSAGE

        tail = res.tail or ""
        m = _SIGNAL_MESSAGE.search(tail)
        detail = m.group(0) if m else ""
        if not detail and res.returncode:
            rc = res.returncode
            detail = _signal_name(rc - 128) if rc > 128 else f"exit status {rc}"
        if not detail:
            last = next((ln.strip() for ln in reversed(tail.splitlines()) if ln.strip()), "")
            detail = last[:200]
        return f"did not run: the driver ended early ({detail})" if detail else \
            "did not run: the driver ended early"

