"""the COBOL language adapter: units are directories of program files,
targets are program files, docs follow the RepoAgent heading contract (ClassDef per program,
VariableDef per inline level-01/77 entry, MethodDef per paragraph), generated tests are
bundles (cobol/bundle.py) run by the GnuCOBOL harness (lang/cobolrun.py).

all static facts come from one `codocs.cobol.index.CobolRepoIndex` per run scope (the
selection subtree, minus the COBOL --exclude-path globs and OUT). The optional hooks the
loops read with getattr (doc_signal, custom_signals, finalize_code, testgen_oneshot, ...)
are the whole interface between the shared loops and COBOL.
"""

