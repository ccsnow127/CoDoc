    def _gate_state(self, runner: Any, rel: str) -> tuple[bool, str]:
        """(gate on, reason when off): the neutralised original compiles."""
        if rel in self._gate:
            return self._gate[rel]
        if runner is None or not getattr(runner, "cobc_ok", lambda: False)():
            state = (False, "cobc not available")
        else:
            ok, errors, _log = runner.harness.compile_check(rel, neutralize=True)
            state = (True, "") if ok else \
                (False, "the original does not compile neutralised"
                 + (f" ({errors[0]})" if errors else ""))
        self._gate[rel] = state
        return state

    async def signal_eval(self, name: str, runner: Any, unit: Any, target: Any,
                          code: str) -> Any:
        """the facts signal of a regenerated program: fact Jaccard, compile gate."""
        import asyncio

        from codocs.cobol.factsig import evaluate, facts

        FactsEval = facts_eval_class()
        rel = getattr(target, "file", target)
        original = self.original_facts(rel)
        regenerated = facts(rel, code, self.index())
        res = evaluate(original, regenerated)
        gate_on, reason = await asyncio.to_thread(self._gate_state, runner, rel)
        notes: list[str] = []
        build_ok = True
        errors: list[str] = []
        if gate_on:
            ok, errs, _log = await asyncio.to_thread(runner.harness.compile_check, rel, code,
                                                     neutralize=True)
            if not ok:
                build_ok, errors = False, list(errs) or [f"{rel}:1: error: does not compile"]
        else:
            notes.append(f"compile gate off: {reason}")
        return FactsEval(signal="facts", build_ok=build_ok,
                         phi=res["phi"] if build_ok else 0.0, relevant=res["relevant"],
                         passed=res["passed"], failing=res["failing"],
                         build_errors=errors or notes, facts_by_class=res["facts_by_class"],
                         phi_scored=res["phi_scored"], phi_structural=res["phi_structural"])

