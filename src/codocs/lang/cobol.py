    def relevant_tests(self, root: Path, unit: Any, target_rel: str,
                       candidates: set[str]) -> list[str]:
        if self.ctx is None:
            return []
        index = self.index()
        defined: set[str] = set()
        for pid in self.programs_of(target_rel):
            defined.add(pid)
            defined.update(e.upper() for e in index.programs[pid].entry_points)
        comp = self._companions(target_rel)
        out = []
        for name, info in self.test_index(root, unit).items():
            if name not in candidates:
                continue
            if defined & set(info["idents"]) or _stem_of(info["file"]).upper() in comp:
                out.append(name)
        return sorted(out)

