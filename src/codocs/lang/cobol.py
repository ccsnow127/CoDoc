    def doc_facts(self, target_rel: str) -> str:
        """the FACTS block of every top-level program of the file, followed by the prose-
        language instruction of `-l` / CODOCS_LANG when it is not English (the block
        reaches the doc seed and refine prompts, not codegen)."""
        from codocs.cobol.facts import build_facts
        from codocs.cobol.layout import prose_note

        if self.ctx is None:
            return ""
        pids = self.programs_of(target_rel)
