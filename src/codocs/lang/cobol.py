    def _calls_of_test(self, rel: str) -> list[str]:
        pids = self.programs_of(rel)
        if not pids:
            return []
        index = self.index()
        out = self._called(index, pids[0])
        out += [c.target.upper() for c in index.programs[pids[0]].calls
                if c.kind == "call" and c.resolved and c.target.upper() not in out]
