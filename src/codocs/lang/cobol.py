def _stem_of(rel: str) -> str:
    """basename without its extension (CBACT01C.cbl -> CBACT01C)."""
    name = PurePosixPath(rel).name
    return name.rsplit(".", 1)[0] if "." in name[1:] else name


def in_test_dir(d: str) -> bool:
    """a directory that holds tests: test, tests, testing, ut, unittest, src/test/cobol."""
    parts = [p.lower() for p in PurePosixPath(d).parts]
    return any(p in TEST_DIRS for p in parts) or "src/test/cobol" in "/".join(parts)


def _dir(rel: str) -> str:
    d = str(PurePosixPath(rel).parent)
    return "" if d == "." else d


def closure_is_spec(index, pid: str) -> bool:
    """EXEC CICS / SQL / DLI or screen I/O in the program or in its link closure."""
    from codocs.cobol.harness import link_closure

    for p in [pid, *link_closure(index, pid)]:
        prog = index.programs.get(p)
        if prog is not None and (prog.has_cics or prog.has_sql or prog.has_dli
                                 or prog.uses_screen_io):
            return True
    return False


def called_programs(index, pid: str) -> list[str]:
    """repo programs a program CALLs directly (static CALL; ENTRY names to owners)."""
    out: list[str] = []
    for c in index.programs[pid].calls:
        if c.kind == "call" and c.resolved:
            owner = c.owner or index.program_of(c.target)
            if owner and owner not in out:
                out.append(owner)
    return out


def test_programs(index) -> tuple[set[str], set[str]]:
    """(existing test program files, test-support program files) of an index: the rule
    every consumer (adapter, wiki, bizlogic) shares."""
    files = {rel: list(pids) for rel, pids in
             getattr(index, "_file_programs", {}).items() if pids}
    tests: set[str] = set()
    support: set[str] = set()
    for f in index.files:
        if f.kind != "program":
            continue
        rel = f.path
        pids = files.get(rel) or []
        test_dir = in_test_dir(_dir(rel))
        if not pids:
            if test_dir:
                support.add(rel)
            continue
        if not (test_dir or TEST_STEM_RE.match(_stem_of(rel))):
            continue
        prog = index.programs[pids[0]]
        if not prog.using_params and called_programs(index, pids[0]) \
                and not closure_is_spec(index, pids[0]):
            tests.add(rel)
        elif test_dir:
            support.add(rel)
    return tests, support


test_programs.__test__ = False      # not a pytest test when imported into a test module


class _Analysis:
    """test programs, test-support programs and units of one COBOL index."""

    def __init__(self) -> None:
        self.files: dict[str, list[str]] = {}       # program file -> top-level program ids
        self.tests: set[str] = set()                # existing test programs
        self.support: set[str] = set()              # non-test programs of test dirs
        self.units: dict[str, Unit] = {}
        self.test_units: dict[str, set[str]] = {}   # test program -> units it belongs to


class CobolAdapter(LangAdapterBase):
    """COBOL, bound to a RepoContext (or unbound: parsing only)."""

    name = "cobol"
    # optional hooks of the shared loops
    fallback_signal = "facts"
    custom_signals = {"facts": {"executes": False}}
    uses_codegen_model = True
    preamble_note = ""
    import_heading = "Allowed COPY members and calls (use only these; omit unused ones)"
    final_statuses = ("ok", "spec")
    test_max_tokens = TEST_MAX_TOKENS

    def __init__(self, ctx: RepoContext | None = None):
        super().__init__(ctx)
        self.scope: str | None = None
        self._runner: Any = None
        self._rels: dict[int, str] = {}          # hash(text) -> rel, of read() texts
        self._decl_cache: dict[int, list[Decl]] = {}
        self._facts_cache: dict[str, set[str]] = {}
        self._gate: dict[str, tuple[bool, str]] = {}

    # -- index and analysis ----------------------------------------------------------------

    def _settings(self) -> Any:
        return self.ctx.settings if self.ctx is not None else None

    def exclude_paths(self) -> tuple[str, ...]:
        from codocs.lang.base import _exclude_paths

        return _exclude_paths(self._settings())

    def index(self, subtree: str | None = None):
        """the COBOL index of the scope (built once per subtree, cached in ctx.cache)."""
        from codocs.cobol.index import CobolRepoIndex

        if self.ctx is None:
            raise RuntimeError("the COBOL index needs a bound adapter")
        sub = _norm(subtree) if subtree is not None else None
        if self.scope is None:
            self.scope = sub or ""
        if sub is None:
            sub = self.scope
        key = ("cobol", "index", sub)
        hit = self.ctx.cache.get(key)
        if hit is None:
            skip = (self.ctx.out_dir,) if self.ctx.out_dir is not None else ()
            hit = CobolRepoIndex.build(self.ctx.root, subtree=sub or None,
                                       exclude=list(self.exclude_paths()), skip=skip)
            self.ctx.cache[key] = hit
        return hit

    def analysis(self, subtree: str | None = None) -> _Analysis:
        sub = _norm(subtree) if subtree is not None else (self.scope or "")
        key = ("cobol", "analysis", sub)
        hit = self.ctx.cache.get(key) if self.ctx is not None else None
        if hit is None:
            hit = self._analyse(self.index(sub))
            if self.ctx is not None:
                self.ctx.cache[key] = hit
        return hit

    def _closure_is_spec(self, index, pid: str) -> bool:
        return closure_is_spec(index, pid)

    def _called(self, index, pid: str) -> list[str]:
        return called_programs(index, pid)

    def _analyse(self, index) -> _Analysis:
        from codocs.cobol.classify import classify, spec_kind

        a = _Analysis()
        a.files = {rel: list(pids) for rel, pids in
                   getattr(index, "_file_programs", {}).items() if pids}
        kinds = {f.path: f.kind for f in index.files}
        program_files = sorted(p for p, k in kinds.items() if k == "program")
        a.tests, a.support = test_programs(index)
        unit_dirs: dict[str, list[str]] = {}
        for rel in program_files:
            if rel in a.tests or rel in a.support:
                continue
            unit_dirs.setdefault(_dir(rel), []).append(rel)
        for rel in sorted(a.tests):
            units: set[str] = set()
            for callee in self._called(index, a.files[rel][0]):
                d = _dir(index.programs[callee].path)
                if d in unit_dirs:
                    units.add(d)
            if _dir(rel) in unit_dirs:
                units.add(_dir(rel))
            a.test_units[rel] = units
        copy_dirs = sorted({str(PurePosixPath(cb.path).parent) if "/" in cb.path else ""
                            for cb in index.copybooks.values()})
        for d, rels in sorted(unit_dirs.items()):
            copybooks = sorted(f for f, k in kinds.items() if k == "copybook" and _dir(f) == d)
            programs = {r: list(a.files.get(r) or []) for r in rels}
            modes: dict[str, str] = {}
            spec_kinds: dict[str, str] = {}
            for r, pids in programs.items():
                if not pids:
                    continue
                try:
                    t = classify(index.programs[pids[0]], index)
                except Exception as e:  # classification never breaks discovery
                    log.warning("cobol: cannot classify %s: %s", r, e)
                    continue
                modes[r] = t.mode
                if t.mode == "spec":
                    spec_kinds[r] = spec_kind(t)
            tests = sorted(t for t, us in a.test_units.items() if d in us)
            a.units[d] = Unit(
                lang="cobol", rel=d, name=PurePosixPath(d).name if d else index.root.name,
                files=sorted(rels + copybooks), test_files=tests, build_root=d,
                extra={"programs": programs, "modes": modes, "spec_kinds": spec_kinds,
                       "copybook_dirs": copy_dirs, "test_programs": tests})
        return a

    def units(self, subtree: str | None = None, packages: list[str] | None = None
              ) -> dict[str, Unit]:
        out = dict(self.analysis(subtree).units)
        sub = _norm(subtree)
        if sub:
            out = {k: v for k, v in out.items() if k == sub or k.startswith(sub + "/")}
        if packages:
            wanted = [_norm(p) for p in packages]
            out = {k: v for k, v in out.items()
                   if any(k == p or not p or k.startswith(p + "/") for p in wanted)}
        return dict(sorted(out.items()))

    def unit(self, rel: str) -> Unit:
        """the unit of a directory (KeyError when it is no unit)."""
        return self.analysis().units[_norm(rel)]

    async def discover(self, runner: Any, subtree: str | None = None,
                       packages: list[str] | None = None) -> dict[str, Unit]:
        if self.scope is None:
            self.scope = _norm(subtree)
        return self.units(subtree if subtree is not None else None, packages)

    def programs_of(self, rel: str) -> list[str]:
        """top-level program ids of a program file (index order)."""
        if self.ctx is None:
            return []
        return list(getattr(self.index(), "_file_programs", {}).get(rel) or [])

    def primary(self, rel: str):
        """the primary (first top-level) CobolProgram of a file, or None."""
        pids = self.programs_of(rel)
        return self.index().programs.get(pids[0]) if pids else None

    def testability(self, rel: str):
        from codocs.cobol.classify import classify

        prog = self.primary(rel)
        return classify(prog, self.index()) if prog is not None else None

    def mode(self, rel: str) -> str:
        t = self.testability(rel)
        return t.mode if t is not None else ""

    def role(self, rel: str) -> str:
        """CICS online program | batch program (JCL) | batch main program | callable
        subprogram | user-defined function | screen program."""
        prog = self.primary(rel)
        if prog is None:
            return "program"
        if prog.unit_kind == "function":
            return "user-defined function"
        if prog.has_cics:
            return "CICS online program"
        if prog.uses_screen_io or prog.uses_terminal_io:
            return "screen program"
        index = self.index()
        if index.jobs_running(prog.program_id):
            return "batch program (JCL)"
        if prog.using_params:
            return "callable subprogram"
        return "batch main program"

    # -- files ------------------------------------------------------------------------------

    def read(self, rel: str, root: Path | None = None) -> str:
        """COBOL text with cobol.source's decoding (utf-8, cp1252, latin-1; CR and EOF
        normalised); the codec is remembered in ctx.codecs."""
        from codocs.cobol.source import decode_bytes

        base = Path(root) if root is not None else (self.ctx.root if self.ctx is not None
                                                     else Path("."))
        try:
            data = (base / rel).read_bytes()
        except OSError:
            return ""
        text, codec = decode_bytes(data)
        text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\x1a", "")
        if self.ctx is not None:
            self.ctx.codecs[rel] = codec
        self._rels[hash(text)] = rel
        return text

    def rel_of_text(self, src: str) -> str | None:
        return self._rels.get(hash(src))

    def owns(self, rel: str) -> bool:
        from codocs.lang.registry import is_cobol_member, source_language

        return source_language(rel) == "cobol" or is_cobol_member(rel)

    def is_test_file(self, rel: str, src: str | None = None) -> bool:
        if rel.endswith(SUITE_SUFFIX):
            return True
        if self.ctx is None:
            return False
        return rel in self.analysis().tests

    def is_generated(self, src: str, rel: str = "") -> bool:
        for line in src.split("\n")[:30]:
            s = line.rstrip()
            comment = s.lstrip().startswith("*>") or (len(s) > 6 and s[6] in "*/")
            if comment and GENERATED_RE.search(s):
                return True
        return False

    # -- declarations ----------------------------------------------------------------------

    def decls(self, src: str) -> list[Decl]:
        key = hash(src)
        hit = self._decl_cache.get(key)
        if hit is None:
            hit = self._decls(src)
            if len(self._decl_cache) > 256:
                self._decl_cache.clear()
            self._decl_cache[key] = hit
        return list(hit)

    def _decls(self, src: str) -> list[Decl]:
        from codocs.cobol.facts import program_span
        from codocs.cobol.layout import exact_program_name
        from codocs.cobol.parser import parse_program_file, tokenize
        from codocs.cobol.source import detect_format, logical_lines

        try:
            progs = parse_program_file("<src>", src, None)
        except Exception:
            return []
        fmt = detect_format(src)
        lines = logical_lines(src, fmt)
        toks = tokenize(lines)
        starts = _line_offsets(src)
        out: list[Decl] = []
        nlines = len(starts) - 1
        for prog in progs:
            span = program_span(src, prog.program_id)
            lo, hi = (0, nlines) if span is None else span
            mine = [t for t in toks if lo < t.line <= hi]
            first = mine[0].line if mine else lo + 1
            last = mine[-1].line if mine else hi
            pid = prog.program_id.upper()
            kw = "FUNCTION-ID" if prog.unit_kind == "function" else "PROGRAM-ID"
            out.append(Decl(kind="type", name=pid, start=_off(starts, first),
                            end=_off(starts, last + 1), line=first, end_line=last,
                            signature=f"{kw}. {exact_program_name(src, prog.program_id)}."))
            out.extend(_data_decls(mine, lines, starts))
            out.extend(_para_decls(prog, mine, lines, starts, last))
        return out

    def imports(self, src: str) -> list[ImportSpec]:
        from codocs.cobol.parser import literal_value, parse_program_file, tokenize
        from codocs.cobol.source import detect_format, logical_lines

        toks = tokenize(logical_lines(src, detect_format(src)))
        out: list[tuple[int, ImportSpec]] = []
        seen: set[tuple[str, str]] = set()

        def add(line: int, spec: ImportSpec) -> None:
            key = (spec.kind, spec.module)
            if key not in seen:
                seen.add(key)
                out.append((line, spec))

        for k, t in enumerate(toks):
            nxt = toks[k + 1] if k + 1 < len(toks) else None
            if nxt is None:
                continue
            if t.up == "COPY" and t.kind == "W" and nxt.kind in ("W", "L"):
                name = literal_value(nxt.text) if nxt.kind == "L" else nxt.text
                add(t.line, ImportSpec(module=name.upper(), kind="copy", line=t.line,
                                       text=f"COPY {name}."))
            elif t.up == "INCLUDE" and k >= 2 and toks[k - 1].up == "SQL" and \
                    toks[k - 2].up == "EXEC" and nxt.kind == "W":
                add(t.line, ImportSpec(module=nxt.up, kind="sql-include", line=t.line,
                                       text=f"EXEC SQL INCLUDE {nxt.text} END-EXEC"))
            elif t.up == "CALL" and nxt.kind == "L":
                name = literal_value(nxt.text)
                add(t.line, ImportSpec(module=name.upper(), kind="call", line=t.line,
                                       text=f"CALL '{name}'"))
            elif t.up in ("LINK", "XCTL") and k >= 2 and toks[k - 1].up == "CICS":
                j = next((j for j in range(k + 1, min(k + 30, len(toks)))
                          if toks[j].up == "PROGRAM"), None)
                if j is not None and j + 2 < len(toks) and toks[j + 1].text == "(" and \
                        toks[j + 2].kind == "L":
                    name = literal_value(toks[j + 2].text)
                    add(t.line, ImportSpec(
                        module=name.upper(), kind=t.up.lower(), line=t.line,
                        text=f"EXEC CICS {t.up} PROGRAM('{name}')"))
            elif t.up == "START" and k >= 2 and toks[k - 1].up == "CICS":
                j = next((j for j in range(k + 1, min(k + 30, len(toks)))
                          if toks[j].up == "TRANSID"), None)
                if j is not None and j + 2 < len(toks) and toks[j + 2].kind == "L":
                    name = literal_value(toks[j + 2].text)
                    add(t.line, ImportSpec(module=name.upper(), kind="start", line=t.line,
                                           text=f"EXEC CICS START TRANSID('{name}')"))
        try:
            progs = parse_program_file("<src>", src, None)
        except Exception:
            progs = []
        spelled = {t.up: t.text for t in toks if t.kind == "W"}
        for prog in progs:
            for c in prog.calls:
                if c.kind == "function":
                    name = spelled.get(c.target.upper(), c.target)
                    add(c.line, ImportSpec(module=c.target.upper(), kind="function",
                                           line=c.line, text=f"FUNCTION {name}"))
        return [spec for _, spec in sorted(out, key=lambda x: x[0])]

    def format_import(self, imp: Any) -> str:
        return getattr(imp, "text", "") or str(getattr(imp, "module", imp))

    def resolve_imports(self, rel: str, imports: list, ctx: RepoContext | None = None
                        ) -> list[str]:
        """unit dirs of the resolved copybooks and callee programs."""
        if self.ctx is None:
            return []
        index = self.index()
        dirs: set[str] = set()
        for i in imports:
            if i.kind in ("copy", "sql-include"):
                path = index.resolve_copybook(i.module, rel)
                if path:
                    dirs.add(_dir(path))
            elif i.kind in ("call", "link", "xctl", "function"):
                pid = index.program_of(i.module)
                if pid:
                    dirs.add(_dir(index.programs[pid].path))
        return sorted(dirs)

    def identifiers(self, src: str) -> set[str]:
        from codocs.cobol.mutate import STATEMENT_VERBS
        from codocs.cobol.oracle import _VERBS
        from codocs.cobol.parser import tokenize
        from codocs.cobol.source import detect_format, logical_lines

        toks = tokenize(logical_lines(src, detect_format(src)))
        out: set[str] = set()
        exec_ = False
        for t in toks:
            if t.up == "EXEC":
                exec_ = True
            if exec_:
                if t.up == "END-EXEC":
                    exec_ = False
                continue
            if t.kind == "W" and not t.text[:1].isdigit() and t.up not in _VERBS and \
                    t.up not in STATEMENT_VERBS and t.up not in _RESERVED_EXTRA:
                out.add(t.up)
        return out

    def extract_code(self, reply: str) -> str:
        """the largest ```cobol / cbl / cob / json (or untagged) block, else the reply; the
        first line keeps its indentation (fixed format is decided by the target)."""
        tags = {"", "cobol", "cbl", "cob", "json"}
        blocks = [m.group(2) for m in _FENCE_RE.finditer(reply) if m.group(1).lower() in tags]
        if blocks:
            code = max(blocks, key=len)
        else:
            code = reply.strip("\n")
            if code.lstrip().startswith("```"):
                first, _, rest = code.lstrip().partition("\n")
                code = rest
                if code.rstrip().endswith("```"):
                    code = code.rstrip()[:-3]
        return code.strip("\n").rstrip() + "\n"

    def finalize_code(self, target_rel: str, code: str) -> str:
        """fixed-format targets: reference and display form keep every line in its area
        (only lines past column 72 are re-wrapped); flush-left code is re-placed into area
        A/B by reflow. free-format targets unchanged."""
        if self._format(target_rel) == "fixed":
            return place_fixed(code)
        return code

    def finalize_doc(self, doc: str) -> str:
        from codocs.cobol.docs import drop_broken_mermaid

        return drop_broken_mermaid(doc)

    def _format(self, rel: str) -> str:
        if self.ctx is not None:
            for f in self.index().files:
                if f.path == rel:
                    return f.format
        from codocs.cobol.source import detect_format

        return detect_format(self.read(rel)) if self.ctx is not None else "fixed"

    def prompt_source(self, src: str) -> str:
        """the code-area display of a source: fixed format keeps columns 7-72 of every
        physical line (line numbers stay aligned); free format unchanged."""
        from codocs.cobol.source import detect_format, expand_tabs_fixed

        if detect_format(src) != "fixed":
            return src
        lines = src.split("\n")
        out = [expand_tabs_fixed(ln)[6:72].rstrip() for ln in lines]
        return "\n".join(out)

    # -- tests in source ----------------------------------------------------------------

    def test_names(self, src: str, rel: str) -> list[str]:
        from codocs.cobol import bundle

        if rel.endswith(SUITE_SUFFIX) or bundle.is_bundle(src):
            return bundle.test_names(src, rel)
        ids = _procedure_test_ids(src)
        if ids:
            return [f"{rel}::{i}" for i in ids]
        return [rel]

    def test_lines(self, src: str, rel: str) -> dict[str, int]:
        from codocs.cobol import bundle

        if rel.endswith(SUITE_SUFFIX) or bundle.is_bundle(src):
            return bundle.test_lines(src, rel)
        out: dict[str, int] = {}
        lines = src.split("\n")
        proc = next((n for n, ln in enumerate(lines, 1)
                     if re.search(r"\bPROCEDURE\s+DIVISION\b", ln, re.I)
                     and not _is_comment(ln)), 1)
        for n, ln in enumerate(lines, 1):
            if _is_comment(ln):
                continue
            m = _TEST_DISPLAY_RE.search(ln)
            if m and f"{rel}::{m.group(1)}" not in out:
                out[f"{rel}::{m.group(1)}"] = n
        names = self.test_names(src, rel)
        for name in names:
            out.setdefault(name, proc)
        return out

    def remove_tests(self, src: str, names: set[str]) -> str:
        from codocs.cobol import bundle

        if bundle.is_bundle(src):
            return bundle.remove_tests(src, names)
        return src

    def strip_non_tests(self, src: str) -> str:
        return src

    def normalize_suite(self, src: str, unit: Any, target_rel: str) -> str:
        """the reply's JSON plan (or an echoed bundle) as a normalised bundle."""
        from codocs.cobol import bundle
        from codocs.cobol.testmodels import Testability

        t = self.testability(target_rel) if self.ctx is not None else None
        pid = t.program_id if t is not None else _stem_of(target_rel).upper()
        if t is None:
            t = Testability(program_id=pid, mode="unit")
        index = self.index() if self.ctx is not None else None
        sut = ""
        if index is not None and pid in index.programs:
            try:
                sut = index.program_source(pid)
            except OSError:
                sut = ""
        return bundle.normalize(src, t, index, target_rel, sut_source=sut)

    def mutation_sites(self, src: str) -> list[Mutant]:
        """COBOL mutants of a target's text; sites outside cobc's statement universe
        and in plumbing paragraphs are dropped."""
        from codocs.cobol.mutate import mutation_sites, statement_verb_lines
        from codocs.cobol.parser import parse_program_file
        from codocs.cobol.source import detect_format

        rel = self.rel_of_text(src)
        program = None
        if self.ctx is not None and rel is not None:
            program = self.primary(rel)
        if program is None:
            try:
                progs = parse_program_file(rel or "<src>", src, None)
                program = progs[0] if progs else None
            except Exception:
                program = None
        fmt = detect_format(src)
        universe = None
        runner = self._runner
        if rel is not None and runner is not None and runner.cobc_ok():
            try:
                universe = runner.harness.statement_lines(rel)
            except Exception as e:
                log.warning("cobol: statement universe of %s: %s", rel, e)
        if universe is None:
            universe = statement_verb_lines(src, fmt)
        return mutation_sites(src, fmt=fmt, program=program, universe=universe)

