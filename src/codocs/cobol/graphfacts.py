"""COBOL facts for the wiki index and the bizlogic graph.

Everything here is read from the one COBOL index of the run (`cobol_index`): wiki packages
are programs (key = program file rel, `<rel>#<PID>` for later top-level programs of a
file), graph nodes are program entries, non-trivial paragraphs and sections, JCL jobs and
steps, and CICS transactions. Procedure-level edges (PERFORM, PERFORM THRU, GO TO) and the
exact spelling of CALL literals come from a token scan of the program text
(`codocs.cobol.parser.tokenize`); the call sites themselves are the index's.
"""

