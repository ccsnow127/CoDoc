# -- the Go-only pipeline never touches the loop-importing members ---------------------------


@needs_go
async def test_legacy_run_with_stub_loops(tmp_path: Path, mod: Path, monkeypatch):
    from codocs import pipeline as pl

    calls: list[str] = []

    async def run_testgen(targets, pkgs, runner, llm, settings, out_dir, module_root,
                          force=False, on_progress=None):
        calls.append("testgen")
        return []

    async def run_docgen(targets, pkgs, runner, llm, settings, out_dir, module_root,
                         force=False, on_progress=None, use_generated_tests=True):
        calls.append("docgen")
        return []

    tes = types.ModuleType("codocs.tesearch.loop")
    tes.run_testgen = run_testgen
    spec = types.ModuleType("codocs.specforge.loop")
    spec.run_docgen = run_docgen
    monkeypatch.setitem(sys.modules, "codocs.tesearch.loop", tes)
    monkeypatch.setitem(sys.modules, "codocs.specforge.loop", spec)

    def forbidden(*a, **k):
        raise AssertionError("Go-only pipeline called a loop-importing GoAdapter member")

    for name in ("fix_allowed", "allowed_third_party", "remove_tests", "strip_non_tests",
                 "default_allowed", "failure_message", "crash_message"):
        monkeypatch.setattr(GoAdapter, name, forbidden)

    class FakeLLM:
        tokens = {"input": 0, "output": 0}
        calls = 0
        cache_hits = 0

        def __init__(self, settings):
            pass

        async def __aenter__(self):
            return self

        async def __aexit__(self, *exc):
            return None

    out = tmp_path / "out"
    meta = await pl.run(mod, out, Settings(workers=2), skip=("wiki",), llm_factory=FakeLLM)
    assert calls == ["testgen", "docgen"]
    assert set(meta["stages"]) == {"analyze", "baseline", "testgen", "docgen"}
    assert (out / "baseline" / "calc.json").is_file()
    assert re.search(r"calc", (out / "analysis.json").read_text())
