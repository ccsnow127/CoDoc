def _sources() -> list[tuple[str, str]]:
    out = [(p.relative_to(FIXTURE).as_posix(), p.read_text(encoding="utf-8"))
           for p in sorted(FIXTURE.rglob("*.go"))]
    out += [("ring/ring.go", CGO_SRC), ("x/gen.go", GEN_SRC), ("calc/extra_test.go", EXTRA_TEST)]
    return out


SOURCES = _sources()
IDS = [rel for rel, _ in SOURCES]


