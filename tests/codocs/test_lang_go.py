def test_doc_prompt_members():
    from codocs.specforge.loop import DocEval

    src = (FIXTURE / "calc/calc.go").read_text()
    ctx = package.package_context(FIXTURE, CALC, "calc/calc.go")
    assert (GO.doc_seed_messages("calc/calc.go", CALC, src, ctx)
            == sf_prompts.seed_messages("calc/calc.go", CALC, src, ctx))
    allowed = gosrc.imports(src)
    for kw in ({}, {"taken": {"helper", "x"}}, {"has_preamble": True}):
        cg = dict(kw)
        if "has_preamble" in cg:
            cg["cgo"] = cg.pop("has_preamble")
        assert (GO.doc_codegen_messages("calc/calc.go", CALC, "# doc", ctx, allowed, **kw)
                == sf_prompts.codegen_messages("calc/calc.go", CALC, "# doc", ctx, allowed,
                                               **cg))
    ev = DocEval(signal="tests", build_ok=True, phi=0.5, relevant=["TestClamp", "TestSum"],
                 passed=["TestClamp"], failing={"TestSum": "boom"})
    last = DocEval(signal="tests", build_ok=False, phi=0.0, build_errors=["calc.go:1: x"])
    for kw in ({}, {"last": last, "last_round": 2, "attempt": 3}):
        assert (GO.doc_refine_messages("calc/calc.go", CALC, src, "# doc", src, ev, ["x"], **kw)
                == sf_prompts.refine_messages("calc/calc.go", CALC, src, "# doc", src, ev,
                                              ["x"], **kw))


