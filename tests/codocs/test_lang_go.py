def test_fix_imports():
    src = 'package calc\n\nimport "os"\n\nfunc F() string { return strings.ToUpper("a") }\n'
    errors = ['calc/x_test.go:3:8: "os" imported and not used',
              "calc/x_test.go:5:28: undefined: strings"]
    allowed = list(ts_measure.STD_ALLOWED)
    got = GO.fix_imports(src, errors, "x_test.go", allowed)
    assert got == package.fix_imports(src, errors, "x_test.go", allowed)
    assert got is not None and '"strings"' in got and '"os"' not in got
    assert GO.fix_imports(src, errors, "other.go", allowed) == package.fix_imports(
        src, errors, "other.go", allowed)


