def test_owns_and_test_files():
    assert GO.owns("a/b.go") and GO.owns("a/b_test.go")
    assert not GO.owns("a/b.c") and not GO.owns("a/go.mod")
    assert GO.is_test_file("a/b_test.go") and not GO.is_test_file("a/b.go")


@pytest.mark.parametrize("rel,src", SOURCES, ids=IDS)
def test_parsing_members(rel: str, src: str):
    assert GO.decls(src) == gosrc.top_level_decls(src)
    assert GO.imports(src) == gosrc.imports(src)
    assert GO.identifiers(src) == gosrc.identifiers(src)
    assert GO.is_generated(src, rel) == gosrc.is_generated(src)
    assert GO.preamble(src) == gosrc.cgo_header(src)
    assert GO.test_names(src, rel) == gosrc.test_functions(src)
    assert GO.mutation_sites(src) == mutate.mutation_sites(src)
    assert GO.strip_non_tests(src) == ts_measure.strip_non_tests(src)
    assert GO.normalize_suite(src, CALC, "calc/calc.go") is src
    names = set(gosrc.test_functions(src))
    if names:
        one = {sorted(names)[0]}
        assert GO.remove_tests(src, one) == ts_measure.prune(src, one)
        assert GO.remove_tests(src, names) == ts_measure.prune(src, names)


def test_generated_detected():
    assert GO.is_generated(GEN_SRC) is True
    assert GO.is_generated(CGO_SRC) is False


@pytest.mark.parametrize("reply", REPLIES)
def test_extract_code(reply: str):
    assert GO.extract_code(reply) == gosrc.extract_go_code(reply)


def test_preamble_round_trip():
    header = GO.preamble(CGO_SRC)
    assert header and 'import "C"' in header
    code = "package ring\n\nimport \"fmt\"\n\nfunc Push(v int) error { return fmt.Errorf(\"x\") }\n"
    assert GO.apply_preamble(code, header) == gosrc.apply_cgo_header(code, header)
    assert GO.apply_preamble(code, "") == gosrc.apply_cgo_header(code, "")


@pytest.mark.parametrize("rel,src", [s for s in SOURCES if s[0].endswith("_test.go")],
                         ids=[r for r in IDS if r.endswith("_test.go")])
def test_test_lines_match_mark_failing(rel: str, src: str):
    names = GO.test_names(src, rel)
    assert names
    lines = GO.test_lines(src, rel)
    assert set(lines) == set(names)
    marked = ts_prompts.mark_failing(src, {n: "boom" for n in names})
    got = {i for i, ln in enumerate(marked.splitlines(), start=1) if "<-- FAILING: boom" in ln}
    assert got == set(lines.values())


