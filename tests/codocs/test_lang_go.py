def test_importing_the_adapter_does_not_import_loops():
    code = ("import sys, codocs.lang, codocs.lang.go as g; g.GO.decls('package x'); "
            "print(sorted(m for m in sys.modules if m.startswith(('codocs.specforge', "
            "'codocs.tesearch', 'codocs.pipeline', 'tree_sitter'))))")
    import subprocess

    out = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True,
                         check=True).stdout.strip()
    assert out == "[]"


