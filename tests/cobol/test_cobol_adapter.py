async def test_context_identifiers_and_prompt_source(mod: Path, tmp_path: Path):
    big = "\n".join([fx("01 BIG-REC.")] + [fx(f"   05 B-{i:05d} PIC X(10).")
                                            for i in range(700)])
    (mod / "cpy" / "BIGREC.cpy").write_text(big)
    text = (mod / "cbl" / "ACCTRPT.cbl").read_text().replace(
        "       COPY DATEPARM.                                                   00003000",
        "       COPY DATEPARM.                                                   00003000\n"
        "       COPY BIGREC.")
    (mod / "cbl" / "ACCTRPT.cbl").write_text(text)
    ad, runner = _bind(mod, tmp_path)
    units = await ad.discover(runner)
    u = units["cbl"]
    ctx = ad.package_context(mod, u, "cbl/ACCTRPT.cbl")
    assert "*> ACCTREC" in ctx and "*> DATEPARM" in ctx and "*> BIGREC" in ctx
    assert "*> ... (truncated)" in ctx and len(ctx) < 62000
    assert "*> callee DATEUTIL ('DATEUTIL', cbl/DATEUTIL.cbl)" in ctx
    assert "PROCEDURE DIVISION USING LK-DATE-PARMS." in ctx
    inq = ad.package_context(mod, u, "cbl/ACCTINQ.cbl")
    assert "*> DFHAID" not in inq and "*> callee DATEUTIL" in inq
    taken = ad.package_identifiers(mod, u, exclude_rel="cbl/DATEUTIL.cbl")
    assert taken == {"ACCTINQ", "ACCTRPT", "DAYS-IN-MONTH"}
    src = ad.read("cbl/ACCTRPT.cbl")
    shown = ad.prompt_source(src)
    assert len(shown.split("\n")) == len(src.split("\n"))
    assert shown.split("\n")[0] == " IDENTIFICATION DIVISION."
    assert "00000100" not in shown
    free = ">>SOURCE FORMAT IS FREE\nIDENTIFICATION DIVISION.\n"
    assert ad.prompt_source(free) == free
    facts = ad.doc_facts("cbl/ACCTRPT.cbl")
    assert "ACCTRPT" in facts and "DATEUTIL" in facts
    head = ad.header_lines("cbl/ACCTRPT.cbl", u)
    assert head == ["# cbl/ACCTRPT.cbl",
                    "**Program**: `ACCTRPT` (COBOL; batch program (JCL); unit `cbl`)"]
    what = ad.unit_description("cbl/ACCTRPT.cbl", u)
    assert what.startswith("the COBOL source file `cbl/ACCTRPT.cbl` of directory unit `cbl` "
                           "(batch program (JCL); GnuCOBOL 3.2, ")
    assert "fixed reference format" in what


async def test_finalize_code_by_target_format(mod: Path, tmp_path: Path):
    (mod / "cbl" / "FREEP.cbl").write_text(
        ">>SOURCE FORMAT IS FREE\nIDENTIFICATION DIVISION.\nPROGRAM-ID. FREEP.\n"
        "PROCEDURE DIVISION.\n    DISPLAY 'X'\n    GOBACK.\n")
    ad, runner = _bind(mod, tmp_path)
    await ad.discover(runner)
    display = "\n".join(ln[6:72].rstrip() for ln in
                        (mod / "cbl" / "DATEUTIL.cbl").read_text().split("\n"))
    fixed = ad.finalize_code("cbl/DATEUTIL.cbl", display)
    lines = fixed.split("\n")
    assert lines[0] == "       IDENTIFICATION DIVISION."
    assert all(len(ln) <= 72 for ln in lines)
    assert any(ln.startswith("      *") for ln in lines)       # comments kept as comments
    flush = "IDENTIFICATION DIVISION.\nPROGRAM-ID. DATEUTIL.\nPROCEDURE DIVISION.\nGOBACK.\n"
    assert ad.finalize_code("cbl/DATEUTIL.cbl", flush).startswith(
        "       IDENTIFICATION DIVISION.\n       PROGRAM-ID. DATEUTIL.")
    ref = (mod / "cbl" / "ACCTRPT.cbl").read_text()
    assert "00000100" not in ad.finalize_code("cbl/ACCTRPT.cbl", ref)
    free = "IDENTIFICATION DIVISION.\nPROGRAM-ID. FREEP.\n"
    assert ad.finalize_code("cbl/FREEP.cbl", free) == free


async def test_loop_hooks(mod: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    ad, runner = _bind(mod, tmp_path)
    units = await ad.discover(runner)
    u = units["cbl"]
    t = SimpleNamespace(file="cbl/ACCTINQ.cbl")
    assert ad.custom_signals == {"facts": {"executes": False}}
    assert ad.fallback_signal == "facts" and ad.uses_codegen_model
    assert ad.final_statuses == ("ok", "spec") and ad.test_max_tokens == 32000
    assert ad.preamble_note == "" and ad.import_heading.startswith("Allowed COPY members")
    monkeypatch.setattr(type(runner), "cobc_ok", lambda self: True)
    assert ad.doc_signal(t, u) == "facts"
    assert ad.doc_signal(SimpleNamespace(file="cbl/DATEUTIL.cbl"), u) is None
    assert ad.testgen_mode(t, u) == "spec"
    assert ad.testgen_mode(SimpleNamespace(file="cbl/DATEUTIL.cbl"), u) == "loop"
    ad._settings().cobol_spec_signal = "compile"
    assert ad.doc_signal(t, u) == "compile"
    monkeypatch.setattr(type(runner), "cobc_ok", lambda self: False)
    assert ad.doc_signal(SimpleNamespace(file="cbl/DATEUTIL.cbl"), u) == "facts"
    assert ad.testgen_mode(SimpleNamespace(file="cbl/DATEUTIL.cbl"), u) == "skip:no-toolchain"
    ids = ad.signal_ids("facts", SimpleNamespace(file="cbl/DATEUTIL.cbl"))
    assert "id:DATEUTIL" in ids and ids == sorted(ids)
    doc = "# x\n\n```mermaid\nflowchart TD\n  A[\"ok\"] --> B[\"x\"]\n```\n"
    assert "```mermaid" in ad.finalize_doc(doc)
    assert ad.failure_message("TEST C01 RUN\nlog line\nTEST C01 FAIL got 2\n") == \
        "TEST C01 FAIL got 2\nlog line"
    res = SimpleNamespace(tail="x\nattempt to reference invalid memory address (signal "
                          "SIGSEGV)\n", returncode=139)
    assert ad.crash_message(res) == ("did not run: the driver ended early (attempt to "
                                     "reference invalid memory address (signal SIGSEGV))")
    assert "signal SIGSEGV" in ad.crash_message(SimpleNamespace(tail="", returncode=139))


def test_wiki_and_graph_facts_delegate_to_graphfacts(mod, tmp_path: Path):
    """the adapter's wiki_facts / graph_facts are the bound index's facts."""
    ad, _ = _bind(mod, tmp_path)
    src = ad.read("cbl/DATEUTIL.cbl")
    wf = ad.wiki_facts(mod, "cbl/DATEUTIL.cbl", src, ad.ctx)
    assert [d.name for d in wf.decls if d.kind == "type"] == ["DATEUTIL"]
    gf = ad.graph_facts(mod, "cbl/DATEUTIL.cbl", src, ad.ctx)
    names = [f.name for f in gf.funcs]
    assert names[0] == "DATEUTIL" and "DATEUTIL.1000-CHECK-MONTH" in names
