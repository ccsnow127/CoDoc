async def test_every_status(mod: Path, tmp_path: Path):
    cbl = mod / "cbl"
    (cbl / "NOTPROG.cbl").write_text(fx("01 X-REC.", "   05 X-ID PIC 9(4)."))
    (cbl / "DUP.cbl").write_text(fx("IDENTIFICATION DIVISION.", "PROGRAM-ID. DATEUTIL.",
                                    "PROCEDURE DIVISION.", "    GOBACK."))
